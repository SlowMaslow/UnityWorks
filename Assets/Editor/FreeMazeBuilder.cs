using System.Collections.Generic;
using UnityEngine;

/// <summary>
/// ⭐ СБОРКА УРОВНЯ БЕЗ РЕШЁТКИ: дерево комнат → раскладка прямоугольников → сетка символов.
///
/// Строится РЯДОМ со старым генератором, а не вместо него: старый работает и отдаёт чистые уровни,
/// и ломать его до того, как новый путь себя покажет, — плохая сделка. Переключение произойдёт, когда
/// новый путь пройдёт те же замеры (брак на выходе, сцепление, время).
///
/// Порядок обратный прежнему и в этом весь смысл:
///   1. РЕЦЕПТ — из чего уровень состоит (баллы сложности → состав);
///   2. ДЕРЕВО — основной путь нужной длины плюс ветки под элементы рецепта;
///   3. РОЛИ — каждый элемент садится на конкретное ребро и диктует ему НАПРАВЛЕНИЕ
///      (ворота требуют подъёма, дверь — бокового ребра);
///   4. РАСКЛАДКА — каждая комната получает свой прямоугольник нужного размера (<see cref="RoomLayout"/>);
///   5. РЕНДЕР — камень, полости комнат, проходы по связям.
/// Раньше геометрия бросалась вслепую, а замысел подбирал, что выпало.
/// </summary>
public static class FreeMazeBuilder
{
    /// Диагностический тумблер: строить голую геометрию без декора и монет.
    /// Нужен, чтобы отличать брак геометрии от брака отделки при замерах.
    public static bool SkipDressing;
    /// <summary>Отключить обход столбцов подъёма при постановке кнопок — только для замера.</summary>
    public static bool SkipButtonAvoid;
    /// Битовая маска разрешённых узоров декора (тумба, пилон, балкон, зубцы, сталактит, лесенка).
    public static int DecorMask = 63;
    /// <summary>Отключить проверку обхода замков по графу комнат — только для замера «с ней и без».</summary>
    public static bool SkipBypassCheck;
    /// <summary>Сколько механизмов не поставлено: обход есть, а завалить его нечем.</summary>
    public static int StatGateBypass;
    /// <summary>
    /// ⭐ РАЗБОР ПЕТЕЛЬ: сколько веток помечено петлёй, сколько кандидатов на ребро возврата нашлось,
    /// сколько отвергла проверка обхода и у скольких меток кандидата не было вовсе.
    /// Заведены потому, что «петли не замыкаются» я трижды объяснял неверно — геометрией, шириной
    /// люка и порогом перекрытия, — а настоящая причина оказалась четвёртой и видна только здесь.
    /// </summary>
    public static int StatLoopCand, StatLoopBypass, StatLoopMarks, StatLoopNoCand;

    /// <summary>
    /// По сколько комнат класть за раз в длинной ветке к ключу. Смысл этапа — дешёвый откат, а он
    /// теряется, когда этап разрастается: вероятность уложить N комнат подряд падает с ростом N,
    /// и переигрывать приходится всё. Шесть — компромисс: форма ветки (вверх-вбок-вниз) ещё
    /// читается внутри куска, а откат стоит куска, а не всей ветки.
    /// </summary>
    private const int KeyChainChunk = 6;

    /// <summary>Комната абстрактного дерева: кто родитель и какой элемент рецепта сидит на её ребре.</summary>
    public class Node
    {
        public int id, parent = -1;
        public PuzzleElement? element;     // элемент на ребре «родитель → эта комната»
        public string route;
        public bool onMainPath;
        /// <summary>В этой комнате лежит ключ — конец ветки, ради которого в неё и идут.</summary>
        public bool holdsKey;
        /// <summary>Та самая комната в КОНЦЕ основного маршрута. ⚠️ Вычислять её как «наибольший id
        /// среди onMainPath» НЕЛЬЗЯ: добивочные комнаты добавляются позже, получают бо́льшие id и
        /// частью тоже помечаются основным путём.</summary>
        public bool isFinish;
        /// <summary>К этой комнате НЕЛЬЗЯ подвешивать ничего сверх плана. Нужна камере: лишний проём
        /// в неё означает вход мимо потолка, и весь замок обесценивается.</summary>
        public bool sealed2;
        /// <summary>Элемент на ребре к родителю играет роль ВЫХОДА из запертой области: кнопка
        /// только изнутри. Ставится проходом починки, а не рецептом.</summary>
        public bool isExit;
        /// <summary>Комната-ПОДВАЛ: пустое место, зарезервированное ровно под родителем для
        /// паттерна, которому одной комнаты мало (см. SpaceNeed.cellarHeight).</summary>
        public bool isCellar;
        /// <summary>
        /// ⭐⭐ ШАГ ВНУТРИ ВЕТКИ-ПЕТЛИ (0 — первая комната после точки отрыва), и длина этой ветки.
        /// Нужны, чтобы прописать ветке ФОРМУ: вверх, вбок, вниз — тогда её конец возвращается к
        /// основному маршруту дальше по ходу, и петлю можно замкнуть дверью.
        /// 🐞 Замер, из-за которого это появилось: концов веток с ключом 120, а рядом с комнатой
        /// маршрута оказалось ШЕСТЬ. То есть «найти» возврат постфактум нельзя — дерево разводит
        /// ветку и трассу далеко. Форму надо заказывать раскладке, как мы уже делали с камерой.
        /// </summary>
        public int branchStep = -1, branchLen;
        /// <summary>⭐ Комната маршрута, К КОТОРОЙ ветка-петля обязана вернуться. −1 — не петля.
        /// На этом ребре и встанет «кнопка+дверь на основной маршрут» из схемы игрока.</summary>
        public int returnTo = -1;
        /// <summary>
        /// ⭐⭐ ВХОД В ВЕТКУ — ПРОВАЛ В ОДИН КОНЕЦ. Комната этого узла лежит ПОД точкой отрыва и выше
        /// дотяжки: игрок сваливается в неё и обратно наверх уже не поднимется.
        ///
        /// Без этого вся затея с петлёй рассыпается: игрок сходит с трассы, берёт ключ и возвращается
        /// ТЕМ ЖЕ путём, а дверь возврата оказывается украшением (поймано игроком: «игрок может
        /// вернуться всегда тем же маршрутом, что и пришёл, задумка ломается»).
        /// ⚠️ Это ОСОЗНАННОЕ исключение из правила «под люком не выше дотяжки»: там правило спасает
        /// от случайной ловушки, здесь ловушка — замысел, и выход из неё нарисован дверью.
        /// </summary>
        public bool oneWayDrop;
        /// <summary>⭐ Этап укладки: 0 — хребет старт→финиш, 1..k — ветки (каждая своя), 99 — добор.
        /// Не встал этап — переигрывается ТОЛЬКО он, остальное остаётся стоять.</summary>
        public int stage;
    }

    public class Built
    {
        /// <summary>⭐ НАСТОЯЩИЙ ВЫХОД: типизированное описание уровня. Из него уровень и строится,
        /// и проверяется. Боковые каналы (инверсия, хозяева кнопок) больше не нужны — всё здесь.</summary>
        public LevelSpec spec;
        /// <summary>Сетка символов — ВИД ДЛЯ ГЛАЗ. Печатать можно, читать обратно нельзя: инверсия,
        /// окно, вложенность и сторона крепления в ней не выражаются.</summary>
        public string scheme;
        /// <summary>Та же сетка, но живая: по ней прокладывается дорога назад (см. CarveReturn).</summary>
        public char[,] grid; public int rows, cols;
        /// <summary>Плоскость номеров групп, парная к <see cref="grid"/>: личность плиток живёт тут.</summary>
        public int[,] grp;
        public List<Node> nodes;
        public RoomLayout.Result layout;
        public List<ModuleStamp> stamps;   // что построили модули (инверсия, вложенность кнопок)
        public string story;               // человекочитаемо: что и куда легло
        public string recipeText;          // рецепт, по которому строили (для лога и панели)
    }

    /// <summary>
    /// Построить дерево под рецепт. Основной путь — цепочка комнат, на рёбрах которой сидят элементы
    /// основного маршрута; между соседними элементами вставляется пустая комната-развязка, чтобы
    /// механизмы не лезли друг другу в клетки. Ветки подвешиваются к случайным комнатам основного пути.
    /// </summary>
    /// <param name="wantRooms">Сколько комнат должно быть в уровне ВСЕГО. ⭐ Размер задаётся отдельно
    /// от числа механизмов: уровень может быть большим и просторным при трёх замках, и тесным при
    /// пяти. 🐞 Раньше размер был жёстко равен «элементы рецепта + развязки», и ползунки размера на
    /// свободный путь не влияли вовсе — игрок ставил сетку 20×20 и не видел разницы.</param>
    public static List<Node> BuildTree(LevelRecipe recipe, System.Random rng, int wantRooms = 0)
    {
        var nodes = new List<Node>();
        System.Func<int, PuzzleElement?, string, bool, int> add = (parent, el, route, main) =>
        {
            var n = new Node { id = nodes.Count, parent = parent, element = el, route = route, onMainPath = main };
            nodes.Add(n); return n.id;
        };

        add(-1, null, "старт", true);                       // комната спавна
        var spine = new List<int> { 0 };
        // ⭐⭐ БЮДЖЕТ КОМНАТ ДЕЛИТСЯ ПО НАЗНАЧЕНИЮ, А НЕ УХОДИТ ЦЕЛИКОМ В ДОБИВКУ.
        // 🐞 Основной маршрут был ровно «элемент + развязка» — на сорока комнатах это 11 комнат, а
        // остальные 29 висели случайными отростками по бокам. Механизмы сидели на коротком маршруте,
        // и замер это подтвердил: они умещались в 53% карты, а игрок увидел «скопление головоломок
        // буквально в одном месте». Даём маршруту долю бюджета — развязок между механизмами столько,
        // сколько позволяет размер уровня.
        int mainElems = 0;
        foreach (var route in recipe.routes) if (route.isMain) mainElems += route.elements.Count;
        int spineBudget = Mathf.Max(0, Mathf.RoundToInt(wantRooms * 0.45f) - (2 * mainElems + 1));
        int gapsCount = Mathf.Max(1, mainElems);
        foreach (var route in recipe.routes)
        {
            if (!route.isMain) continue;
            for (int i = 0; i < route.elements.Count; i++)
            {
                // ⭐⭐ ВЛОЖЕННЫЕ ВОРОТА САДЯТСЯ ВПЛОТНУЮ К ХОЗЯИНУ — развязки между ними нет.
                // Вся вложенность в том, что кнопка лежит НА СТУПЕНЬКЕ предыдущих ворот: нажал, залез
                // по ним — и ты уже в нижней комнате следующих. Комната-развязка эту цепочку рвёт, и
                // кнопка остаётся в одной части уровня, а ворота — в другой (см. HostForNested).
                var el = route.elements[i];
                bool nest = el == PuzzleElement.NestedGate && i > 0
                         && (route.elements[i - 1] == PuzzleElement.Gate
                          || route.elements[i - 1] == PuzzleElement.NestedGate);
                if (el == PuzzleElement.NestedGate && !nest) el = PuzzleElement.Gate;   // вкладывать не во что
                // Комната-развязка между механизмами: два подряд в соседних комнатах не помещаются.
                // Сверх обязательной добавляем долю бюджета, чтобы механизмы разошлись по уровню.
                if (i > 0 && !nest)
                {
                    int extra = spineBudget / gapsCount + (rng.Next(100) < 50 ? 1 : 0);
                    for (int k = 0; k <= extra; k++)
                        spine.Add(add(spine[spine.Count - 1], null, route.name, true));
                }
                spine.Add(add(spine[spine.Count - 1], el, route.name, true));
                // ⚠️ Комнате-коридору нельзя подвешивать лишнее: у неё ровно две боковые стороны, и
                // обе заняты трассой. 🐞 Замер: добор комнат вешал на камеру третьего ребёнка, все
                // трое требовали горизонтали — раскладка не сходилась НИ РАЗУ из шестидесяти.
                // ⚠️ Запираем ОБЕ комнаты ребра: сквозным коридором работает то комната элемента
                // (камера), то комната родителя (мост), а лишний проём губит обе одинаково.
                if (PuzzleVocabulary.Need(el).throughCorridor)
                {
                    nodes[spine[spine.Count - 1]].sealed2 = true;
                    if (spine.Count >= 2) nodes[spine[spine.Count - 2]].sealed2 = true;
                }
                // ⭐⭐ ПАТТЕРН МОЖЕТ ЗАНИМАТЬ НЕ ОДНУ КОМНАТУ, А НЕСКОЛЬКО ЭТАЖЕЙ. Камере нужен ПОДВАЛ
                // под коридором: там лежат камера с ключом и колодец возврата. Раньше она пыталась
                // выкопать его сама — «рою в сплошном камне», — и замер показал, что сплошного камня
                // под коридором не бывает: 104 отказа из 110 посадок. Место надо РЕЗЕРВИРОВАТЬ.
                if (PuzzleVocabulary.Need(el).cellarHeight > 0)
                {
                    int cellar = add(spine[spine.Count - 1], null, route.name + " (подвал)", false);
                    nodes[cellar].sealed2 = true;
                    nodes[cellar].isCellar = true;
                }
            }
            spine.Add(add(spine[spine.Count - 1], null, route.name, true));   // комната финиша
        }
        // 🐞 ФИНИШ УЕЗЖАЛ В СЛУЧАЙНУЮ КОМНАТУ. Раньше его искали как «наибольший id среди onMainPath»,
        // а добивочные комнаты добавляются ниже, получают бо́льшие id и в 30% случаев тоже помечаются
        // основным путём — финиш оказывался в отростке сбоку от СЕРЕДИНЫ маршрута. Игрок: «старт и
        // финиш буквально в двух шагах друг от друга» (замер: 29 клеток при габарите 97).
        if (spine.Count > 1) nodes[spine[spine.Count - 1]].isFinish = true;

        // Ветки рецепта уходят в конец очереди (50+), ветки-ключи — в начало (1..).
        int stageCounter = 50, keyCounter = 0;
        foreach (var route in recipe.routes)
        {
            if (route.isMain) continue;
            // Ветка цепляется к случайной комнате основного пути, кроме самой первой и последней:
            // у спавна и финиша своя работа, механизмы туда не ставим.
            // ⚠️ Не цепляем ветку к комнате-коридору: у неё обе боковые стороны уже заняты трассой.
            // 🐞 Замер: у камеры выходило в среднем ДВА ребёнка (ветка плюс продолжение трассы), все
            // требовали горизонтали — раскладка не сходилась ни разу. sealed2 сторожил только добор
            // комнат, а ветки и ключи цеплялись мимо него.
            // ⭐⭐ МЕСТО НА ТРАССЕ БЕРЕЖЁМ ЗАРАНЕЕ (идея игрока). У комнаты четыре стороны, две из них
            // уже заняты самим маршрутом — значит принять она может от силы одну-две ветки.
            // 🐞 Замер до этого: на 40 сборок 26 ПОЛНЫХ перезапусков раскладки. Ветка цеплялась к
            // случайной комнате трассы, та оказывалась обстроенной со всех сторон, и этапу было
            // некуда встать — а переиграть ранний этап поздний уже не может.
            // Теперь берём наименее загруженную комнату: у неё стороны ещё свободны.
            int attach = PickAttach(nodes, spine, rng);
            if (attach < 0) continue;
            int cur = attach;
            int myStage = ++stageCounter;

            // ⭐ ВЕТКА — ЭТО МАРШРУТ, А НЕ ТУПИЧОК. 🐞 Замер показал: 52 ветки из 58 были ровно в ОДНУ
            // комнату — открыл дверь, ключ сразу за ней. Никакого «сходить за ключом» в этом нет.
            // Теперь у ветки есть три части: РАЗБЕГ (чтобы она не начиналась замком), сами механизмы
            // с развязками между ними, и ХВОСТ — ключ лежит в КОНЦЕ ветки, а не сразу за дверью.
            // ⭐ САМОДОСТАТОЧНАЯ ВЕТКА — вылазка: она несёт ключ ВНУТРИ себя и кончает ветку.
            //
            // ⭐⭐ КАМЕРЫ ЗДЕСЬ БОЛЬШЕ НЕТ, И ЭТО ГЛАВНАЯ ПРАВКА ПОСЛЕ РАЗБОРА Level_11.
            // 🐞 Три захода подряд я строил ей особую форму в дереве: то камера родитель верхней
            // комнаты, то наоборот, то с отдельной комнатой-выходом на ребре. Каждый раз всплывала
            // одна и та же болезнь под новым именем — потолок оказывался украшением, выход упирался
            // в тупик, ребро уезжало горизонтально. Причина была не в форме дерева: у ОРИГИНАЛА
            // камера вообще не ветка. Это ПРОЛЁТ ОСНОВНОЙ ТРАССЫ — коридор, чей пол в середине
            // держится на исчезающей платформе, а под коридором в толще вырыта камера с ключом и
            // колодец возврата. Значит камере не нужен ни особый случай, ни выход из словаря: она
            // обычный элемент на ребре, а всё остальное объявляет словарь (сквозной коридор, 20×3)
            // и рисует трафарет. Заодно ушли комната-кнопка, комната-выход и спор за направление.
            bool isExcursion = route.elements.Count == 1 && route.elements[0] == PuzzleElement.Excursion;
            if (!isExcursion && rng.Next(100) < 60)
                cur = add(cur, null, route.name, false);            // разбег
            for (int i = 0; i < route.elements.Count; i++)
            {
                // Вложенные ворота — вплотную к хозяину, без развязки (см. HostForNested).
                var el = route.elements[i];
                bool nest = el == PuzzleElement.NestedGate && i > 0
                         && (route.elements[i - 1] == PuzzleElement.Gate
                          || route.elements[i - 1] == PuzzleElement.NestedGate);
                if (el == PuzzleElement.NestedGate && !nest) el = PuzzleElement.Gate;
                if (i > 0 && !nest) cur = add(cur, null, route.name, false); // развязка между механизмами
                int prev = cur;
                cur = add(cur, el, route.name, false);
                // ⚠️ Комнате-коридору нельзя подвешивать лишнее: у неё ровно две боковые стороны,
                // и обе заняты трассой. 🐞 Замер: добор комнат вешал на камеру третьего ребёнка,
                // все трое требовали горизонтали — раскладка не сходилась НИ РАЗУ из шестидесяти.
                if (PuzzleVocabulary.Need(el).throughCorridor)
                { nodes[cur].sealed2 = true; if (prev >= 0) nodes[prev].sealed2 = true; }
            }
            // ⚠️ У вылазки хвоста нет: её камера И ЕСТЬ конец ветки, ключ лежит внутри неё.
            if (!isExcursion)
            {
                // ⭐ ХВОСТ ВЕТКИ ТОЖЕ ЖИВЁТ НА БЮДЖЕТЕ. 🐞 Было `1 + rng(2)` — замер дал среднюю длину
                // ветки 2,08 комнаты на любом размере уровня, и игрок сказал «ответвления вообще ни о
                // чём». За ключом должно быть идти интересно, а не «открыл дверь — вот он».
                int tail = 1 + rng.Next(2) + Mathf.RoundToInt(wantRooms * 0.06f);
                for (int k = 0; k < tail; k++) cur = add(cur, null, route.name, false);
            }
            nodes[cur].holdsKey = true;                             // ключ — в последней комнате ветки

            // ⭐⭐ ВЕТКА РЕЦЕПТА ТОЖЕ ЗАМЫКАЕТСЯ В ПЕТЛЮ.
            //
            // 🐞 Метку петли получали ТОЛЬКО ветки, которые добирает «запасной проход» до трёх
            // ключей, а ветки рецепта — те, на которых и стоят механизмы, — не получали её вовсе.
            // Замер на умолчаниях: ключей 31, из них в замкнутой петле 4, в тупиковой ветке 27.
            // При заказе 50 — 0 из 15. Отсюда же и вся непроходимость: из тупика выходят тем же
            // механизмом, которым вошли, и возвратную кнопку с него не снять.
            //
            // ⭐ Гарантию несёт ВЕТКА, А НЕ МЕХАНИЗМ (решение игрока 2026-09-11): основной маршрут
            // односторонний по замыслу, а ветка обязана уйти с трассы, забрать ключ и вернуться на
            // трассу дальше по ходу. Метка включает связку ringTarget + nextToAny: конец ветки
            // садится рядом с любой комнатой маршрута, и туда открывается ребро возврата с клапаном
            // (см. loopLinks в Build). Именно она и даёт работающие клапаны — вычисляемое кольцо
            // PlaceRing не встаёт по другим причинам, см. комментарий при ringStart.
            {
                var chain = new List<int>();
                for (int c4 = cur; c4 >= 0 && c4 != attach; c4 = nodes[c4].parent) chain.Add(c4);
                chain.Reverse();                                   // от точки отрыва к ключу
                for (int k2 = 0; k2 < chain.Count; k2++)
                { nodes[chain[k2]].branchStep = k2; nodes[chain[k2]].branchLen = chain.Count; }
                // Возвращаемся на трассу в комнату СЛЕДУЮЩУЮ за точкой отрыва — тогда игрок выходит
                // дальше по ходу, а не там же, где свернул.
                int ai2 = spine.IndexOf(attach);
                if (chain.Count > 0 && ai2 >= 0 && ai2 + 1 < spine.Count && !nodes[spine[ai2 + 1]].sealed2)
                    nodes[cur].returnTo = spine[ai2 + 1];
            }

            // ⭐⭐ ВЕТКА РЕЦЕПТА РЕЖЕТСЯ НА ЭТАПЫ ПО KeyChainChunk КОМНАТ (см. константу).
            // 🐞 Раньше вся ветка получала ОДИН номер этапа. Её длина растёт от размера уровня
            // (хвост = 1 + wantRooms*0.06), и при заказе в 160 комнат ветка выходила на 14-16 комнат:
            // 2-4 с механизмами и 10-13 рядовых. Разбор пяти несошедшихся уровней при заказе 50
            // показал у ВСЕХ ПЯТИ ровно такой этап, и все пятеро умирали после двенадцати
            // перезапусков подряд. Этап заведён ради дешёвого отката — «не встал, переигрываем
            // только его», — а этап в четверть уровня этот смысл отменяет.
            // ⚠️ Выбросить звено нельзя: в конце ветки ключ, и цепочка к нему обязана быть целой.
            // Поэтому не выбрасываем, а дробим: откат стоит куска, ветка остаётся той же.
            {
                // ⛔ УКЛАДКА КОЛЬЦОМ (PlaceRing) РАЗОБРАНА И ОСТАВЛЕНА КАК ЕСТЬ (2026-09-11).
                //
                // Счётчики показали, что кольцо не встаёт по ДВУМ причинам, и первую я починил, а
                // вторая оказалась не по зубам этой укладке вовсе:
                //   • дробление веток на этапы ломало ПРЕДУСЛОВИЕ кольца: PlaceRing ищет ringStart на
                //     первом звене этапа и ringTarget на последнем, а разные чанки — разные этапы.
                //     Отказов «не размечено» было 504 на десяти уровнях. Если ветку не дробить,
                //     кольцо доходит до геометрии — но поставка падает с 19.85 до 19.10;
                //   • из 152 вызовов, дошедших до геометрии, 145 отказывают «задели чужое». Кольцу
                //     нужен свободный прямоугольник примерно 30×10 на ярус ниже трассы, а укладка
                //     «комната за комнатой от родителя» такой формы не держит. Ранняя очередь для
                //     кольцевых веток тоже не помогла: стало 145 вместо 140.
                //
                // ⚠️ ВЫВОД: кольцо не поставить, пока хребет кладётся первым. Нужен обратный порядок —
                // кольца как готовые блоки, а хребет между ними, — то есть ДРУГАЯ укладка, а не
                // правка этой. Пока петли замыкает простой механизм (соседство + ребро возврата),
                // и он даёт 9 замыканий из 23 меток без всякого PlaceRing.
                int stageNow = myStage;
                int since = 0;
                for (int id = attach + 1; id < nodes.Count; id++)
                {
                    if (nodes[id].stage != 0 || nodes[id].onMainPath) continue;
                    if (since > 0 && since % KeyChainChunk == 0) stageNow = ++stageCounter;
                    nodes[id].stage = stageNow; since++;
                }
            }
        }

        // ── ТРИ КЛЮЧА РАЗМЕЧАЕТ ПЛАН, А НЕ АВАРИЙНЫЙ ЗАПАСНОЙ ПРОХОД ─────────────────────────────
        // 🐞 Ключи привязывались к веткам РЕЦЕПТА, а рецепт — про механизмы: если он не выкатил
        // ветку, план не размечал ни одного ключа. Замер: размечено 9 из 36, остальные 27 клал
        // запасной проход в «какие-нибудь комнаты подальше друг от друга». Отсюда и «все ключи лежат
        // преимущественно в одном тупике»: запасной проход не строит МАРШРУТ, он просто ищет место.
        // ⚠️ Точки отрыва разносим по маршруту: три ветки из одной комнаты — это не три пути, а куст.
        {
            int haveKeys = 0;
            foreach (var nd in nodes) if (nd.holdsKey) haveKeys++;
            var used = new List<int>();
            foreach (var nd in nodes) if (nd.holdsKey)
            { int c = nd.id; while (c >= 0 && !nodes[c].onMainPath) c = nodes[c].parent; if (c >= 0) used.Add(c); }
            while (haveKeys < 3 && spine.Count > 3)
            {
                // Точка отрыва — комната маршрута подальше от уже занятых.
                int attach = -1; float bestGap = -1f;
                var load0 = KidCounts(nodes);
                for (int i = 1; i < spine.Count - 1; i++)
                {
                    if (nodes[spine[i]].sealed2) continue;   // коридор занят трассой с обеих сторон
                    if (load0[spine[i]] >= 3) continue;      // стороны кончились, ветку принять некуда
                    int gap = int.MaxValue;
                    foreach (int u in used) gap = Mathf.Min(gap, Mathf.Abs(spine.IndexOf(u) - i));
                    if (used.Count == 0) gap = i;
                    // Разнос по маршруту важнее, но при равном разносе берём менее загруженную.
                    // ⭐ И ещё: следующее ребро трассы должно быть СВОБОДНО от механизма — иначе
                    // ребро возврата обойдёт его, и проверка обхода петлю не пропустит (см. PickAttach).
                    bool nextFree = i + 1 < spine.Count && nodes[spine[i + 1]].element == null;
                    float score = gap - 0.25f * load0[spine[i]] + (nextFree ? 2f : 0f);
                    if (score > bestGap) { bestGap = score; attach = spine[i]; }
                }
                if (attach < 0) break;
                used.Add(attach);
                // ⭐⭐ ВЕТКА К КЛЮЧУ — ПЕТЛЯ, А НЕ ТУПИК (форма из рисунка игрока): игрок сходит с
                // трассы, проходит виток, забирает ключ и ВОЗВРАЩАЕТСЯ на трассу дальше по ходу.
                // Форму заказываем раскладке шагами: первая треть вверх, вторая вбок, третья вниз.
                // Тогда конец ветки сам оказывается на высоте маршрута, рядом с его комнатой.
                int len = 5 + rng.Next(2) + Mathf.RoundToInt(wantRooms * 0.06f);
                int cur2 = attach;
                for (int k = 0; k < len; k++)
                {
                    cur2 = add(cur2, null, "ключ", false);
                    nodes[cur2].branchStep = k; nodes[cur2].branchLen = len;
                }
                nodes[cur2].holdsKey = true;
                // ⭐⭐ ВЕТКИ-КОЛЬЦА КЛАДЁМ СРАЗУ ПОСЛЕ ХРЕБТА, номерами 1.. — до всех прочих веток и
                // добора. 🐞 Замер объяснил, почему вычисляемое кольцо не встало ни разу: ему нужен
                // свободный прямоугольник на ярус ниже трассы, а укладывалось оно последним, когда
                // место уже разобрано (120 отказов «цель не подошла», 64 «задели чужое»).
                // ⭐⭐ ДЛИННАЯ ВЕТКА РЕЖЕТСЯ НА НЕСКОЛЬКО ЭТАПОВ.
                // 🐞 Раньше вся ветка была ОДНИМ этапом, а её длина растёт от размера уровня
                // (len = 5 + wantRooms*0.06): при заказе в 160 комнат это пятнадцать комнат разом.
                // Этапы заведены ровно ради дешёвого отката — «не встал этап, переигрываем только
                // его», — а этап в четверть уровня этот смысл отменяет: не встала одна комната из
                // пятнадцати, и переигрывается всё, включая четырнадцать вставших. Разбор пяти
                // несошедшихся уровней при заказе 50 показал у всех пяти именно такой этап: 14-16
                // комнат, из них 10-13 — рядовые звенья цепочки.
                // ⚠️ Выбросить звено нельзя: в конце ветки лежит КЛЮЧ, и цепочка к нему обязана быть
                // целой. Поэтому не выбрасываем, а дробим — откат становится дешевле, а ветка та же.
                // ⭐⭐ ЗАМЫКАЕМ ПЕТЛЮ: последнее звено должно вернуться к маршруту — к комнате
                // СЛЕДУЮЩЕЙ за точкой отрыва. Так игрок выходит на трассу дальше по ходу, как на
                // схеме игрока, а не возвращается тем же путём.
                // ⚠️ ДО разметки этапов: от того, кольцевая ли ветка, зависит, дробить ли её.
                int ai = spine.IndexOf(attach);
                if (ai >= 0 && ai + 1 < spine.Count && !nodes[spine[ai + 1]].sealed2)
                    nodes[cur2].returnTo = spine[ai + 1];
                {
                    var chain = new List<int>();
                    for (int c3 = cur2; c3 >= 0 && c3 != attach; c3 = nodes[c3].parent) chain.Add(c3);
                    chain.Reverse();                       // от точки отрыва к ключу
                    int stageNow = ++keyCounter;
                    for (int k2 = 0; k2 < chain.Count; k2++)
                    {
                        if (k2 > 0 && k2 % KeyChainChunk == 0) stageNow = ++keyCounter;
                        nodes[chain[k2]].stage = stageNow;
                    }
                }
                // ⚠️ Резервировать бок комнаты-цели (sealed2) пробовал — не помогает: 22% → 20%.
                // Дело не в занятых боках, см. замер ниже.
                haveKeys++;
            }
        }

        // ── ДОБОР ДО ЗАКАЗАННОГО РАЗМЕРА ────────────────────────────────────────────────────────
        // Лишние комнаты — это просто пространство: коридоры, залы, обходы. Механизмов они не несут,
        // но именно они делают уровень уровнем, а не связкой из четырёх замков.
        // Вешаем их к случайным уже существующим комнатам, растя дерево вширь и вглубь.
        // ⚠️ ВЕШАЕМ НА НАИМЕНЕЕ ЗАГРУЖЕННЫЕ УЗЛЫ. 🐞 Случайный выбор родителя давал узлы с пятью
        // детьми, а у комнаты всего четыре стороны — раскладка переставала сходиться: замер показал
        // 27/30 при десяти комнатах, 20/30 при двадцати четырёх и 0/30 при сорока.
        // ⚠️ Родитель уже занимает одну сторону, значит детей у комнаты не больше трёх.
        var kidCount = new int[Mathf.Max(wantRooms, nodes.Count) + 8];
        foreach (var nd in nodes) if (nd.parent >= 0) kidCount[nd.parent]++;
        int guard = 0, fillerStage = 0;
        while (nodes.Count < wantRooms && guard++ < 2000)
        {
            int at = -1;
            for (int shot = 0; shot < 12; shot++)
            {
                int cand2 = rng.Next(nodes.Count);
                if (cand2 == 0 && nodes.Count > 2) continue;        // стартовую не обвешиваем
                if (nodes[cand2].sealed2) continue;                 // камера и её выход — неприкосновенны
                if (kidCount[cand2] >= (nodes[cand2].parent < 0 ? 3 : 2)) continue;
                at = cand2; break;
            }
            if (at < 0) break;                                      // свободных сторон не осталось
            kidCount[at]++;
            int filler = add(at, null, "простор", nodes[at].onMainPath && rng.Next(100) < 30);
            // ⭐⭐ КАЖДАЯ КОМНАТА ДОБОРА — СВОЙ ЭТАП, а не общий девяносто девятый.
            // 🐞 Комментарий «его провал безвреден» был правдой замысла и неправдой кода: одинаковый
            // номер этапа складывал ВЕСЬ добор в одну укладку, и провал любой комнаты ронял уровень
            // целиком. На тридцати комнатах добора мало и это не замечалось, на восьмидесяти их
            // полсотни и все обязаны встать разом — уровень не собирался в 9 случаях из 12.
            nodes[filler].stage = 99 + fillerStage++;
        }
        return nodes;
    }

    /// <summary>
    /// Кем закрыть выход из замкнутой области. Спрашиваем СЛОВАРЬ, а не выбираем руками: добавится
    /// новый паттерн, умеющий возвращать игрока, — он попадёт сюда сам, ничего не переписывая.
    /// </summary>
    /// <param name="verticalEntry">В запертую область ПРОВАЛИВАЮТСЯ сверху. Тогда у её комнаты есть
    /// вертикальная связь, и исполнитель, которому нужен сквозной боковой коридор, отпадает сразу.</param>
    private static PuzzleElement ExitElement(System.Random rng, bool verticalEntry)
    {
        var able = new List<PuzzleElement>();
        foreach (PuzzleElement e in System.Enum.GetValues(typeof(PuzzleElement)))
        {
            if (!PuzzleVocabulary.CanBeExit(e)) continue;
            // ⚠️ Спрашиваем у кандидата, не мешает ли ему сама форма запертой области.
            // 🐞 Без этого мост выпадал выходом в половине случаев и не вставал НИ РАЗУ: ему нужен
            // сквозной коридор, а у камеры есть люк сверху. Камера оставалась без выхода, и уровень
            // выходил непроходимым — ключ брался, финиш достигался, но не в одном прохождении.
            if (verticalEntry && PuzzleVocabulary.Need(e).throughCorridor) continue;
            able.Add(e);
        }
        return able.Count == 0 ? PuzzleElement.Door : able[rng.Next(able.Count)];
    }

    /// <summary>
    /// ⭐⭐ ВОРОТА ОБХОДЯТ ПО ГЕОМЕТРИИ, А НЕ ПО ГРАФУ. Проверяем ПЕРЕД штампом: дотянется ли игрок
    /// до пола верхней комнаты из клетки, которая НЕ лежит за этими воротами. Ступеньки ещё нет,
    /// значит это ровно вопрос «нужны ли ворота вообще».
    ///
    /// 🐞 Замер, ради которого правило заведено (сид 2008): комната 12 стоит справа-снизу, комната 14
    /// слева-сверху, между ними комната 13 с воротами. Полы 12 и 14 разошлись на dx=2, dy=3 — ровно в
    /// дотяжку. Игрок из 12 лезет прямо на кромку люка в полу 14, минуя и комнату 13, и ворота.
    /// По ГРАФУ комнат обхода нет (проверка это подтверждала), и все прежние правила — лишние рёбра,
    /// рёбра возврата, тоннели — тут ни при чём: комнаты просто оказались в дотяжке друг от друга.
    ///
    /// ⚠️ Правило шага берётся из <see cref="LevelModel.StepPossible"/>, а не пишется здесь заново:
    /// копии правил в этом проекте уже трижды расходились и давали баги.
    /// </summary>
    /// <param name="stepRow">Ряд каменной ступеньки под люком и её столбцы: модуль сносит её и кладёт
    /// на её место свой зигзаг, поэтому в расчёте обхода её быть НЕ должно.
    /// 🐞 Без этого проверка браковала ВСЕ ворота подряд (17 из 17): она видела ступеньку, честно
    /// находила по ней подъём и заключала «залезут и так» — хотя лезли ровно по той плите, которую
    /// ворота вот-вот уберут.</param>
    /// <param name="wallCol">Столбец ЗАКРЫТОЙ двери и её ряды: у инверсной двери камень в покое стоит,
    /// но в сетке его ещё нет — модуль поставит его сам. Считать обход надо по ЗАКРЫТОЙ двери, иначе
    /// проверка увидит открытый проём и решит, что дверь не нужна. Зеркало случая со ступенькой:
    /// у ворот из геометрии плиту вычитаем, у двери — прибавляем. −1 — двери нет.</param>
    private static bool GateBypassed(char[,] g, int[,] grp, int rows, int cols, List<Node> nodes,
                                     MazeCanvas.RoomRect[] rects, List<ModuleStamp> stamps, int childId,
                                     int stepRow, int shaftCol0, int shaftWidth,
                                     int wallCol = -1, int wallRowTop = 0, int wallHeight = 0)
    {
        // ⚠️ ИНВЕРСНЫЕ ПЛИТЫ В ПОКОЕ — КАМЕНЬ. В сетке они обычные буквы, и если считать их воздухом,
        // проверка пропускает игрока сквозь закрытые стены и объявляет обходом то, чего нет.
        // 🐞 Раньше множество было по БУКВАМ сетки. Буква повторяется по кругу (см. MazeCanvas.TileChar),
        // так что опознавать по ней группу нельзя — спрашиваем плоскость номеров.
        var solidAtRest = new HashSet<int>();
        foreach (var st0 in stamps) if (st0.inverted) solidAtRest.Add(st0.groupIx);
        var behind = new HashSet<int> { childId };
        for (bool grew = true; grew; )
        {
            grew = false;
            foreach (var nd in nodes)
                if (nd.parent >= 0 && behind.Contains(nd.parent) && behind.Add(nd.id)) grew = true;
        }
        // Камень: за краем сетки считаем камнем — так же, как MazeCanvas.At.
        System.Func<Vector2Int, bool> solid = k =>
        {
            int r = rows - 1 - k.y, c = k.x;
            if (r < 0 || r >= rows || c < 0 || c >= cols) return true;
            if (r == stepRow && c >= shaftCol0 && c < shaftCol0 + shaftWidth) return false;  // ступеньку снесут
            if (c == wallCol && r >= wallRowTop && r < wallRowTop + wallHeight) return true; // дверь закрыта
            return g[r, c] == '#' || solidAtRest.Contains(grp[r, c]);
        };
        System.Func<Vector2Int, bool> isHold = k => solid(k) && !solid(new Vector2Int(k.x, k.y + 1));

        // ⚠️ Защищаемая область — ВСЁ ПОДДЕРЕВО, а не только комната сразу за механизмом.
        // 🐞 Сначала целями были клетки одной комнаты, и три обхода из трёх на свежей серии прошли
        // мимо: игрок входил не в неё, а глубже — во внучатую комнату, куда обход дотягивался ровно
        // так же. Вопрос ставится один: можно ли попасть за механизм ГДЕ УГОДНО, минуя его проход.
        var targets = new List<Vector2Int>();
        foreach (int id in behind)
        {
            if (id < 0 || id >= rects.Length || rects[id].w == 0) continue;
            var rm = rects[id];
            for (int c = rm.col0; c < rm.col0 + rm.w; c++)
            for (int r = rm.row0; r <= rm.row0 + rm.h; r++)
            {
                var k = new Vector2Int(c, rows - 1 - r);
                if (isHold(k)) targets.Add(k);
            }
        }
        if (targets.Count == 0) return false;

        var targetSet = new HashSet<Vector2Int>(targets);

        // ⭐⭐ ОБХОД ДОКАЗЫВАЕТСЯ ПОХОДОМ, А НЕ СОСЕДСТВОМ. Идём по холдам от стартовой комнаты,
        // НЕ НАЖИМАЯ НИЧЕГО, и смотрим, доберёмся ли за механизм. Всё, что игрок может нажать,
        // только добавляет ему возможностей, поэтому дошли без единой кнопки — обход доказан.
        //
        // 🐞 До этого проверка спрашивала «есть ли рядом с поддеревом достижимая на вид клетка», и
        // это оказалось не тем вопросом: клетка может лежать в комнате-предке и всё равно быть
        // недостижимой (высокий холд, до которого дотягиваются только с платформы этого же
        // механизма). Замер: снималось 20 механизмов на 24 уровнях, причём 17 — на уровнях, которые
        // и так были чисты; механизмов на уровень падало с 4.1 до 3.4. Сужения «только предки» и
        // «инверсные плиты — камень» не помогли НИ НА ОДИН случай: вопрос был поставлен неверно,
        // а не грубо.
        var seen = new HashSet<Vector2Int>();
        var queue = new Queue<Vector2Int>();
        int rootRoom2 = 0;
        foreach (var nd in nodes) if (nd.parent < 0) { rootRoom2 = nd.id; break; }
        if (rootRoom2 < rects.Length && rects[rootRoom2].w > 0)
        {
            var rm = rects[rootRoom2];
            for (int c = rm.col0; c < rm.col0 + rm.w; c++)
            for (int r = rm.row0; r <= rm.row0 + rm.h; r++)
            {
                var k = new Vector2Int(c, rows - 1 - r);
                if (!isHold(k)) continue;
                // Вырожденный случай: стартовая комната сама попала в защищаемую область.
                if (targetSet.Contains(k)) return true;
                if (seen.Add(k)) queue.Enqueue(k);
            }
        }
        while (queue.Count > 0)
        {
            var a = queue.Dequeue();
            for (int dx = -MazeCanvas.ReachSide; dx <= MazeCanvas.ReachSide; dx++)
            for (int dy = -MazeCanvas.Climb; dy <= MazeCanvas.Climb; dy++)
            {
                if (dx == 0 && dy == 0) continue;
                if (!LevelModel.InReach(dx, dy, MazeCanvas.ReachSide, MazeCanvas.Climb)) continue;
                var t = new Vector2Int(a.x + dx, a.y + dy);
                if (seen.Contains(t) || !isHold(t)) continue;
                if (!LevelModel.StepPossible(solid, a, t, MazeCanvas.ReachSide, MazeCanvas.Climb)) continue;
                // ⭐ Первый же шаг ИЗВНЕ ВНУТРЬ и есть обход — запоминаем его целиком, а не факт.
                if (targetSet.Contains(t)) return true;
                seen.Add(t); queue.Enqueue(t);
            }
        }
        return false;
    }

    /// <summary>
    /// Ближайший предок, в который МОЖНО вложить кнопку. ⚠️ Это обязательно ВОРОТА: полку под чужую
    /// кнопку умеет пристраивать только вертикальный зигзаг, у двери и моста платформы для этого нет.
    /// 🐞 Пока хозяином брался любой ближайший механизм, семь вложений из тринадцати доставались
    /// двери или мосту и молча вырождались в обычные ворота.
    /// </summary>
    /// <summary>
    /// Хозяин вложенной кнопки — ТОЛЬКО НЕПОСРЕДСТВЕННЫЙ РОДИТЕЛЬ, и только если на его ребре стоят
    /// ворота (у двери и моста полки нет).
    ///
    /// 🐞🐞 РАНЬШЕ ИСКАЛОСЬ ВВЕРХ ПО ДЕРЕВУ ДО ПЕРВОГО МЕХАНИЗМА, БЕЗ ОГРАНИЧЕНИЯ РАССТОЯНИЯ — и это
    /// ломало сами ворота. Кнопка «открыть» садится на полку хозяина; если хозяин в восьми рёбрах,
    /// кнопка уезжает через полкарты, а в нижней комнате ворот НЕ ОСТАЁТСЯ НИ ОДНОГО триггера.
    /// Игрок стоит под воротами и открыть их нечем. Замер: из пяти вложенных ворот на 24 уровнях
    /// рядом с хозяином не оказалось НИ ОДНИХ (расстояния 3, 3, 4, 4 и 8 рёбер), и они всплывали
    /// в приёмке двумя разными способами сразу — как «отсечение» (за воротами всё потеряно) и как
    /// «холостая группа» (наверх нашёлся другой путь, а ворота так и не понадобились).
    ///
    /// Смысл вложенности требует соседства: игрок нажимает кнопку НА СТУПЕНЬКЕ хозяина, лезет по ней
    /// наверх — и оказывается ровно в нижней комнате следующих ворот. Одна комната между ними эту
    /// цепочку рвёт, восемь — превращают в мусор. Не соседи — не вложенность: строим обычные ворота
    /// со своей кнопкой на полу (ветка `else hostSt = null` в Furnish).
    /// </summary>
    public static int HostForNested(List<Node> nodes, int id)
    {
        int a = nodes[id].parent;
        if (a < 0) return -1;
        var el = nodes[a].element;
        return (el == PuzzleElement.Gate || el == PuzzleElement.NestedGate) ? a : -1;
    }

    /// <summary>Требования и направления для раскладки — прямо из деклараций словаря.</summary>
    public static void Requirements(List<Node> nodes, out RoomLayout.RoomReq[] req, out RoomLayout.LinkDir[] dir,
                                    System.Random rng = null, int hallPercent = 0)
    {
        int n = nodes.Count;
        req = new RoomLayout.RoomReq[n];
        dir = new RoomLayout.LinkDir[n];
        for (int i = 0; i < n; i++) { req[i] = new RoomLayout.RoomReq(); dir[i] = RoomLayout.LinkDir.Any; }

        // ⭐ ЗАЛЫ — РАЗБРОС МАСШТАБОВ. Часть комнат просит высоту сверх дотяжки; подъём в них разбит
        // уступами (см. HallLedges). Без этого весь уровень одного размера 3×5 и объёма нет.
        // ⚠️ Комнаты С МЕХАНИЗМОМ залами не делаем: модули считают геометрию от пола и потолка, и
        // высокий зал им не по зубам — это отдельная работа.
        if (rng != null && hallPercent > 0)
        {
            var busy = new HashSet<int>();
            foreach (var nd in nodes)
                if (nd.element != null) { busy.Add(nd.id); if (nd.parent >= 0) busy.Add(nd.parent); }
            for (int i = 1; i < n; i++)
            {
                if (busy.Contains(i) || nodes[i].holdsKey) continue;
                if (rng.Next(100) >= hallPercent) continue;
                req[i].maxH = RoomLayout.MaxHallHeight;
                req[i].minH = RoomLayout.MaxRoomHeight + 1;
                req[i].minW = Mathf.Max(req[i].minW, 5);          // узкий высокий зал читается колодцем
            }
        }

        // ⭐⭐ ЖЁСТКИЕ ПРИТЯЗАНИЯ НА НАПРАВЛЕНИЕ — ПЕРВЫМ ПРОХОДОМ, И ИХ НЕЛЬЗЯ ПЕРЕБИТЬ.
        // 🐞 ЗАМЕР, из-за которого это появилось: камеру заказывали 60 раз, а вставало 15. Половина
        // потерь (21 из 45 сошедшихся раскладок) — ребро камеры выходило ГОРИЗОНТАЛЬНЫМ, хотя словарь
        // требовал Down. Виноват был не словарь и не раскладка: ВЫХОД из камеры выбирается случайно
        // (дверь или мост), и когда выпадал МОСТ, его собственное требование `dir[nd.parent] =
        // Horizontal` затирало уже поставленный Down — ведь родитель моста и есть камера. Узлы
        // обходятся по возрастанию id, камера идёт раньше выхода, и последнее слово всегда
        // оставалось за мостом. Рендер потом честно ронял камеру на `if (!link.vertical) break`.
        // ⚠️ Разница между притязаниями: камере вертикаль НУЖНА ПО ГЕОМЕТРИИ (в неё проваливаются
        // сквозь потолок, иного входа нет), а мосту сквозной коридор нужен, ЧТОБЫ НЕ СТАТЬ
        // ДЕКОРАЦИЕЙ — он и так проверяется постфактум и просто не строится. Поэтому уступает мост.
        var locked = new bool[n];
        foreach (var nd in nodes)
        {
            if (nd.element == null || nd.element.Value != PuzzleElement.Vault) continue;
            // Камера — СКВОЗНОЙ пролёт: трасса входит в её коридор сбоку и выходит сбоку же.
            // Вертикальная связь здесь всё бы обесценила — провал в полу обошли бы поверху.
            dir[nd.id] = RoomLayout.LinkDir.Horizontal; locked[nd.id] = true;
            var vneed = PuzzleVocabulary.Need(nd.element.Value);
            foreach (var kid in nodes)
            {
                if (kid.parent != nd.id) continue;
                if (kid.isCellar)
                {
                    // ПОДВАЛ — единственное вертикальное ребро коридора, и он встаёт столбец в
                    // столбец под ним: трафарет рисует оба этажа как одну картинку.
                    dir[kid.id] = RoomLayout.LinkDir.Down; locked[kid.id] = true;
                    req[kid.id].minW = req[kid.id].maxW = vneed.maxWidth;
                    req[kid.id].minH = req[kid.id].maxH = vneed.cellarHeight;
                    req[kid.id].alignX = true;
                    req[kid.id].ownClimb = true;   // лестница внутри подвала нарисована трафаретом
                }
                else { dir[kid.id] = RoomLayout.LinkDir.Horizontal; locked[kid.id] = true; }
            }
        }
        // ⭐⭐ ВЕТКА-ПЕТЛЯ: её звеньям разрешено выходить из области роста, а последнему предписано
        // встать вплотную к комнате маршрута. Без первого петля невозможна в принципе (области и
        // заведены, чтобы ветки не возвращались), без второго — не замкнётся.
        // Цель петли известна всем звеньям ветки: к ней и тянемся со второй половины пути.
        var loopTarget = new Dictionary<string, int>();
        foreach (var nd in nodes) if (nd.returnTo >= 0) loopTarget[nd.route ?? ""] = nd.returnTo;
        foreach (var nd in nodes)
        {
            if (nd.branchStep < 0) continue;
            req[nd.id].freeRegion = true;
            // ⭐ Первому звену ветки разрешаем ПЕРЕЕХАТЬ на другую комнату маршрута, если на
            // назначенной она не встала: точка отрыва выбиралась в плане вслепую, до геометрии.
            if (nd.branchStep == 0)
            {
                var opts = new List<int>();
                foreach (var m in nodes) if (m.onMainPath && !m.sealed2 && m.id != nd.parent) opts.Add(m.id);
                req[nd.id].reattach = opts;
                // ⭐⭐ ЗДЕСЬ НАЧИНАЕТСЯ КОЛЬЦО. Метка включает ТОЛЬКО вычисляемую укладку (PlaceRing):
                // она сама сделает провал, марш и подъём. Общих требований (направление, высота) не
                // ставим — прошлая попытка так и провалилась: провал требовали от обычной укладки,
                // и он воевал с петлёй (14 провалов, но лишь 2 ветки целиком).
                // ⚠️ Не вышло кольцо — ветка ложится как обычная, без провала. Это осознанный
                // размен: замысел целиком или ничего, но уровень не страдает.
                req[nd.id].ringStart = true;
                // ⭐⭐ ПОЛОСА ПОД КОЛЬЦО БРОНИРУЕТСЯ ВМЕСТЕ С ХРЕБТОМ. Комната, к которой цепляется
                // ветка, держит под собой пустой прямоугольник — туда потом ляжет кольцо.
                // 🐞 Без брони кольцо не встало ни разу: по мере починки прочих причин отказ
                // смещался к столкновениям (137 из 184 попыток) — место занимал сам хребет.
                // Глубина: ярус кольца (4) + провал (минимум 4) + запас.
                // ⚠️⚠️ БРОНЬ ЗДЕСЬ ВЫКЛЮЧЕНА — ПО ЗАМЕРУ. Узкая (в ширину комнаты) не спасала:
                // столкновений оставалось 125 из 184. Широкая (±20 клеток) сделала хуже — двери
                // возврата упали с 5 до 0, потому что бронь выдавила из уровня всё остальное.
                // Вывод: укладка «комната за комнатой от родителя» не умеет держать пустоту нужной
                // кольцу формы (30×10). Правильный порядок, судя по схеме игрока, обратный —
                // сперва кольца как готовые блоки, потом хребет между ними. Это другая укладка.
                if (nd.parent >= 0) { req[nd.parent].reserveBelow = 0; req[nd.parent].reserveWide = 0; }
            }
            // ⚠️⚠️ ОДНОСТОРОННЕГО ВХОДА В ВЕТКУ ЗДЕСЬ НЕТ — ОТКАЧЕНО ПО ЗАМЕРУ (решение игрока).
            // Замысел верный: игрок должен сваливаться в ветку и возвращаться дверью, иначе дверь
            // возврата — украшение. Но провал и петля тянут раскладку в разные стороны: с провалом
            // из 27 веток односторонними стали 14, а дверь замкнулась лишь на 3, вместе — на 2.
            // Без провала дверь ставится втрое чаще. Оставлять генератор в худшем состоянии ради
            // недоделанного замысла нельзя, поэтому вход снова обычный.
            // ⚠️ Продолжение — ВЫЧИСЛЯЕМОЕ КОЛЬЦО (RoomLayout.PlaceRing, уже написано и замерено):
            // оно считает форму «провал → марш вбок → подъём → дверь», но не встаёт ни разу, потому
            // что укладывается ПОСЛЕДНИМ, когда свободного места на ярус ниже трассы уже нет
            // (120 отказов «цель не подошла», 64 «задели чужое»). Следующий заход — резервировать
            // полосу под кольцо ВМЕСТЕ с хребтом, как сделано для подвала камеры.
            if (nd.returnTo >= 0)
            {
                req[nd.id].ringTarget = nd.returnTo;
                // Выходим на трассу где угодно: назначать одну конкретную комнату оказалось строго —
                // к моменту укладки последнего звена она бывает обстроена со всех сторон.
                var any = new List<int>();
                foreach (var m in nodes) if (m.onMainPath && !m.sealed2) any.Add(m.id);
                req[nd.id].nextToAny = any;
            }
            // Первую половину ветки уводим ОТ трассы (иначе виток выйдет в две комнаты), вторую —
            // тянем обратно к ней. Это и есть форма с рисунка: ушёл, обошёл, вернулся.
            int tgt;
            if (nd.branchStep >= nd.branchLen / 2 && loopTarget.TryGetValue(nd.route ?? "", out tgt))
                req[nd.id].pullTo = tgt;
        }

        // ⚠️⚠️ ФОРМЫ «ВВЕРХ → ВБОК → ВНИЗ» ЗДЕСЬ НЕТ, И ЭТО РЕЗУЛЬТАТ ЗАМЕРА.
        // Задумка была прямо с рисунка игрока: ветка к ключу уходит вверх, идёт вбок и спускается
        // обратно к трассе, чтобы её конец стал соседом маршрута и петлю можно было замкнуть дверью.
        // 🐞 Жёстким требованием раскладка не сошлась НИ РАЗУ из сорока. Мягким (RoomReq.prefer) она
        // сходится 40/40, но соседей стало МЕНЬШЕ: 1 конец ветки из 120 против 6 без всякой формы.
        // Причина не в направлениях: раскладка НАМЕРЕННО разводит ветки по своим областям (region),
        // чтобы они не наезжали друг на друга, — и вернуться к трассе ветка не может в принципе.
        // Значит петля упирается не в выбор направления, а в саму область роста. Это следующая
        // работа по графу, и делать её надо в RoomLayout, а не подбором направлений здесь.

        // ⭐ ТОННЕЛЬ ВМЕСТО ОБЩЕЙ СТЕНЫ — только там, где на ребре нет механизма. Ворота, дверь и мост
        // считают свою геометрию от общей стены, им зазор ломает всё; обычной комнате он лишь даёт
        // место встать. Замер до этого: 38 отказов стыковки на уровень, и три четверти из них —
        // у комнат без всяких требований.
        foreach (var nd in nodes)
            if (nd.element == null && !nd.isCellar) req[nd.id].allowTunnel = true;

        // ⭐ Раскладке нужно знать, на каких рёбрах стоят ЗАМКИ: вокруг них она держит зазор, иначе
        // игрок перешагивает из комнаты перед механизмом в комнату за ним (см. RoomReq.lockedEdge).
        foreach (var nd in nodes)
            if (nd.element != null && nd.parent >= 0) req[nd.id].lockedEdge = true;

        // ⭐⭐ РАСКЛАДКА ВПРАВЕ ПРОПУСТИТЬ ПОДДЕРЕВО, КОТОРОЕ НИЧЕГО НЕ НЕСЁТ.
        //
        // 🐞 Раньше это право имели ТОЛЬКО комнаты-доборы (условие «nd.stage >= 99»), а хвост ветки
        // рецепта — точно такие же пустые комнаты — считался обязательным. Разбор пяти несошедшихся
        // уровней при заказе 50 показал у всех пяти одну и ту же картину: этап из 14-16 комнат, из
        // них 2-4 с механизмом, а 10-13 — пустые 3x3 без направления. Не встала одна пустая комната
        // из шестнадцати — не встал ВЕСЬ УРОВЕНЬ, после двенадцати перезапусков подряд.
        //
        // ⚠️ Пропускать можно не всякую пустую комнату, а только ту, ЗА КОТОРОЙ тоже пусто: посреди
        // цепочки она держит потомков, и выбросив её, мы оторвём то, что за ней. Поэтому считаем
        // признак по ПОДДЕРЕВУ снизу вверх. Комнаты маршрута не трогаем вовсе — на них стоят
        // чекпоинты, и трасса обязана быть целой.
        // ⭐ Комнаты ДОБОРА (те, что добавлены ради простора) раскладка вправе пропустить, если им не
        // нашлось места: за ними нет ни цели, ни механизма (см. RoomReq.optional).
        // ⛔ ПРОБОВАЛ РАСШИРИТЬ ЭТО ПРАВИЛО — НЕ ПРИГОДИЛОСЬ (2026-09-11). Идея была отдавать
        // раскладке право бросить ЛЮБОЕ поддерево, которое ничего не несёт, а звенья ветки-петли
        // ронять на последней ступени послаблений. Замер убил затею: StatDropped = 0 и на
        // умолчаниях, и при заказе 50 — раскладка не бросает комнаты ВООБЩЕ, ни старым правилом,
        // ни новым. Сходимость чинило не это, а дробление длинных веток на этапы (см. KeyChainChunk).
        foreach (var nd in nodes)
            if (nd.element == null && !nd.holdsKey && !nd.isFinish && !nd.isCellar
                && nd.parent >= 0 && nd.stage >= 99) req[nd.id].optional = true;

        var dirL = dir;                                // out-параметр в лямбду не пускают, ссылка та же
        System.Action<int, RoomLayout.LinkDir> claim = (id, d) =>
        { if (id >= 0 && !locked[id]) dirL[id] = d; };

        foreach (var nd in nodes)
        {
            if (nd.element == null) continue;
            var need = PuzzleVocabulary.Need(nd.element.Value);
            // ⭐ Требование к месту берётся ИЗ СЛОВАРЯ и применяется к ОБЕИМ комнатам ребра:
            // механизм живёт между ними, и тесной не должна быть ни та, ни другая.
            // ⚠️ ПАТТЕРН С ЗАКРЕПЛЁННЫМ РАЗМЕРОМ НИЧЕГО НЕ ТРЕБУЕТ ОТ СОСЕДА: он самодостаточен, и
            // его комната резервируется ровно под картинку.
            // 🐞 Замер: камере 20×3 требование ширины уезжало и на соседнюю комнату, а у той потолок
            // ширины восемь — раскладка не сошлась НИ РАЗУ из шестидесяти.
            bool pinned = need.maxWidth > 0 || need.maxHeight > 0;
            // ⭐ КОМНАТА ПОД КАРТИНКУ — у подъёма это РОДИТЕЛЬ (см. SpaceNeed.patternInParent):
            // игрок приходит снизу, и лестница обязана стоять на его стороне люка.
            int pinRoom = need.patternInParent && nd.parent >= 0 ? nd.parent : nd.id;
            foreach (int id in pinned ? new[] { pinRoom } : new[] { nd.id, nd.parent })
            {
                if (id < 0) continue;
                req[id].minW = Mathf.Max(req[id].minW, need.minWidth);
                // ⚠️ Потолок высоты не применяем к паттерну, который сам несёт свои уступы:
                // ограничение существует ради проходимости, а он за неё уже отвечает.
                int hCap = need.selfClimbing ? RoomLayout.MaxHallHeight : RoomLayout.MaxRoomHeight;
                req[id].minH = Mathf.Max(req[id].minH, Mathf.Min(need.minHeight, hCap));

                // ⭐⭐ МЕСТО ЗАКАЗЫВАЕТСЯ И ПОД ПОДМЕНУ. Направление ребра выбирает раскладка, то есть
                // ПОЗЖЕ этого места, и на постройке элемент может смениться (дверь на вертикальном
                // ребре → ворота, мост без коридора → ворота или дверь). Комната при этом остаётся
                // отмеренной под исходный элемент — и модуль отказывается встать.
                // 🐞 Замер при заказе 50 механизмов: 72 потери из 85 — ровно отказ ворот «комната
                // ниже 4 рядов», потому что дверь просила 3. Остальные пять причин отказа дали НОЛЬ.
                // Результат: заказ 50 — встало 99% вместо 72%, все шесть причин отказа ворот по нулям.
                //
                // ⚠️ ЦЕНА ИЗМЕРЕНА И ПРИНЯТА. Комната двери и моста стала 4 ряда вместо 3, раскладке
                // теснее. A/B на 20 сидах (заказ 20, 56 комнат): поставка 18.75 → 19.79 из 20, зато
                // раскладка сошлась 19/20 вместо 20/20, а чистых стало 14/19 против 17/20.
                // Чистота падает НЕ от поломки: непроходимых 5 против 3, потому что замки, которые
                // раньше молча пропадали и оставляли проход открытым, теперь действительно стоят.
                // Перебор сидов дорожает с 1.2 попытки до 1.4 — дёшево за +1 механизм на уровень и
                // за снятие главной потери на плотных заказах.
                foreach (var alt in PuzzleVocabulary.Substitutes(nd.element.Value))
                {
                    var an = PuzzleVocabulary.Need(alt);
                    req[id].minW = Mathf.Max(req[id].minW, an.minWidth);
                    req[id].minH = Mathf.Max(req[id].minH, Mathf.Min(an.minHeight, hCap));
                }
            }
            // ⚠️ ПОТОЛОК РАЗМЕРА — ТОЛЬКО КОМНАТЕ САМОГО ЭЛЕМЕНТА, не соседней: трафарет рисует
            // себя в одной комнате, а вторая нужна ему лишь как место для кнопки снаружи.
            if (need.maxWidth > 0)  req[pinRoom].maxW = Mathf.Max(need.minWidth, need.maxWidth);
            if (need.maxHeight > 0) req[pinRoom].maxH = Mathf.Max(need.minHeight, need.maxHeight);
            // ⚠️ ХОЗЯИНУ ВЛОЖЕННОЙ КНОПКИ НУЖНА ЛИШНЯЯ ШИРИНА. Полка — это пристройка сбоку к верхнему
            // уступу зигзага, и она не строится, если уступ вместе с ней занял бы всю ширину комнаты
            // (иначе комната запечатывается). 🐞 Замер: из шести ворот-хозяев полка вышла у трёх.
            if (nd.element.Value == PuzzleElement.NestedGate)
            {
                int host = HostForNested(nodes, nd.id);
                if (host >= 0)
                {
                    req[host].minW = Mathf.Max(req[host].minW, 7);
                    if (nodes[host].parent >= 0) req[nodes[host].parent].minW = Mathf.Max(req[nodes[host].parent].minW, 7);
                }
            }

            // ⭐⭐ ГЕОМЕТРИЯ КАМЕРЫ ЗАКАЗЫВАЕТСЯ, А НЕ ВЫПРАШИВАЕТСЯ.
            // 🐞 Пока требования камеры проверялись постфактум, она не строилась ни разу из четырёх
            // заказов: нужно было СРАЗУ комнату ≥7×5, один люк сверху и ровно один боковой проём, а
            // дерево такое сочетание почти не выдаёт. Тот же урок, что с мостом: сквозной коридор
            // начал получаться только когда его заказали раскладке (13 мостов из 17).
            // Направления камеры (вниз в камеру, вбок к кнопке, вбок на выход) уже расставлены
            // первым проходом и залочены — здесь остаются только её требования к размеру.
            if (nd.element.Value == PuzzleElement.Vault) continue;

            if (need.verticalEdge) claim(nd.id, RoomLayout.LinkDir.Up);
            else if (need.horizontalEdge) claim(nd.id, RoomLayout.LinkDir.Horizontal);

            // ⚠️ МОСТУ НУЖЕН СКВОЗНОЙ КОРИДОР, и это надо заказать РАСКЛАДКЕ, а не проверять постфактум.
            // 🐞 Пока я просто сообщал модулю «это сквозной коридор», не проверяя, мост выходил
            // декоративным в 31% случаев (ворота — 2%, двери — 0%): его обходили через вертикальную
            // связь той же комнаты. Комната моста обязана быть проходной насквозь ВБОК — значит и
            // ребро к ней, и ребро от неё дальше должны быть горизонтальными.
            if (nd.element.Value == PuzzleElement.Bridge)
            {
                claim(nd.id, RoomLayout.LinkDir.Horizontal);
                if (nd.parent >= 0 && nodes[nd.parent].parent >= 0)
                    claim(nd.parent, RoomLayout.LinkDir.Horizontal);
            }
        }
    }

    /// <summary>
    /// Рендер раскладки в сетку символов: сплошной камень, в нём вырезаются полости комнат и проходы
    /// по связям. Дверной проём режется от пола вверх (низкий, как и на решётке), люк — во всю ширину
    /// общего отрезка.
    /// ⚠️ Сетка символов растёт СВЕРХУ ВНИЗ, а раскладка считает Y вверх — перевод здесь, в одном месте.
    /// </summary>
    /// <summary>Сколько клеток пола комната обязана сохранить, сколько бы люков в неё ни вело.</summary>
    private const int MinFloorKept = 2;

    public static char[,] Render(RoomLayout.Result lay, System.Random rng, out int rows, out int cols)
    {
        int maxX = 0, maxY = 0;
        foreach (var r in lay.rooms) { maxX = Mathf.Max(maxX, r.X1); maxY = Mathf.Max(maxY, r.Y1); }
        cols = maxX + 4; rows = maxY + 4;
        var g = new char[rows, cols];
        for (int r = 0; r < rows; r++) for (int c = 0; c < cols; c++) g[r, c] = '#';
        int rowsLocal = rows;
        System.Func<int, int> toRow = y => rowsLocal - 1 - y;      // мир (Y вверх) → строка сетки

        foreach (var rm in lay.rooms)
            for (int y = rm.y0; y <= rm.Y1; y++)
            for (int x = rm.x0; x <= rm.X1; x++)
                g[toRow(y), x] = '.';

        // Кто из пары ВЫШЕ: у вертикальной связи это `b` по построению раскладки.
        System.Func<RoomLayout.RoomLink, int> nodesAbove = l2 => l2.b;

        foreach (var l in lay.links)
        {
            if (l.vertical)
            {
                // ⚠️ ЛЮК УЖЕ ОБЩЕЙ СТЕНЫ, А НЕ ВО ВСЮ ЕЁ ШИРИНУ. Стена между этажами — это ПОЛ верхней
                // комнаты, и вылезая из люка игрок цепляется за её клетку СБОКУ. Прорежешь весь общий
                // отрезок — цепляться станет не за что.
                // 🐞 Первый сквозной прогон именно так и делал: 27 холдов из 94 достижимы, финиш
                // недостижим. На решётке люк всегда был 2-3 клетки внутри комнаты ровно поэтому.
                // ⚠️⚠️ У КОМНАТЫ МОЖЕТ БЫТЬ НЕСКОЛЬКО ЛЮКОВ В ПОЛУ, и вместе они съедают его целиком.
                // 🐞 Поймано на разборе: под комнатой 3 сходились два прохода, из шести клеток пола
                // оставалась одна — три этажа сливались в колодец высотой 10 рядов без единого уступа,
                // и половина уровня становилась недостижимой. На решётке такого не бывало: там у
                // комнаты был ровно один проход вниз.
                var upper = lay.rooms.Find(rr => rr.id == (nodesAbove(l)));
                int span = l.to - l.from + 1;
                int hw = Mathf.Min(span, 2 + rng.Next(2));
                // ⛔ ПОБЛАЖКУ РЕБРУ ВОЗВРАТА ЗДЕСЬ ПРОБОВАЛ И УБРАЛ (2026-09-11). Рассуждение было
                // такое: MinFloorKept бережёт пол от люков, а инверсный барьер в покое КАМЕНЬ и пола
                // не отнимает, значит клапану можно резать шире. Замер не подтвердил: клапанов стало
                // 8 вместо 9, поставка 20.00 вместо 20.10. Правило остаётся общим для всех люков.
                if (upper != null)
                {
                    int free = 0;
                    for (int x = upper.x0; x <= upper.X1; x++) if (g[toRow(l.wall), x] == '#') free++;
                    hw = Mathf.Min(hw, Mathf.Max(0, free - MinFloorKept));
                }
                if (hw < 1) continue;                            // пол верхней комнаты кончился
                int off = span > hw ? rng.Next(span - hw + 1) : 0;
                for (int x = l.from + off; x < l.from + off + hw; x++) g[toRow(l.wall), x] = '.';
                l.cutFrom = l.from + off; l.cutTo = l.from + off + hw - 1;   // где люк на самом деле

                // ⚠️⚠️ УСТУПОВ ПОД ЛЮКОМ ЗДЕСЬ НЕТ — ДВЕ ПОПЫТКИ, ОБЕ ПРОВАЛИЛИСЬ ПО ЗАМЕРУ.
                // Вторая ставила уступ в СЕРЕДИНЕ комнаты (первая — поперёк люка, у стены, и садилась
                // в дверной проём). Недостижимых ключей стало 9 → 12. Значит чинить надо не подъём
                // постфактум, а не создавать непроходимый люк вовсе — см. проверку высоты в
                // RoomLayout: комната ПОД люком обязана быть не выше дотяжки.

                // ⚠️⚠️ О ПРЕЖНЕЙ ПОПЫТКЕ УСТУПА ПОПЕРЁК ЛЮКА — РЕЗУЛЬТАТ ЗАМЕРА, А НЕ НЕДОДЕЛКА.
                // Гипотеза была стройной: из 389 вертикальных связей без механизма 203 ведут в
                // комнату ВЫШЕ ДОТЯЖКИ (высота 4-5 при подъёме 3), значит половина провалов —
                // ловушка, и уступ на середине комнаты вернул бы игрока наверх.
                // 🐞 Замер сказал обратное. Уступ во всю ширину люка: безвыходных клеток 247 → 266,
                // а достижимых стало МЕНЬШЕ (745 → 644) — плита садилась в дверной проём и затыкала
                // его. Уступ, отодвинутый от боковых стен: 565 → 565, ноль эффекта.
                // Причина промаха в том, что чинилось не то место: разбор безвыходных клеток дал
                // 145 из 197 ВНЕ комнат — на внешней кожуре массива и в прорезанных тоннелях, а не
                // в комнатах под люками. Возврат надо строить туда, и по указанию модели.
            }
            else
            {
                // Проём режем на всю высоту, что запросила связь: она уже учла перепад полов.
                // Для ЛИШНЕГО ребра это может быть не одна стена, а короткий ТОННЕЛЬ сквозь камень.
                for (int y = l.from; y <= l.to; y++)
                for (int x = l.wall; x <= Mathf.Max(l.wall, l.wallEnd); x++)
                    if (x >= 0 && x < cols) g[toRow(y), x] = '.';

                // ⭐ СТУПЕНИ В ПРОЁМЕ (идея игрока): если полы соседей расходятся больше дотяжки,
                // перепад разбивается площадками через каждые Climb рядов. Ставим их со стороны
                // НИЖНЕЙ комнаты, вплотную к стене — там они читаются как лестница, а не как мусор.
                var ra = lay.rooms.Find(r2 => r2.id == l.a);
                var rb = lay.rooms.Find(r2 => r2.id == l.b);
                if (ra == null || rb == null) continue;
                int gap = Mathf.Abs(ra.y0 - rb.y0);
                if (gap <= MazeCanvas.Climb) continue;
                var low = ra.y0 < rb.y0 ? ra : rb;                 // из чьей комнаты лезем вверх
                int dir = low.X1 < l.wall ? -1 : +1;               // вглубь нижней комнаты от стены
                for (int step = MazeCanvas.Climb; step < gap; step += MazeCanvas.Climb)
                {
                    int y = low.y0 + step;
                    for (int k = 1; k <= 2; k++)                   // площадка шириной 2 клетки
                    {
                        int x = l.wall + dir * k;
                        if (x < low.x0 || x > low.X1) break;
                        g[toRow(y), x] = '#';
                    }
                }
            }
        }
        return g;
    }

    /// <summary>
    /// ⭐ ОБРЕЗКА ОБОЛОЧКИ — перенос со старого пути. Оставляем вокруг вырезанного пространства
    /// <see cref="RockShell"/> клеток камня, остальное превращаем в пустоту. Без этого уровень
    /// обрамлён сплошным прямоугольником камня и силуэта нет вовсе — именно это игрок и увидел,
    /// когда сказал «как играбельный уровень очень слабо».
    ///
    /// ⚠️ СРЕЗАЕМ ТОЛЬКО КАМЕНЬ, СВЯЗАННЫЙ С ВНЕШНЕЙ ГРАНИЦЕЙ. Иначе середина крупного массива
    /// оказывается дальше оболочки и выедается ИЗНУТРИ — получается запечатанная камера, визуально
    /// неотличимая от комнаты, куда невозможно попасть (обжигались на этом на решётке).
    /// ⚠️ Обрезка идёт последней и сама может оставить два тайла углом к углу — такие клетки
    /// возвращаем в камень, проверка зажимов не разбирает, игровая это зона или оболочка.
    /// </summary>
    private const int RockShell = 2;

    private static void TrimShell(char[,] g, int rows, int cols)
    {
        var dRock = new int[rows, cols];
        for (int r = 0; r < rows; r++) for (int c = 0; c < cols; c++) dRock[r, c] = int.MaxValue;
        var q = new Queue<Vector2Int>();
        for (int r = 0; r < rows; r++)
        for (int c = 0; c < cols; c++)
            if (g[r, c] != '#') { dRock[r, c] = 0; q.Enqueue(new Vector2Int(c, r)); }
        while (q.Count > 0)
        {
            var cur = q.Dequeue();
            for (int k = 0; k < 4; k++)
            {
                int nr = cur.y + (k == 0 ? -1 : k == 1 ? 1 : 0), nc = cur.x + (k == 2 ? -1 : k == 3 ? 1 : 0);
                if (nr < 0 || nr >= rows || nc < 0 || nc >= cols || dRock[nr, nc] != int.MaxValue) continue;
                dRock[nr, nc] = dRock[cur.y, cur.x] + 1; q.Enqueue(new Vector2Int(nc, nr));
            }
        }
        var outside = new bool[rows, cols];
        var qOut = new Queue<Vector2Int>();
        System.Action<int, int> seed = (r, c) =>
        {
            if (r < 0 || r >= rows || c < 0 || c >= cols || outside[r, c]) return;
            if (g[r, c] != '#' || dRock[r, c] <= RockShell) return;
            outside[r, c] = true; qOut.Enqueue(new Vector2Int(c, r));
        };
        for (int c = 0; c < cols; c++) { seed(0, c); seed(rows - 1, c); }
        for (int r = 0; r < rows; r++) { seed(r, 0); seed(r, cols - 1); }
        while (qOut.Count > 0)
        {
            var cur = qOut.Dequeue();
            for (int k = 0; k < 4; k++)
                seed(cur.y + (k == 0 ? -1 : k == 1 ? 1 : 0), cur.x + (k == 2 ? -1 : k == 3 ? 1 : 0));
        }
        for (int r = 0; r < rows; r++) for (int c = 0; c < cols; c++) if (outside[r, c]) g[r, c] = ' ';

        for (int iter = 0; iter < 8; iter++)
        {
            int restored = 0;
            for (int r = 0; r + 1 < rows; r++)
            for (int c = 0; c + 1 < cols; c++)
            {
                bool tl = g[r, c] == '#',     tr = g[r, c + 1] == '#';
                bool bl = g[r + 1, c] == '#', br = g[r + 1, c + 1] == '#';
                if (!((tl && br && !tr && !bl) || (tr && bl && !tl && !br))) continue;
                if (g[r, c + 1] == ' ')          { g[r, c + 1] = '#'; restored++; }
                else if (g[r + 1, c] == ' ')     { g[r + 1, c] = '#'; restored++; }
                else if (g[r, c] == ' ')         { g[r, c] = '#'; restored++; }
                else if (g[r + 1, c + 1] == ' ') { g[r + 1, c + 1] = '#'; restored++; }
            }
            if (restored == 0) break;
        }
    }

    /// <summary>
    /// ⭐ ДЕКОР И МОНЕТЫ — перенос со старого пути. Без них комнаты голые, и уровень читается как
    /// чертёж, а не как место: именно этого не хватало, когда игрок сказал «очень слабо».
    ///
    /// ⚠️ ЗАЩИЩЁННЫЕ КЛЕТКИ. На решётке были маски `noBump`/`noFill`, тут их нет, поэтому список
    /// неприкосновенного собираем сами: клетки проходов и по клетке над ними (посадочные холды), а
    /// также ступени. Декор, заткнувший проём или посадочный холд, рвёт маршрут — а поймать это можно
    /// будет только приёмкой, то есть дорого и поздно.
    /// ⚠️ Кладём ПОСЛЕ объектов и механизмов и трогаем только чистый воздух: так декор физически не
    /// может занять место кнопки, ключа или платформы.
    /// </summary>
    private static void Decorate(char[,] g, int rows, int cols, MazeCanvas.RoomRect[] rects,
                                 bool[,] guarded, HashSet<int> noDecor, System.Random rng)
    {
        // ── Инвариант отделки: узор не имеет права ЗАПЕЧАТАТЬ воздушный карман ──
        // 🐞 Тумба и зубцы садились в ходовую полосу у пола, воздух при этом оставался связным (проверял),
        // но карман отрезался от внешнего контура: «замуровано» 0→8, а вместе с ним терялся ключ
        // (сиды 2, 10, 14). Считаем воздух, достижимый от края: узор вправе съесть ровно свои клетки.
        System.Func<int> openAir = () =>
        {
            var seen = new bool[rows, cols];
            var q = new Queue<Vector2Int>();
            System.Action<int, int> push = (r, c) =>
            { if (!seen[r, c] && g[r, c] != '#') { seen[r, c] = true; q.Enqueue(new Vector2Int(c, r)); } };
            for (int c = 0; c < cols; c++) { push(0, c); push(rows - 1, c); }
            for (int r = 0; r < rows; r++) { push(r, 0); push(r, cols - 1); }
            int n = 0;
            int[] dx = { 1, -1, 0, 0 }, dy = { 0, 0, 1, -1 };
            while (q.Count > 0)
            {
                var p = q.Dequeue(); n++;
                for (int k = 0; k < 4; k++)
                {
                    int nx = p.x + dx[k], ny = p.y + dy[k];
                    if (nx < 0 || nx >= cols || ny < 0 || ny >= rows) continue;
                    push(ny, nx);
                }
            }
            return n;
        };
        int openBefore = openAir();

        var placed = new List<Vector2Int>();
        System.Func<int, int, bool> put = (r, c) =>
        {
            if (r < 0 || r >= rows || c < 0 || c >= cols) return false;
            if (g[r, c] != '.' || guarded[r, c]) return false;
            g[r, c] = '#';
            placed.Add(new Vector2Int(c, r));
            // Диагональный зажим: два тайла углом к углу, пэдам не пролезть.
            for (int rr = r - 1; rr <= r; rr++)
            for (int cc = c - 1; cc <= c; cc++)
            {
                if (rr < 0 || rr + 1 >= rows || cc < 0 || cc + 1 >= cols) continue;
                bool tl = g[rr, cc] == '#',     tr = g[rr, cc + 1] == '#';
                bool bl = g[rr + 1, cc] == '#', br = g[rr + 1, cc + 1] == '#';
                if ((tl && br && !tr && !bl) || (tr && bl && !tl && !br))
                { g[r, c] = '.'; placed.RemoveAt(placed.Count - 1); return false; }
            }
            return true;
        };
        for (int id = 0; id < rects.Length; id++)
        {
            var rm = rects[id];
            if (rm.w == 0) continue;
            // ⚠️⚠️ В КОМНАТАХ С МЕХАНИЗМОМ ДЕКОРА НЕТ. 🐞 Балкон и лесенка дают лишние зацепы, и
            // подъём, ради которого стоят ворота, становится возможен БЕЗ них — механизм превращается
            // в декоративный. Замер: брак подскочил 2 → 9 из 16, и все девять именно такие.
            if (noDecor.Contains(id)) continue;
            if (rng.Next(100) >= 55) continue;                 // деталь примерно в половине комнат
            int rFloor = rm.row0 + rm.h - 1, w = rm.w, h = rm.h;
            int pick = rng.Next(6);
            if ((DecorMask & (1 << pick)) == 0) continue;       // диагностика: гасим отдельный паттерн
            placed.Clear();
            switch (pick)
            {
                case 0:                                        // ТУМБА: 1-2 клетки на полу
                {
                    int bw = 1 + rng.Next(2), off = 1 + rng.Next(Mathf.Max(1, w - bw - 1));
                    for (int k = 0; k < bw; k++) put(rFloor, rm.col0 + off + k);
                    break;
                }
                case 1:                                        // ПИЛОН: столб от пола вверх
                {
                    if (w < 4) break;                          // в узкой комнате столб = пробка
                    int off = 1 + rng.Next(w - 2), ph = 1 + rng.Next(Mathf.Min(2, h - 1));
                    for (int k = 0; k < ph; k++) put(rFloor - k, rm.col0 + off);
                    break;
                }
                case 2:                                        // БАЛКОН: полка у стены на высоте 2
                {
                    if (h < 4) break;
                    bool left = rng.Next(2) == 0;
                    int lw = 2 + rng.Next(Mathf.Max(1, w - 3));
                    for (int k = 0; k < lw; k++) put(rFloor - 2, rm.col0 + (left ? k : w - 1 - k));
                    break;
                }
                case 3:                                        // ЗУБЦЫ: два выступа с зазором
                {
                    if (w < 5) break;
                    int off = 1 + rng.Next(Mathf.Max(1, w - 4));
                    put(rFloor, rm.col0 + off);
                    put(rFloor, rm.col0 + Mathf.Min(w - 2, off + 2));
                    break;
                }
                case 4:                                        // СТАЛАКТИТ: свисает с потолка, не холд
                {
                    if (h < 4) break;
                    int sw = 1 + rng.Next(2), off = 1 + rng.Next(Mathf.Max(1, w - sw - 1));
                    for (int k = 0; k < sw; k++) put(rm.row0, rm.col0 + off + k);
                    break;
                }
                default:                                       // ЛЕСЕНКА: две ступени вразнобой
                {
                    if (w < 4 || h < 4) break;
                    int off = 1 + rng.Next(Mathf.Max(1, w - 3));
                    put(rFloor,     rm.col0 + off);
                    put(rFloor - 2, rm.col0 + Mathf.Min(w - 1, off + 2));
                    break;
                }
            }
            if (placed.Count == 0) continue;
            int openAfter = openAir();
            if (openAfter < openBefore - placed.Count)
                foreach (var p in placed) g[p.y, p.x] = '.';    // узор запечатал карман — откатываем
            else openBefore = openAfter;
        }
    }

    /// <summary>Монеты: дорожка-приманка по комнатам. Кладём только в чистый воздух над полом.</summary>
    private static void DropCoins(char[,] g, int rows, int cols, MazeCanvas.RoomRect[] rects,
                                  int budget, System.Random rng)
    {
        int left = budget;
        foreach (var rm in rects)
        {
            if (left <= 0) break;
            if (rm.w == 0) continue;
            int air = rm.row0 + rm.h - 1;
            int want = 2 + rng.Next(3);
            for (int dy = 0; dy < 2 && want > 0 && left > 0; dy++)
            for (int k = 0; k < rm.w && want > 0 && left > 0; k++)
            {
                int r = air - dy, c = rm.col0 + k;
                if (r < 0 || r >= rows || c < 0 || c >= cols) continue;
                if (g[r, c] != '.') continue;
                if (g[r + 1, c] == '#' || dy > 0)               // над полом либо на клетку выше
                {
                    // ⚠️ Не занимаем зазор ключа: спрайт ключа шире своей клетки.
                    if (c > 0 && g[r, c - 1] == '*') continue;
                    if (c + 1 < cols && g[r, c + 1] == '*') continue;
                    g[r, c] = '$'; want--; left--;
                }
            }
        }
    }

    /// <summary>Клетка воздуха над полом комнаты, куда можно поставить объект (кнопку, ключ, флаг).</summary>
    /// <param name="preferCol">К какому столбцу тянуться (−1 — к середине комнаты). Нужно кнопке
    /// двери: она обязана стоять У СВОЕЙ двери, иначе игрок ищет её по всей комнате (поймано игроком
    /// на скриншоте: «кнопка от двери далековато от самой двери»).</param>
    /// <param name="avoidCols">Столбцы, где игрок КАРАБКАЕТСЯ (люки и подходы к ним). Кнопку туда
    /// ставить нельзя: она занимает ровно ту клетку, за которую он тянется.
    /// 🐞 Поймано игроком на скриншоте: «вот тут игрок не сможет залезть, помешает кнопка».
    /// ⚠️ Модель этого НЕ ловит: для неё клетка кнопки — воздух, и проходимость не меняется. Значит
    /// правило должно жить здесь, в размещении, а не в приёмке.</param>
    private static int FloorSpot(char[,] g, MazeCanvas.RoomRect r, int rows, int cols,
                                 int preferCol = -1, HashSet<int> avoidCols = null)
    {
        int air = r.row0 + r.h - 1, floor = r.row0 + r.h;
        int anchor = preferCol >= 0 ? Mathf.Clamp(preferCol - r.col0, 0, r.w - 1) : r.w / 2;
        // Два прохода: сперва в обход столбцов подъёма, потом — как получится (лучше кнопка
        // в неудобном месте, чем механизм без кнопки вовсе).
        for (int pass = 0; pass < 2; pass++)
        for (int d = 0; d < r.w; d++)
        {
            int off = anchor + (d % 2 == 0 ? d / 2 : -(d / 2 + 1));
            if (off < 0 || off >= r.w) continue;
            int c = r.col0 + off;
            if (air < 0 || air >= rows || floor >= rows || c < 0 || c >= cols) continue;
            if (pass == 0 && !SkipButtonAvoid && avoidCols != null && avoidCols.Contains(c)) continue;
            if (g[air, c] == '.' && g[floor, c] == '#') return c;
        }
        return -1;
    }

    /// <summary>
    /// ⭐⭐ МЕСТО ПОД КНОПКУ В ЛЮБОЙ ПЛОСКОСТИ: пол, потолок или боковая стена.
    ///
    /// 🐞 Кнопку умели сажать ТОЛЬКО на пол (<see cref="FloorSpot"/>), и когда пола не находилось,
    /// механизм просто не ставился. На клапанах возврата это стоило трёх замыканий из одиннадцати
    /// попыток — отказ «возврат: негде кнопка».
    /// Игрок: «кнопки теперь также должны уметь располагаться в любой плоскости».
    /// ⚠️ Пол пробуем первым: на него игрок встаёт, и это самое удобное место. Потолок и стены —
    /// когда пола нет. Рисовать все четыре ориентации редактор уже умеет (см. MountSide).
    /// </summary>
    private static bool MountSpot(char[,] g, MazeCanvas.RoomRect r, int rows, int cols,
                                  int preferCol, HashSet<int> avoidCols,
                                  out Vector2Int cell, out MountSide mount)
    {
        cell = new Vector2Int(-1, -1); mount = MountSide.Floor;
        int col = FloorSpot(g, r, rows, cols, preferCol, avoidCols);
        if (col >= 0) { cell = new Vector2Int(col, r.row0 + r.h - 1); return true; }

        int anchor = preferCol >= 0 ? Mathf.Clamp(preferCol - r.col0, 0, r.w - 1) : r.w / 2;
        for (int d = 0; d < r.w; d++)
        {
            int off = anchor + (d % 2 == 0 ? d / 2 : -(d / 2 + 1));
            if (off < 0 || off >= r.w) continue;
            int c = r.col0 + off;
            if (c < 0 || c >= cols) continue;
            for (int row = r.row0; row < r.row0 + r.h; row++)
            {
                if (row < 0 || row >= rows || g[row, c] != '.') continue;
                if (row - 1 >= 0 && g[row - 1, c] == '#')
                { cell = new Vector2Int(c, row); mount = MountSide.Ceiling; return true; }
                if (c - 1 >= 0 && g[row, c - 1] == '#')
                { cell = new Vector2Int(c, row); mount = MountSide.WallLeft; return true; }
                if (c + 1 < cols && g[row, c + 1] == '#')
                { cell = new Vector2Int(c, row); mount = MountSide.WallRight; return true; }
            }
        }
        return false;
    }

    /// <summary>Столбцы, в которых игрок лезет через люк, — по одному набору на комнату.
    /// Берём проём люка с запасом в клетку: за его край и цепляются.</summary>
    private static Dictionary<int, HashSet<int>> ClimbCols(List<RoomLayout.RoomLink> links, int roomCount)
    {
        var map = new Dictionary<int, HashSet<int>>();
        System.Action<int, int> add = (room, col) =>
        {
            HashSet<int> set;
            if (!map.TryGetValue(room, out set)) { set = new HashSet<int>(); map[room] = set; }
            set.Add(col);
        };
        foreach (var l in links)
        {
            if (!l.vertical) continue;
            // Берём ФАКТИЧЕСКИЙ люк (2-3 клетки), а не весь общий отрезок стены.
            int from = l.cutFrom >= 0 ? l.cutFrom : l.from;
            int to   = l.cutTo   >= 0 ? l.cutTo   : l.to;
            for (int x = from - 1; x <= to + 1; x++) { add(l.a, x); add(l.b, x); }
        }
        return map;
    }

    /// <summary>
    /// ⭐ ОБСТАВИТЬ УРОВЕНЬ: спавн, финиш, ключи, чекпоинты — и вызвать модули на тех рёбрах, которым
    /// рецепт назначил элемент. Это то, что превращает пустую геометрию в уровень.
    ///
    /// ⚠️ Порядок важен: сперва объекты, потом механизмы. Вылазке нужен ключ уже лежащим в её камере,
    /// а модули могут занять клетки, куда объект потом не встанет.
    /// </summary>
    /// <returns>Плоскость НОМЕРОВ ГРУПП по клеткам (−1 — ничья). Уходит дальше в Built и BuildSpec:
    /// личность плитки живёт в ней, а не в букве сетки.</returns>
    private static int[,] Furnish(char[,] g, int rows, int cols, List<Node> nodes,
                                  MazeCanvas.RoomRect[] rects, List<RoomLayout.RoomLink> links,
                                  System.Random rng, List<ModuleStamp> stamps, System.Text.StringBuilder story,
                                  List<RoomLayout.RoomLink> loopLinks = null)
    {
        // ⚠️ Уступы зала — ДО объектов: объект должен встать на готовый пол, а не быть замурован.
        HallLedges(g, rows, cols, rects, rng);
        PlaceObjects(g, rows, cols, nodes, rects);
        return FurnishLinks(g, rows, cols, nodes, rects, links, rng, stamps, story, loopLinks);
    }

    /// <summary>
    /// ⭐ СПАВН, ФИНИШ, ТРИ КЛЮЧА И ЧЕКПОИНТ. Зависит ТОЛЬКО от прямоугольников комнат и дерева,
    /// поэтому одинаково годится и решётчатой раскладке, и раскладке расталкиванием.
    /// </summary>
    public static void PlaceObjects(char[,] g, int rows, int cols, List<Node> nodes,
                                    MazeCanvas.RoomRect[] rects)
    {
        // ── Спавн в стартовой комнате, финиш в КОНЦЕ основного маршрута (см. Node.isFinish) ──
        int lastMain = 0;
        foreach (var nd in nodes) if (nd.isFinish) lastMain = nd.id;
        if (lastMain == 0) foreach (var nd in nodes) if (nd.onMainPath) lastMain = nd.id;
        System.Action<int, char> put = (id, ch) =>
        {
            int c = FloorSpot(g, rects[id], rows, cols);
            if (c >= 0) g[rects[id].row0 + rects[id].h - 1, c] = ch;
        };
        put(0, '@');
        put(lastMain, '^');

        // ── КЛЮЧИ: РОВНО ТРИ, как требует прогрессия (артефакты собираются в картинку-мир) ──
        // 🐞 Сперва ключ клался только в конец ветки — и уровень, где рецепт не дал ни одной ветки,
        // выходил ВООБЩЕ БЕЗ КЛЮЧЕЙ. Концы веток остаются лучшими местами (за ключом надо сходить),
        // но добираем из комнат маршрута, начиная с дальних от спавна.
        // 🐞 Сперва я добирал ключи «с конца списка узлов» — а последними в дерево добавляются узлы
        // ОДНОЙ И ТОЙ ЖЕ ветки, и все три ключа ложились в один тупик (поймано игроком). Теперь
        // разносим: каждый следующий ключ обязан быть подальше по дереву от уже поставленных.
        System.Func<int, int, int> treeDist = (x, y) =>
        {
            var upX = new List<int>(); int cur = x;
            for (int g = 0; g < 64 && cur >= 0; g++) { upX.Add(cur); cur = nodes[cur].parent; }
            cur = y;
            for (int d = 0; d < 64 && cur >= 0; d++)
            { int i2 = upX.IndexOf(cur); if (i2 >= 0) return i2 + d; cur = nodes[cur].parent; }
            return 99;
        };
        // ⚠️ КАМЕРА ПРИНОСИТ СВОЙ КЛЮЧ. Он лежит в её кармане и кладётся модулем, поэтому обычных
        // ключей нужно на столько же меньше. 🐞 Иначе на уровне их становится четыре при трёх
        // положенных прогрессией (артефакты собираются в картинку-мир, лишний ломает счёт).
        int vaultKeys = 0;
        foreach (var nd in nodes) if (nd.element == PuzzleElement.Vault) vaultKeys++;
        int wantKeys = Mathf.Max(0, 3 - vaultKeys);

        var keySpots = new List<int>();
        foreach (var nd in nodes) if (nd.holdsKey) keySpots.Add(nd.id);
        while (keySpots.Count > wantKeys) keySpots.RemoveAt(keySpots.Count - 1);
        // Кандидаты по убыванию удалённости от спавна: за дальним ключом идти интереснее.
        var cand = new List<int>();
        for (int i = 1; i < nodes.Count; i++) if (i != lastMain && !keySpots.Contains(i)) cand.Add(i);
        cand.Sort((x, y) => treeDist(0, y).CompareTo(treeDist(0, x)));
        for (int minGap = 3; minGap >= 0 && keySpots.Count < wantKeys; minGap--)
            foreach (int id in cand)
            {
                if (keySpots.Count >= wantKeys) break;
                if (keySpots.Contains(id)) continue;
                bool farEnough = true;
                foreach (int k in keySpots) if (treeDist(id, k) < minGap) { farEnough = false; break; }
                if (farEnough) keySpots.Add(id);
            }
        foreach (int id in keySpots) put(id, '*');

        // ⭐⭐ ЧЕКПОИНТ ПОСЛЕ КАЖДОГО КЛЮЧА (правило игрока). Дорога к ключу — это РИСК, и наградой за
        // него служит связка «ключ + чекпоинт»: пройденный опасный участок больше не переигрывается.
        //
        // Почему именно ПОСЛЕ, а не перед. Проверка по коду игры: сорваться игрок может почти всегда
        // (разрыв доводится до Fail принудительно), оживление возвращает на самый высокий пройденный
        // чекпоинт и СОХРАНЯЕТ ключи и время. Значит цена застревания — это откат до последнего
        // чекпоинта, и ставить его надо там, где риск уже позади, а добыча уже в руках.
        // ⚠️ Ставим на шаг В СТОРОНУ РОДИТЕЛЯ: это и есть «сразу после того, как ключ забрали», по
        // дороге обратно к маршруту. В самой комнате с ключом нельзя — там уже лежит '*'.
        var cpAt = new HashSet<int>();
        foreach (int keyId in keySpots)
        {
            int back = nodes[keyId].parent;
            if (back < 0) continue;
            if (cpAt.Contains(back)) continue;
            cpAt.Add(back); put(back, '=');
        }
        // Плюс один посреди основного пути: прогресс должен фиксироваться и без веток.
        var mainIds = new List<int>();
        foreach (var nd in nodes) if (nd.onMainPath && !cpAt.Contains(nd.id)) mainIds.Add(nd.id);
        if (mainIds.Count >= 4) put(mainIds[mainIds.Count / 2], '=');
    }

    /// <summary>
    /// ⭐ УСТУПЫ В ЗАЛЕ. Зал выше дотяжки, и без опор он непроходим — это ровно то, чем ручные уровни
    /// игрока набирают объём: большое открытое пространство, размеченное площадками вразнобой.
    ///
    /// ⚠️⚠️ ОТСЧЁТ ОТ РЯДА КАМНЯ, А НЕ ВОЗДУХА. Холд — это камень, НАД которым воздух; пол зала как
    /// опора лежит на ряд ниже его нижнего ряда воздуха. Ошибка на единицу даёт 4 ряда между опорами
    /// при подъёме 3, и зал становится непроходим целиком (обжёгся на этом в коридорной ветке).
    /// ⚠️ Площадки УЗКИЕ и жмутся к стенам поочерёдно: во всю ширину они запечатывают зал.
    /// </summary>
    public static void HallLedges(char[,] g, int rows, int cols, MazeCanvas.RoomRect[] rects,
                                  System.Random rng)
    {
        foreach (var rm in rects)
        {
            if (rm.w == 0 || rm.h <= RoomLayout.MaxRoomHeight) continue;
            int top = rm.row0, floorRow = rm.row0 + rm.h;        // ряд КАМНЯ под залом
            // ⚠️⚠️ ШАГ ВБОК ОГРАНИЧЕН ДОТЯЖКОЙ, А НЕ ШИРИНОЙ ЗАЛА.
            // 🐞 Сперва площадки просто чередовались у противоположных стен — в зале шириной 8 это
            // скачок вбок на 6 при подъёме 3, а дотяжка ограничена ещё и СУММОЙ (≤ ReachSumCells = 7).
            // Замер был однозначным: финиш достижим 2 уровня из 5 вместо 5, ключи 6 из 15 вместо 15.
            // Теперь это лестница: каждая следующая площадка в паре клеток от предыдущей.
            int maxStep = Mathf.Max(1, LevelModel.ReachSumCells - MazeCanvas.Climb - 1);
            int cx = rm.col0 + rng.Next(Mathf.Max(1, rm.w - 2));
            int stepDir = rng.Next(2) == 0 ? 1 : -1;
            // ⚠️⚠️ ЛЕСТНИЦА ПРИВЯЗАНА К ПОТОЛКУ, А НЕ К ПОЛУ.
            // 🐞 Считая от пола, я получал верхнюю площадку в ЧЕТЫРЁХ рядах от потолка при подъёме 3 —
            // и люк в потолке зала становился недосягаем, то есть зал резал уровень надвое. Замер:
            // финиш 2 уровня из 5, ключи 7 из 15. От потолка низ сходится сам собой: последний
            // промежуток до пола выходит ≤ Climb при любой высоте зала.
            for (int r = top + MazeCanvas.Climb - 1; r < floorRow; r += MazeCanvas.Climb)
            {
                int lw = Mathf.Clamp(2, 1, rm.w - 2);
                cx += stepDir * (1 + rng.Next(maxStep));
                if (cx < rm.col0) { cx = rm.col0; stepDir = 1; }
                if (cx > rm.col0 + rm.w - 1 - lw) { cx = rm.col0 + rm.w - 1 - lw; stepDir = -1; }
                for (int k = 0; k < lw; k++)
                {
                    int c = cx + k;
                    if (r >= 0 && r < rows && c >= 0 && c < cols && g[r, c] == '.') g[r, c] = '#';
                }
            }
        }
    }

    /// <summary>Ступени в связях и модули механизмов — это уже про КОНКРЕТНУЮ модель связи
    /// (дыра в общей стене), поэтому живёт отдельно от расстановки объектов.</summary>
    private static int[,] FurnishLinks(char[,] g, int rows, int cols, List<Node> nodes,
                                     MazeCanvas.RoomRect[] rects, List<RoomLayout.RoomLink> links,
                                     System.Random rng, List<ModuleStamp> stamps,
                                     System.Text.StringBuilder story,
                                     List<RoomLayout.RoomLink> loopLinks = null)
    {
        int lastMain = 0;
        foreach (var nd in nodes) if (nd.isFinish) lastMain = nd.id;
        if (lastMain == 0) foreach (var nd in nodes) if (nd.onMainPath) lastMain = nd.id;

        // ── КАМЕННАЯ СТУПЕНЬКА В КАЖДОЙ ВЕРТИКАЛЬНОЙ СВЯЗИ ──────────────────────────────────────
        // 🐞 Без неё первый же сквозной прогон дал 100% брака: люк прорезан, а лезть к нему не по чему —
        // подъём с пола нижней комнаты до её потолка это H+1 рядов, вчетверо больше дотяжки. На решётке
        // такую ступеньку клал сам рендер, и при переносе она потерялась.
        // ⚠️ Высота выстрадана: ступенька на Climb рядов над полом, тогда ОБА участка (пол→ступенька и
        // ступенька→потолок) укладываются в дотяжку при H ≤ Climb+2.
        var stepRowOf = new Dictionary<int, int>();               // ребёнок → ряд ступеньки
        foreach (var l in links)
        {
            if (!l.vertical) continue;
            // Ниже та комната, у которой ряд больше (сетка растёт вниз).
            int lower = rects[l.a].row0 > rects[l.b].row0 ? l.a : l.b;
            // ⚠️ ВЫСОТА ПОДЪЁМА ПОДСТРАИВАЕТСЯ ПОД КОМНАТУ. 🐞 Жёсткие 3 ряда в комнате высотой 3
            // ставили ступеньку прямо в потолок, и такая связь оставалась непроходимой вовсе —
            // на решётке подъём считался как min(Climb, H−1) ровно поэтому.
            int climb = Mathf.Min(MazeCanvas.Climb, rects[lower].h - 1);
            if (climb < 2) continue;                              // совсем низкая — долезут и так
            int stepRow = rects[lower].row0 + rects[lower].h - climb;
            if (stepRow <= rects[lower].row0) continue;
            // ⚠️⚠️ УСТУП НЕ ВО ВСЮ ШИРИНУ КОМНАТЫ. 🐞 Класть его на весь общий отрезок нельзя: в узкой
            // комнате он становится СПЛОШНЫМ ПЕРЕКРЫТИЕМ и запечатывает её — игрок стоит на полу, а
            // выше не пройти. Ровно эта ошибка уже была на решётке («ступенька во всю ширину
            // запечатывает комнату», 25 схем из 40 с глухими карманами), и при переносе я повторил её:
            // люк сузил, а уступ — нет. Оставляем свободной хотя бы одну колонку комнаты.
            int span = l.to - l.from + 1;
            int lw = Mathf.Min(span, 2 + rng.Next(2));
            lw = Mathf.Min(lw, Mathf.Max(1, rects[lower].w - 1));
            int loff = span > lw ? rng.Next(span - lw + 1) : 0;
            for (int x = l.from + loff; x < l.from + loff + lw; x++)
                if (stepRow >= 0 && stepRow < rows && x >= 0 && x < cols) g[stepRow, x] = '#';
            int child = nodes[l.b].parent == l.a ? l.b : l.a;
            stepRowOf[child] = stepRow;
        }

        // ── Модули на назначенных рёбрах ──
        var canvas = new MazeCanvas(g, rows, cols, rects,
                                    new bool[rows, cols], new bool[rows, cols], new bool[rows, cols], rng);
        var linkOf = new Dictionary<int, RoomLayout.RoomLink>();
        foreach (var l in links)
        {
            // Связь помним по РЕБЁНКУ: у него и записан элемент рецепта.
            if (l.extra) continue;                            // лишнее ребро — механизма на нём нет
            int child = nodes[l.b].parent == l.a ? l.b : l.a;
            linkOf[child] = l;
        }

        // ── ВЛОЖЕННЫЙ ТРИГГЕР: КТО КОМУ ХОЗЯИН ──────────────────────────────────────────────────
        // 🐞 До этого `NestedGate` разбирался тем же case, что и обычные ворота, и строил ровно их:
        // замер дал 0 вложенных кнопок на 55 механизмов при 20 заказанных. Рецепт при этом честно
        // начислял за вложенность 5 баллов — то есть сложность врала, а игрок видел одни и те же
        // ворота (63 из 92 построенных). Хозяин — БЛИЖАЙШИЙ ПРЕДОК С МЕХАНИЗМОМ: только он гарантированно
        // открывается раньше по маршруту, иначе вложенная кнопка оказывается заперта навсегда.
        var hostOf = new Dictionary<int, int>();                  // вложенный узел → узел-хозяин
        var needsShelf = new HashSet<int>();
        foreach (var nd in nodes)
        {
            if (nd.element != PuzzleElement.NestedGate) continue;
            int a = HostForNested(nodes, nd.id);
            if (a < 0) continue;
            hostOf[nd.id] = a; needsShelf.Add(a);
        }
        var stampOf = new Dictionary<int, ModuleStamp>();
        var climbCols = ClimbCols(links, nodes.Count);

        foreach (var nd in nodes)
        {
            if (nd.element == null || nd.parent < 0) continue;
            RoomLayout.RoomLink link;
            if (!linkOf.TryGetValue(nd.id, out link)) continue;
            canvas.SetNextGroupIndex(stamps.Count);

            var site = new MazeSite
            {
                room = new Vector2Int(nd.parent, 0), roomAbove = new Vector2Int(nd.id, 0),
                roomId = nd.parent, roomAboveId = nd.id,
                onRoute = nd.onMainPath, hasFloorBelow = false, throughCorridor = true,
                buttonBelow = new Vector2Int(-1, -1), buttonAbove = new Vector2Int(-1, -1)
            };
            // Кнопки: по одной на каждой стороне ребра, на полу своей комнаты.
            HashSet<int> avoidP, avoidC;
            climbCols.TryGetValue(nd.parent, out avoidP);
            climbCols.TryGetValue(nd.id, out avoidC);
            int cb = FloorSpot(g, rects[nd.parent], rows, cols, -1, avoidP);
            int ca = FloorSpot(g, rects[nd.id], rows, cols, -1, avoidC);
            if (cb < 0 || ca < 0) { story.Append("нет места под кнопки у ").Append(nd.id).Append("; "); continue; }
            site.buttonBelow = new Vector2Int(cb, rects[nd.parent].row0 + rects[nd.parent].h - 1);
            site.buttonAbove = new Vector2Int(ca, rects[nd.id].row0 + rects[nd.id].h - 1);

            ModuleStamp st = null;
            // ⭐⭐ РЕБРО ВЫШЛО НЕ ТОГО НАПРАВЛЕНИЯ — МЕНЯЕМ МЕХАНИЗМ, А НЕ ТЕРЯЕМ ЕГО.
            // Направление заказывается раскладке заранее, но заказы конфликтуют: мост требует
            // горизонтали ОБОИМ своим рёбрам, и если на одном из них уже стоят ворота, чей-то заказ
            // обязан уступить. Раньше уступивший механизм просто не строился.
            // 🐞 Замер на 25 уровнях: так терялись трое — одни ворота на горизонтальном ребре и две
            // двери на вертикальном. Замена бесплатна: ворота на боковом ребре бессмысленны, а дверь
            // там ровно к месту, и наоборот.
            var element = nd.element.Value;
            if (link.vertical && element == PuzzleElement.Door)
            { element = PuzzleElement.Gate; story.Append("дверь ").Append(nd.id).Append(" → ворота (ребро вертикальное); "); }
            else if (!link.vertical && (element == PuzzleElement.Gate || element == PuzzleElement.NestedGate))
            { element = PuzzleElement.Door; story.Append("ворота ").Append(nd.id).Append(" → дверь (ребро боковое); "); }
            // ⭐ МОСТУ НЕ ДОСТАЛСЯ СКВОЗНОЙ КОРИДОР — СТАВИМ ТО, ЧТО ЗДЕСЬ УМЕСТНО.
            // Коридор мост заказывает заранее, но когда этап не встаёт, раскладка снимает требование
            // направления, чтобы не уронить весь уровень (см. «послабление» в BuildStaged). При
            // многих механизмах этапы срываются часто, и мост оставался ни с чем.
            // 🐞 Замер на заказе в 36 групп: из 108 заказанных элементов построено 68, и двадцать
            // потерь — мост, причём у ВСЕХ десяти проверенных комната имела ровно две связи, одну
            // горизонтальную и одну вертикальную. То есть коридор не «занят», а просто не выдан.
            if (element == PuzzleElement.Bridge)
            {
                int horB = 0, vertB = 0;
                foreach (var l2 in links)
                {
                    if (l2.a != nd.parent && l2.b != nd.parent) continue;
                    if (l2.vertical) vertB++; else horB++;
                }
                if (vertB > 0 || horB != 2)
                {
                    element = link.vertical ? PuzzleElement.Gate : PuzzleElement.Door;
                    story.Append("мост ").Append(nd.id).Append(" → ")
                         .Append(link.vertical ? "ворота" : "дверь").Append(" (коридор не сквозной); ");
                }
            }
            switch (element)
            {
                case PuzzleElement.Gate:
                case PuzzleElement.NestedGate:
                    if (!link.vertical) break;
                    // Внизу тот, у кого пол ниже: подъём всегда снизу вверх.
                    bool parentBelow = rects[nd.parent].row0 > rects[nd.id].row0;
                    site.roomId = parentBelow ? nd.parent : nd.id;
                    site.roomAboveId = parentBelow ? nd.id : nd.parent;
                    site.shaftCol0 = link.from; site.shaftWidth = link.to - link.from + 1;
                    // Каменную ступеньку этой связи модуль уберёт: её место займёт его зигзаг.
                    int sr; site.shaftStepRow = stepRowOf.TryGetValue(nd.id, out sr) ? sr : -1;
                    // ⭐ Замком ворота работают только когда игрок приходит СНИЗУ: при родителе сверху
                    // это «дорога обратно», и запирать ею нечего. Обход считаем именно для замка —
                    // и обязательно ПОСЛЕ того, как известна шахта: иначе в расчёт попадёт ступенька,
                    // которую ворота как раз и сносят.
                    // Обходятся — не ставим. ⚠️ Проверено замером, что это НЕ ложное срабатывание:
                    // если такие ворота всё-таки построить, приёмка тут же метит их холостыми
                    // (сиды 3009 и 4014 из чистых становились браком).
                    if (parentBelow && GateBypassed(g, canvas.Grp, rows, cols, nodes, rects, stamps, nd.id,
                                                    site.shaftStepRow, site.shaftCol0, site.shaftWidth))
                    // ⚠️ continue, а не break: после break сработало бы ещё и «не встал», и один
                    // отказ печатался ДВАЖДЫ — на этом я сам сбился, разбирая потери.
                    { story.Append("ворота ").Append(nd.parent).Append("->").Append(nd.id)
                           .Append(" обходятся по геометрии — не ставлю; "); StatGateBypass++; continue; }
                    // 🐞 ОБМЕН БЕЗ ВРЕМЕННОЙ: было две строки подряд, и вторая брала УЖЕ ПЕРЕЗАПИСАННОЕ
                    // значение — при родителе сверху обе кнопки схлопывались в одну и ту же клетку,
                    // то есть ворота оставались без кнопки «открыть» внизу.
                    if (!parentBelow)
                    {
                        var swap = site.buttonBelow;
                        site.buttonBelow = site.buttonAbove;
                        site.buttonAbove = swap;
                    }
                    // Этому механизму предстоит принять чужую кнопку — просим у него полку.
                    site.wantButtonShelf = needsShelf.Contains(nd.id);
                    // ⚠️ Кнопка «открыть» садится НА ПОЛКУ ХОЗЯИНА: чтобы до неё дотянуться, придётся
                    // сперва открыть хозяина. Это и есть вложенность — иерархия, а не соседство.
                    int hostId; ModuleStamp hostSt = null;
                    if (hostOf.TryGetValue(nd.id, out hostId) && stampOf.TryGetValue(hostId, out hostSt)
                        && hostSt.shelfCell.x >= 0)
                        site.buttonBelow = hostSt.shelfCell;
                    else hostSt = null;                            // полки не вышло — строим обычные ворота
                    st = new VerticalGateModule().Stamp(canvas, site);
                    if (st != null && hostSt != null)
                        for (int i = 0; i < st.buttons.Count; i++)
                            if (st.buttons[i] == site.buttonBelow) st.buttonHosts[i] = hostSt.groupIx;
                    break;
                case PuzzleElement.Door:
                    if (link.vertical) break;
                    site.doorCol = link.wall;
                    site.doorRowTop = link.from; site.doorHeight = link.to - link.from + 1;
                    // Проём режется от пола вверх — берём только вырезанную часть столбца.
                    // ⛔ ПРОВЕРЕНО И ОТВЕРГНУТО: я думал, что отсчёт надо вести от низа СВЯЗИ, а не от
                    // нижнего ряда комнаты — полы соседей ведь не обязаны совпадать (MaxFloorStep), и
                    // казалось, что при перепаде отсчёт начинается в камне. Замер с переключателем:
                    // оба варианта дают ровно одно и то же (дверей потеряно 4, клапанов 2, механизмов
                    // 3.86). Гипотеза неверна, причина потери дверей НЕ ЗДЕСЬ.
                    int top = link.from, hgt = 0;
                    for (int r = rects[nd.id].row0 + rects[nd.id].h - 1; r >= 0 && g[r, link.wall] == '.'; r--)
                    { top = r; hgt++; }
                    if (hgt < 2) break;
                    site.doorRowTop = top; site.doorHeight = hgt;
                    // ⭐ Роль ВЫХОДА: кнопка только со стороны ЗАПЕРТОЙ области.
                    // ⚠️⚠️ Запертая область — это комната РОДИТЕЛЯ (сама камера), а узел-выход стоит
                    // ЗА дверью. buttonBelow считается по родителю, buttonAbove — по узлу, значит
                    // «внутри» = buttonBelow.
                    // 🐞 Я написал наоборот, и кнопка уехала за дверь — в комнату, куда без этой же
                    // двери и не попасть. Группа выхода получалась МЁРТВОЙ, игрок оставался в камере
                    // с ключом навсегда, и уровень становился непроходимым, хотя каждая цель по
                    // отдельности была достижима (поймано моделью, критерием «одно прохождение»).
                    // Тот же вопрос, что и у ворот, только зеркально: если за ЗАКРЫТУЮ дверь всё равно
                    // попадают, дверь декоративна. ⚠️ Выход из камеры (exitOnly) не проверяем: он
                    // выпускает игрока наружу, а не запирает вход, и «обход» для него бессмыслен.
                    if (!nd.isExit && GateBypassed(g, canvas.Grp, rows, cols, nodes, rects, stamps, nd.id,
                                                   -1, 0, 0, site.doorCol, site.doorRowTop, site.doorHeight))
                    { story.Append("дверь ").Append(nd.parent).Append("->").Append(nd.id)
                           .Append(" обходится по геометрии — не ставлю; "); StatGateBypass++; continue; }
                    site.exitOnly = nd.isExit;
                    site.insideIsBelow = true;                     // buttonBelow = комната родителя
                    st = new InvertedDoorModule().Stamp(canvas, site);
                    break;
                case PuzzleElement.Bridge:
                    // ⚠️ ПРОВЕРЯЕМ, а не декларируем: комната моста обязана быть проходной насквозь
                    // вбок — ровно два боковых прохода и ни одного вертикального. Иначе мост обходят
                    // и приёмка справедливо зовёт его декоративным.
                    int hor = 0, vert = 0;
                    foreach (var l2 in links)
                    {
                        if (l2.a != nd.parent && l2.b != nd.parent) continue;
                        if (l2.vertical) vert++; else hor++;
                    }
                    if (vert > 0 || hor != 2)
                    { story.Append("мост: комната ").Append(nd.parent).Append(" не сквозной коридор; "); break; }
                    // Тот же вопрос, что у ворот и двери: если за мост попадают в обход, он украшение.
                    // Провал в полу мост режет сам, значит в сетке его ещё нет — поправок не нужно.
                    // ⚠️ МОСТ ПРОВЕРЯТЬ ОБХОДОМ НЕЛЬЗЯ, и это выяснилось замером: провал в полу коридора
                    // мост вырезает САМ, при штампе, а проверка идёт до него — и видит ровный проход,
                    // объявляя обходом ровно то место, где мост и появится. Ложное срабатывание,
                    // а не находка (разбор: «(43,12)->(37,12) путь 7 клеток, все внутри комнат»).
                    site.roomId = nd.parent;
                    // ⭐ С КАКОЙ СТОРОНЫ ПРИХОДИТ ИГРОК. Комната моста — сквозной коридор с ровно
                    // двумя боковыми связями: одна к деду (оттуда приходят), вторая к nd.id (туда
                    // уходят). При одной кнопке (см. MazeCanvas.TwoSidedButtons) сторона решает всё:
                    // кнопка с неверной стороны оказывается ЗА пропастью, и мост не перейти вовсе.
                    {
                        int granny = nodes[nd.parent].parent;
                        site.entryOnLeft = granny >= 0 && rects[granny].w > 0
                            ? (rects[granny].col0 < rects[nd.parent].col0 ? 1 : 0)
                            : -1;
                    }
                    st = new TimedBridgeModule().Stamp(canvas, site);
                    break;
                case PuzzleElement.LootPit:
                case PuzzleElement.Vault:
                {
                    // ⚠️ ПРОВЕРЯЕМ СКВОЗНОСТЬ, а не декларируем — тот же урок, что с мостом: комната
                    // камеры обязана быть проходной насквозь вбок, иначе провал в её полу обходят по
                    // вертикальной связи, и весь пролёт становится украшением.
                    if (link.vertical) break;
                    int hor2 = 0, vert2 = 0;
                    foreach (var l3 in links)
                    {
                        if (l3.a != nd.id && l3.b != nd.id) continue;
                        // Связь с собственным подвалом не в счёт: это внутренность паттерна.
                        int other = l3.a == nd.id ? l3.b : l3.a;
                        if (other >= 0 && other < nodes.Count && nodes[other].isCellar) continue;
                        if (l3.vertical) vert2++; else hor2++;
                    }
                    if (vert2 > 0 || hor2 != 2)
                    { story.Append("камера: комната ").Append(nd.id).Append(" не сквозной коридор; "); break; }
                    // ⭐⭐ КАМЕРА ТЕПЕРЬ ТРАФАРЕТ, А НЕ МОДУЛЬ. Вся её геометрия — картинка в
                    // StencilLibrary; здесь остаётся только выбрать КОМНАТУ и позвать штамповщик.
                    // Сравнение цены: модулем это 150 строк кода и три ошибки в форме дерева подряд,
                    // трафаретом — семь строк картинки и две строки объявлений.
                    var stencil = StencilLibrary.For(nd.element.Value);
                    if (stencil == null) break;
                    // Комната камеры — её СОБСТВЕННАЯ: это коридор, а сама камера роется в толще
                    // под ним. Размер коридора заказан словарём ровно под картинку.
                    int chamber = nd.id;
                    Vector2Int keyCell;
                    // ⭐ С КАКОЙ СТОРОНЫ ИГРОК ПРИХОДИТ — это решает зеркало формы: у камеры пролог с
                    // кнопкой только с одной стороны, и войти с другой значит упереться в провал,
                    // кнопка которого за провалом (см. StencilStamper.Stamp, parentSide).
                    int side = rects[nd.parent].col0 <= rects[chamber].col0 ? 0 : 1;
                    var made = StencilStamper.Stamp(canvas, chamber, stencil, rng, out keyCell, side);
                    if (made == null) break;
                    // ⚠️ Ключ трафарет уже нарисовал в сетке — сюда он приходит только чтобы генератор
                    // знал, что артефакт этой ветки поставлен, и не клал второй.
                    foreach (var one in made) stamps.Add(one);
                    stampOf[nd.id] = made[0];
                    story.Append(PuzzleVocabulary.Name(nd.element.Value)).Append(" (трафарет) на ")
                         .Append(chamber).Append("; ");
                    continue;                                  // штампы уже добавлены
                }
                case PuzzleElement.Ladder:
                {
                    // ⭐ ЛЕСТНИЦА НА ТАЙМЕРЕ (группа D ручного Level_09) живёт внутри ОДНОЙ комнаты и
                    // от соседей не требует ничего: ни сквозного коридора, ни подвала. Поэтому и
                    // проверок здесь нет — только выбрать комнату и позвать штамповщик.
                    // ⚠️⚠️ ШТАМПУЕМ В РОДИТЕЛЯ — В НИЖНЮЮ КОМНАТУ. Ребро вертикальное, игрок приходит
                    // снизу, и подъём обязан стоять на его стороне люка.
                    // 🐞 Сперва я штамповал в комнату ребра (верхнюю), и ступени оказывались уже ЗА
                    // люком: непроходимыми становились 9 уровней из 10 при достижимом финише и
                    // собранных ключах. У работающих вертикальных ворот зигзаг строится ровно в
                    // нижней комнате (VerticalGateModule берёт s.roomId = родитель).
                    if (!link.vertical || nd.parent < 0) break;
                    var ladder = StencilLibrary.For(nd.element.Value);
                    if (ladder == null) break;
                    Vector2Int noKey;
                    var madeL = StencilStamper.Stamp(canvas, nd.parent, ladder, rng, out noKey, -1);
                    if (madeL == null) break;
                    foreach (var one in madeL) stamps.Add(one);
                    stampOf[nd.id] = madeL[0];
                    story.Append(PuzzleVocabulary.Name(nd.element.Value)).Append(" (трафарет) на ")
                         .Append(nd.parent).Append("; ");
                    continue;
                }
            }
            if (st == null) { story.Append("не встал ").Append(PuzzleVocabulary.Name(element))
                                   .Append(" на ").Append(nd.parent).Append("→").Append(nd.id).Append("; "); continue; }
            stampOf[nd.id] = st;
            st.edgeRooms = new Vector2Int(nd.parent, nd.id);
            stamps.Add(st);
        }

        // ── ⭐⭐ ДВЕРЬ НА РЕБРЕ ВОЗВРАТА ─────────────────────────────────────────────────────────
        // Замыкает ветку-петлю на основной маршрут. Кнопка ТОЛЬКО ИЗНУТРИ ветки: игрок, забравший
        // ключ, выходит на трассу, а войти этим путём с трассы нельзя — значит петля ничего не
        // обесценивает. Ровно «КНОПКА+ДВЕРЬ НА ОСНОВНОЙ МАРШРУТ» со схемы игрока.
        if (loopLinks != null)
        foreach (var ll in loopLinks)
        {
            // Изнутри — та сторона, что НЕ на основном маршруте.
            int inside = nodes[ll.a].onMainPath ? ll.b : ll.a;
            int outside = inside == ll.a ? ll.b : ll.a;
            canvas.SetNextGroupIndex(stamps.Count);
            // Кнопку ставим У САМОЙ ДВЕРИ: тянемся к столбцу проёма, а не к середине комнаты.
            HashSet<int> avoidIn, avoidOut;
            climbCols.TryGetValue(inside, out avoidIn);
            climbCols.TryGetValue(outside, out avoidOut);
            // ⚠️ У ВЕРТИКАЛЬНОЙ связи wall — это РЯД, и тянуть к нему кнопку по столбцу бессмысленно.
            // Тянемся к столбцу люка; у боковой связи всё как было.
            int nearCol = ll.vertical ? (ll.cutFrom >= 0 ? ll.cutFrom : ll.from) : ll.wall;
            int nearCol2 = ll.vertical ? (ll.cutTo >= 0 ? ll.cutTo : ll.to) : ll.wallEnd;
            // ⭐ Кнопка садится в ЛЮБУЮ плоскость: пола может не быть, а клапан нужен.
            Vector2Int cellIn, cellOut; MountSide mIn, mOut;
            if (!MountSpot(g, rects[inside], rows, cols, nearCol, avoidIn, out cellIn, out mIn)
             || !MountSpot(g, rects[outside], rows, cols, nearCol2, avoidOut, out cellOut, out mOut))
            { story.Append("возврат: негде кнопка; "); continue; }
            var site = new MazeSite
            {
                roomId = inside, roomAboveId = outside,
                buttonBelow = cellIn,  mountBelow = mIn,
                buttonAbove = cellOut, mountAbove = mOut,
                exitOnly = true, insideIsBelow = true      // «внутри» = buttonBelow = комната ветки
            };
            if (ll.vertical)
            {
                // ⭐ ЛЮК В ПОЛУ: у вертикальной связи wall — это ряд-стена, а прорезанные столбцы
                // лежат в cutFrom..cutTo (весь общий отрезок шире реально прорезанного).
                // ⚠️⚠️ КООРДИНАТА РАСКЛАДКИ, А НЕ РЯД СЕТКИ. У раскладки y растёт ВВЕРХ, у сетки
                // ряды идут ВНИЗ — рендер переводит через toRow, и здесь надо так же.
                // 🐞 Я взял ll.wall напрямую как ряд, и вертикальный клапан не встал НИ РАЗУ:
                // проверка смотрела в чужое место и честно сообщала «люк не прорезан».
                int wallRow = rows - 1 - ll.wall;
                int x0 = ll.cutFrom >= 0 ? ll.cutFrom : ll.from;
                int x1 = ll.cutTo   >= 0 ? ll.cutTo   : ll.to;
                while (x0 <= x1 && (wallRow < 0 || wallRow >= rows || g[wallRow, x0] != '.')) x0++;
                while (x1 >= x0 && (wallRow < 0 || wallRow >= rows || g[wallRow, x1] != '.')) x1--;
                if (x1 < x0) { story.Append("возврат: люк не прорезан; "); continue; }
                site.doorRow = wallRow; site.doorCol0 = x0; site.doorWidth = x1 - x0 + 1;
            }
            else
            {
                // Проём режем от пола вверх, как и обычной двери, — берём его фактическую высоту.
                site.doorCol = ll.wall;
                int top = ll.from, hgt = 0;
                for (int r = rects[inside].row0 + rects[inside].h - 1; r >= 0 && g[r, ll.wall] == '.'; r--)
                { top = r; hgt++; }
                if (hgt < 2) { story.Append("возврат: проём низкий; "); continue; }
                site.doorRowTop = top; site.doorHeight = hgt;
            }
            var stDoor = new InvertedDoorModule().Stamp(canvas, site);
            if (stDoor == null) { story.Append("возврат: дверь не встала; "); continue; }
            stDoor.returnValve = true;        // роль объявлена: приёмка не считает клапан холостым
            stamps.Add(stDoor);
            story.Append("возврат на маршрут ").Append(inside).Append("→").Append(outside).Append("; ");
        }
        return canvas.Grp;
    }

    /// <summary>Полный проход: рецепт → дерево → роли → раскладка → сетка. null, если не уложилось.</summary>
    /// <param name="extraEdgesPercent">Сколько рёбер СВЕРХ дерева открыть, в процентах от числа
    /// связей. Идея из статьи про генерацию подземелий (там 8-10%): уровень перестаёт быть деревом,
    /// появляются петли и обходные пути. ⚠️ Открываются только безопасные — см. проверку внутри.</param>
    public static Built Build(LevelRecipe recipe, System.Random rng, int wantRooms = 0,
                              int extraEdgesPercent = 10, int hallPercent = 0)
    {
        var nodes = BuildTree(recipe, rng, wantRooms);
        RoomLayout.RoomReq[] req; RoomLayout.LinkDir[] dir;
        Requirements(nodes, out req, out dir, rng, hallPercent);
        var parent = new int[nodes.Count];
        for (int i = 0; i < nodes.Count; i++) parent[i] = nodes[i].parent;

        // ⭐⭐ ПОЭТАПНАЯ УКЛАДКА: хребет → каждая ветка отдельно → добор. Не встал этап —
        // переигрывается только он (предложение игрока; прежняя укладка теряла всю попытку целиком).
        var stageOf = new int[nodes.Count];
        for (int i = 0; i < nodes.Count; i++) stageOf[i] = nodes[i].stage;
        var lay = RoomLayout.BuildStaged(nodes.Count, parent, req, dir, rng, stageOf);
        // ⚠️ Раскладка могла ПЕРЕВЕСИТЬ ветку на другую комнату — синхронизируем дерево с ней,
        // иначе связи, ключи и роли будут считаться по устаревшему родителю.
        if (lay != null)
            for (int i = 0; i < nodes.Count; i++) nodes[i].parent = parent[i];
        if (lay == null) return null;

        // ── ЛИШНИЕ РЁБРА: петли сверх дерева ────────────────────────────────────────────────────
        // ⚠️⚠️ ГЛАВНАЯ ОПАСНОСТЬ: лишний проход может ОБОЙТИ механизм, и тот станет декоративным —
        // приёмка его забракует, и вся затея выйдет в минус. Поэтому открываем только те рёбра, чей
        // путь ПО ДЕРЕВУ не пересекает ни одного замка: такая петля ничего не обходит, она просто
        // даёт второй способ пройти уже открытый участок.
        //
        // 🐞🐞 ЭТОГО НЕ ХВАТИЛО, И ИМЕННО ЭТО ДАВАЛО ХОЛОСТЫЕ ВОРОТА. Проверка смотрит на путь ПО
        // ДЕРЕВУ, а рёбра открываются ПО ОДНОМУ и каждое сверяется с деревом заново — то есть друг
        // друга они не видят. Два ребра, поодиночке безобидных, вместе замыкают крюк вокруг замка:
        // замер по 12 уровням дал шесть холостых ворот, и в обходном маршруте КАЖДОГО из четырёх с
        // обходом лежало лишнее ребро (одно из них — цепочка из трёх сразу, через полкарты).
        // Поэтому ниже к дешёвой проверке по дереву добавлена честная проверка ПО ГРАФУ: ребро
        // открывается только если после него КАЖДОЕ запертое ребро всё ещё остаётся единственным
        // путём в своё поддерево. Рёбра возврата в этот граф не входят — их дверь односторонняя.
        System.Func<int, int, bool> pathHasElement = (x, y) =>
        {
            var upX = new List<int>(); int cur = x;
            for (int g = 0; g < 64 && cur >= 0; g++) { upX.Add(cur); cur = nodes[cur].parent; }
            var branchY = new List<int>(); cur = y;
            int meet = -1;
            for (int d = 0; d < 64 && cur >= 0; d++)
            { if (upX.Contains(cur)) { meet = cur; break; } branchY.Add(cur); cur = nodes[cur].parent; }
            if (meet < 0) return true;                        // общий предок не нашёлся — не рискуем
            foreach (int id in branchY) if (nodes[id].element != null) return true;
            for (int i = 0; i < upX.Count && upX[i] != meet; i++)
                if (nodes[upX[i]].element != null) return true;
            return false;
        };
        var cands = RoomLayout.FindAdjacent(lay);

        // ── ⭐ ЕДИНАЯ ПРОВЕРКА ОБХОДА: ориентированный граф комнат ───────────────────────────────
        // Запертые рёбра берём из ПЛАНА, а не из построенного: механизм может ещё не встать, но
        // открывать под него обход заранее всё равно нельзя.
        var locked = new List<Vector2Int>();
        foreach (var nd in nodes)
            if (nd.element != null && nd.parent >= 0) locked.Add(new Vector2Int(nd.parent, nd.id));
        int rootRoom = 0;
        foreach (var nd in nodes) if (nd.parent < 0) { rootRoom = nd.id; break; }

        // ⚠️ РЕБРО ВОЗВРАТА ОДНОСТОРОННЕЕ, НО ОПАСНОЕ НАПРАВЛЕНИЕ У НЕГО — НАРУЖУ. Долгое время оно
        // считалось безобидным («снаружи дверь не открыть»), и проверку на нём не делали вовсе.
        // 🐞 Замер поймал обратное: все четыре обойдённых замка обходились ИМЕННО через возврат и ни
        // один — без него. Схема обхода одна и та же: игрок входит в ветку сбоку (лишним ребром или
        // просто по дереву), доходит до её конца и выходит дверью УЖЕ ЗА воротами. Дверь при этом
        // работает ровно как задумано — обесценивает не она, а то, куда она ведёт.
        System.Func<List<RoomLayout.RoomLink>, Vector2Int, bool> lockBypassed = (ls, e) =>
        {
            var adj = new Dictionary<int, List<int>>();
            System.Action<int, int> link = (x, y) =>
            { if (!adj.ContainsKey(x)) adj[x] = new List<int>(); adj[x].Add(y); };
            foreach (var l in ls)
            {
                if ((l.a == e.x && l.b == e.y) || (l.a == e.y && l.b == e.x)) continue;
                if (l.returnEdge && l.returnFrom >= 0)
                { link(l.returnFrom, l.returnFrom == l.a ? l.b : l.a); continue; }
                link(l.a, l.b); link(l.b, l.a);
            }
            var seen = new HashSet<int> { rootRoom };
            var q = new Queue<int>(); q.Enqueue(rootRoom);
            while (q.Count > 0)
            {
                int cur = q.Dequeue();
                if (cur == e.y) return true;
                List<int> ns; if (!adj.TryGetValue(cur, out ns)) continue;
                foreach (int o in ns) if (seen.Add(o)) q.Enqueue(o);
            }
            return false;
        };
        // 🐞 И ВТОРАЯ ПОЛОВИНА ТОЙ ЖЕ ОШИБКИ: рёбра открывались ПО ОДНОМУ и каждое сверялось с
        // ДЕРЕВОМ заново, то есть друг друга они не видели. Два ребра, поодиночке безобидных, вместе
        // замыкали крюк вокруг замка (в одном обходе их набралось три, через полкарты). Поэтому
        // кандидат добавляется в граф НАЧЕРНО и проверяется вместе со всем, что уже открыто.
        // ⭐⭐ РЕБРУ ВОЗВРАТА ДОЗВОЛЕН ОДИН ОБОЙДЁННЫЙ ЗАМОК, ЛИШНИМ РЁБРАМ — НИ ОДНОГО.
        //
        // Почему не поровну. Ветка отрывается от комнаты A и возвращается на трассу в комнату B
        // дальше по ходу — в этом весь замысел петли. Между A и B почти всегда стоит механизм
        // трассы, и ребро возврата его обходит: замер по 20 уровням дал 27 кандидатов, из них
        // с нулём замков между — ПЯТЬ, ровно с одним — ТРИНАДЦАТЬ. То есть строгий запрет режет
        // петли не по вине геометрии, а по самому их устройству.
        //
        // ⚠️ Обойдённый механизм — это ХОЛОСТАЯ группа, а холостые группы решением игрока
        // (2026-09-11) браком больше не считаются: «мне абсолютно не важно, в каком порядке эти
        // механизмы, главное просто чтобы они были». Значит для клапана это правило было строже,
        // чем сама приёмка. Один замок разрешаем, больше — нет: петля обязана оставаться коротким
        // витком рядом с точкой отрыва, а не срезать полмаршрута.
        // ⭐ ДВОЙКА ПОДОБРАНА ЗАМЕРОМ, И ОНА РАБОТАЕТ ТОЛЬКО В ПАРЕ С ГУСТОЙ ВЫБОРКОЙ.
        // 🐞 Сперва допуск 2 вышел ИНЕРТНЫМ (те же 25 клапанов, те же 15/20): кандидатов с двумя
        // замками между отрывом и целью до дела просто не доходило. Когда звену, тянущемуся к цели,
        // дали вчетверо больше бросков (RoomLayout, «гуще выборка»), пул кандидатов изменился —
        // их стало 44 вместо 36, но возвращаются они дальше по трассе. И тогда двойка окупилась:
        //   допуск 1: клапанов 24, чистых 16/20, поставка 20.55, зарублено 12;
        //   допуск 2: клапанов 26, чистых 18/20, поставка 20.70, зарублено 4, холостых 8.5%;
        //   допуск 3: то же самое, но холостых 9.2% — чистая переплата.
        // ⚠️ Две правки взаимные: порознь каждая почти ничего не даёт. Менять одну, не перемерив
        // другую, нельзя.
        const int ReturnEdgeSlack = 2;
        System.Func<RoomLayout.RoomLink, bool> tryOpen = c =>
        {
            lay.links.Add(c);
            if (SkipBypassCheck) return true;
            int allowed = c.returnEdge ? ReturnEdgeSlack : 0, bypassed = 0;
            foreach (var e in locked)
                if (lockBypassed(lay.links, e) && ++bypassed > allowed)
                { lay.links.RemoveAt(lay.links.Count - 1); return false; }
            return true;
        };

        // ⭐⭐ РЕБРО ВОЗВРАТА: замыкаем ветку-петлю на основной маршрут. Ветка ушла с трассы, прошла
        // виток, забрала ключ — и выходит обратно рядом с точкой отрыва, как на схеме игрока.
        var loopLinks = new List<RoomLayout.RoomLink>();
        {
            var onMainSet = new HashSet<int>();
            foreach (var nd in nodes) if (nd.onMainPath) onMainSet.Add(nd.id);
            foreach (var nd in nodes)
            {
                if (nd.returnTo < 0) continue;
                // ⭐⭐ ВЫХОД ИЩЕТСЯ ПО ВСЕЙ ВЕТКЕ, А НЕ ТОЛЬКО ОТ ПОСЛЕДНЕЙ КОМНАТЫ.
                // 🐞 Раньше ребро возврата пробовали открыть ровно из комнаты с ключом. Она стоит в
                // конце цепочки из десятка звеньев, и рядом с трассой оказывается редко: требование
                // «коснуться маршрута» (nextToAny) — пожелание, а не ультиматум, жёстким оно роняло
                // раскладку до 4 сборок из 40. Замер: меток петли 23, а до попытки открыть ребро
                // доходило ТРИ, и клапан вставал у двух.
                // ⚠️ Петле и не нужно замыкаться именно ключевой комнатой. Смысл — «игрок забрал ключ
                // и вышел на трассу, не возвращаясь тем же путём», а выйти он может из любого звена
                // ветки: до него он дойдёт изнутри, своим же путём назад. Поэтому перебираем ВСЮ
                // ветку от ключа к точке отрыва и берём первое звено, у которого выход нашёлся, —
                // чем глубже, тем короче обратный путь.
                var branch = new List<int>();
                for (int c5 = nd.id; c5 >= 0 && !onMainSet.Contains(c5); c5 = nodes[c5].parent) branch.Add(c5);
                bool closed = false;
                StatLoopMarks++; int candsHere = 0;
                foreach (int room in branch)
                {
                    for (int i = 0; i < cands.Count && !closed; i++)
                    {
                        var c = cands[i];
                        // ⛔ РАСШИРЯТЬ ЦЕЛЬ ДО «ЛЮБОЙ КОМНАТЫ ВНЕ ВЕТКИ» ПРОБОВАЛ — ИНЕРТНО (2026-09-11).
                        // Рассуждение верное: смысл петли — «вышел, не возвращаясь тем же путём», и
                        // для этого годится не только маршрут, до него игрок дойдёт дальше сам.
                        // Замер: кандидатов ровно столько же (16) и клапанов столько же (10) —
                        // у веток попросту не бывает годных соседей вне маршрута.
                        // ⚠️ Заодно выяснилось: исключать сквозные комнаты (sealed2) НЕЛЬЗЯ — их треть
                        // от всех комнат маршрута (118 из 386), и без них кандидатов становится 13
                        // вместо 16. Третий проём в такой комнате ловит сам модуль моста (hor != 2).
                        bool mine = (c.a == room && onMainSet.Contains(c.b))
                                 || (c.b == room && onMainSet.Contains(c.a));
                        // ⭐ Вертикальные соседства тоже годятся: дверь теперь режется и в пол
                        // (см. MazeSite.doorRow). Раньше здесь стояло «|| c.vertical» — и половина
                        // найденных соседств отбрасывалась только из-за ориентации.
                        if (!mine) continue;
                        candsHere++; StatLoopCand++;
                        c.returnEdge = true; c.returnFrom = room;
                        if (!tryOpen(c)) { c.returnEdge = false; c.returnFrom = -1; StatLoopBypass++; continue; }
                        loopLinks.Add(c); cands.RemoveAt(i); closed = true;
                    }
                    if (closed) break;
                }
                if (candsHere == 0) StatLoopNoCand++;
                // ⛔ ЗАПАСНОЙ ПОИСК ПО ПЕРЕКРЫТИЮ В ОДНУ КЛЕТКУ ПРОБОВАЛСЯ И УБРАН (2026-09-11).
                // Замысел: из 12 веток без кандидата ОДИННАДЦАТЬ стоят прямо над комнатой маршрута
                // через одну стену и промахиваются мимо неё на колонку — общий список соседств
                // требует перекрытия в две клетки (MinOverlap), и они отсеиваются.
                //
                // ⚠️ ШИРИНА ЛЮКА ПРОХОДИМОСТИ НЕ МЕШАЕТ — проверено на голой геометрии: артефакт под
                // люком достижим одинаково через 1, 2, 3 и 5 клеток. Первый заход я списал провал
                // именно на ширину и ошибся.
                // 🐞 Ломала РУЧНАЯ ВРЕЗКА в сетку уже ПОСЛЕ рендера — мимо уступов, climbCols и всего,
                // что рендер делает вокруг люка: клапанов становилось 14 против 9, но чистых уровней
                // 5 из 10 вместо 8. А когда люк стал резать сам рендер, запасной поиск не дал НИ
                // ОДНОГО лишнего клапана (8 против 9) — то есть искал он то, что и так не строится.
                // Чинить надо не порог перекрытия, а ПОСАДКУ последнего звена ветки: оно должно
                // вставать в створ с комнатой маршрута, а не «где получилось». Это правка раскладки.
            }
        }
        for (int i = cands.Count - 1; i > 0; i--)
        { int j = rng.Next(i + 1); var tmp = cands[i]; cands[i] = cands[j]; cands[j] = tmp; }
        int wantExtra = Mathf.RoundToInt(lay.links.Count * extraEdgesPercent / 100f);
        foreach (var c in cands)
        {
            if (wantExtra <= 0) break;
            // ⭐ СКВОЗНОЙ КОРИДОР ОБЯЗАН ОСТАТЬСЯ СКВОЗНЫМ. Комната моста и комната камеры объявлены
            // проходными ровно насквозь вбок (sealed2): два боковых прохода и ни одного лишнего.
            // 🐞 Лишние рёбра добавляются ПОСЛЕ дерева и про это не знали — третий проём в такой
            // комнате превращал её в развилку, и мост отказывался вставать. Замер на 21 уровне: из
            // 18 потерянных механизмов девять были мостом, и четыре из них — ровно с этой жалобой
            // («мост: комната N не сквозной коридор»).
            if (c.a >= 0 && c.a < nodes.Count && nodes[c.a].sealed2) continue;
            if (c.b >= 0 && c.b < nodes.Count && nodes[c.b].sealed2) continue;
            if (pathHasElement(c.a, c.b)) continue;         // дешёвый отсев до полной проверки
            if (tryOpen(c)) wantExtra--;
        }

        int rows, cols;
        var g = Render(lay, rng, out rows, out cols);

        // Прямоугольники комнат в координатах СЕТКИ (Y вниз) — их же получит холст модулей.
        var rects = new MazeCanvas.RoomRect[nodes.Count];
        foreach (var rm in lay.rooms)
            rects[rm.id] = new MazeCanvas.RoomRect
            { col0 = rm.x0, row0 = rows - 1 - rm.Y1, w = rm.w, h = rm.h };

        var story = new System.Text.StringBuilder();
        story.Append("комнат ").Append(nodes.Count).Append(", габарит ").Append(cols).Append('×').Append(rows).Append(": ");
        var stamps = new List<ModuleStamp>();
        var grpPlane = Furnish(g, rows, cols, nodes, rects, lay.links, rng, stamps, story, loopLinks);
        foreach (var st in stamps) story.Append(st.moduleName).Append(' ').Append(st.groupId).Append("; ");

        // ── Неприкосновенное: проходы, клетки над ними (посадочные холды) и ступени ──
        var guarded = new bool[rows, cols];
        System.Action<int, int> guard = (r, c) =>
        { if (r >= 0 && r < rows && c >= 0 && c < cols) guarded[r, c] = true; };
        foreach (var l in lay.links)
        {
            if (l.vertical)
            {
                int wr = rows - 1 - l.wall;
                for (int x = l.from; x <= l.to; x++) { guard(wr, x); guard(wr - 1, x); guard(wr + 1, x); }
            }
            else
            {
                for (int y = l.from; y <= l.to; y++)
                for (int x = l.wall; x <= Mathf.Max(l.wall, l.wallEnd); x++)
                { int rr = rows - 1 - y; guard(rr, x); guard(rr, x - 1); guard(rr, x + 1); }
            }
        }
        // ⭐⭐ ПОЛ КОМНАТЫ — ДОРОГА, А НЕ ХОЛСТ. По нижнему ряду воздуха игрок и ходит; бугор,
        // выросший там, режет проход надвое.
        // 🐞 Замер, из-за которого это появилось: с отделкой недостижимых комнат 57 из 618, без
        // отделки 28 — декор УДВАИВАЛ отсечённые куски уровня. Разбор одного случая (сид 504): треть
        // уровня отрезана, 11 комнат подряд, и всё из-за одного бугра у входа в тоннель. Коридоры
        // защита уже прикрывала, а пол комнаты, ведущий к ним, — нет.
        foreach (var rm in lay.rooms)
        {
            int floorAir = rows - 1 - rm.y0;                  // нижний ряд ВОЗДУХА комнаты
            for (int x = rm.x0; x <= rm.X1; x++) guard(floorAir, x);
        }
        foreach (var st in stamps) foreach (var bcell in st.buttons)
        { guard(bcell.y, bcell.x); guard(bcell.y - 1, bcell.x); }
        // ⚠️ ОБЪЕКТЫ И ИХ ОКРЕСТНОСТЬ. 🐞 Декор садился вплотную к ключу и перекрывал подход: замер
        // дал «ключи 2/3» на двух схемах из шестнадцати. У ключа спрайт ШИРЕ своей клетки, ему нужен
        // зазор с боков — это правило было на решётке, при переносе потерялось.
        for (int r = 0; r < rows; r++)
        for (int c = 0; c < cols; c++)
        {
            char ch = g[r, c];
            if (ch != '*' && ch != '@' && ch != '^' && ch != '=') continue;
            for (int dr = -1; dr <= 1; dr++)
            for (int dc = -2; dc <= 2; dc++) guard(r + dr, c + dc);
        }

        if (!SkipDressing)
        {
            var noDecor = new HashSet<int>();
            foreach (var nd in nodes)
                if (nd.element != null) { noDecor.Add(nd.id); if (nd.parent >= 0) noDecor.Add(nd.parent); }
            Decorate(g, rows, cols, rects, guarded, noDecor, rng);
            DropCoins(g, rows, cols, rects, 8 + nodes.Count * 2, rng);
        }

        // ⚠️ Обрезка — САМОЙ ПОСЛЕДНЕЙ: до неё камень нужен целиком (модули на него опираются),
        // а после неё правки геометрии уже нельзя — они снова оставят зажимы.
        TrimShell(g, rows, cols);

        var sb = new System.Text.StringBuilder();
        for (int r = 0; r < rows; r++) { for (int c = 0; c < cols; c++) sb.Append(g[r, c]); sb.Append('\n'); }
        return new Built { scheme = sb.ToString(), nodes = nodes, layout = lay,
                           stamps = stamps, story = story.ToString(),
                           grid = g, grp = grpPlane, rows = rows, cols = cols,
                           spec = BuildSpec(g, grpPlane, rows, cols, stamps, cellSize) };
    }

    /// <summary>
    /// ⭐⭐ ДОРОГА НАЗАД НА ТРАССУ. Прокладывает от безвыходной клетки проход к БЕЗОПАСНОЙ —
    /// такой, из которой финиш достижим.
    ///
    /// Почему именно так, а не по геометрии. Первая попытка чинила «по виду»: ставила уступ в
    /// каждой комнате, куда ведёт люк выше дотяжки (таких оказалось 203 из 389). Замер: безвыходных
    /// клеток стало БОЛЬШЕ (247 → 266), а достижимых меньше (745 → 644) — плита садилась в дверной
    /// проём. Разбор показал, что чинилось не то место: 145 безвыходных клеток из 197 лежат ВНЕ
    /// комнат. Место для прохода умеет назвать только модель, и спрашиваем теперь её.
    ///
    /// Что рисуем: ступенчатый ход — вертикальные пролёты не длиннее дотяжки, между ними полки в
    /// две клетки. Так проход climbable ПО ПОСТРОЕНИЮ, а не «надеюсь, дотянется».
    /// ⚠️ Чужие клетки (буквы групп, ключи, спавн, финиш) не трогаем НИКОГДА: проход обязан быть
    /// дорогой, а не ластиком по чужой головоломке.
    /// </summary>
    /// <returns>Сколько клеток прорезано; 0 — проход построить не удалось.</returns>
    public static int CarveReturn(char[,] g, int rows, int cols, Vector2Int from, Vector2Int to)
    {
        // Сетка растёт сверху вниз, клетки модели — снизу вверх.
        System.Func<int, int> toRow = y => rows - 1 - y;
        System.Func<int, int, bool> free = (x, y) =>
        {
            int r = toRow(y);
            if (r < 1 || r >= rows - 1 || x < 1 || x >= cols - 1) return false;
            char ch = g[r, x];
            // Камень, воздух, обрезанная кожура и МОНЕТЫ. 🐞 Монет на уровне под сотню, и пока они
            // считались чужими, ход не строился ни разу из шести: любая длинная дорога упирается в
            // монету. Потерять монету не жалко — она украшение, а не головоломка.
            return ch == '#' || ch == '.' || ch == ' ' || ch == '$';
        };
        System.Action<int, int, char> put = (x, y, ch) =>
        {
            int r = toRow(y);
            if (r < 1 || r >= rows - 1 || x < 1 || x >= cols - 1) return;
            char cur = g[r, x];
            if (cur != '#' && cur != '.' && cur != ' ' && cur != '$') return;   // чужое не трогаем
            g[r, x] = ch;
        };

        // Путь ведём буквой Г: сперва по вертикали до высоты цели, потом по горизонтали.
        // ⚠️ Ход в ДВЕ клетки шириной: одноклеточный колодец игрок проходит, но выглядит он щелью,
        // и любой зажим по диагонали делает его непроходимым.
        int x0 = Mathf.Clamp(from.x, 1, cols - 2), x1 = Mathf.Clamp(to.x, 1, cols - 2);
        int y0 = from.y, y1 = to.y;
        for (int x = x0; x <= x0 + 1; x++)
            for (int y = Mathf.Min(y0, y1); y <= Mathf.Max(y0, y1) + 1; y++)
                if (!free(x, y)) return 0;
        int stepX = x1 >= x0 ? 1 : -1;
        for (int x = x0; x != x1 + stepX; x += stepX)
            for (int y = y1; y <= y1 + 1; y++)
                if (!free(x, y)) return 0;

        int carved = 0;
        // Вертикальный пролёт с полками через каждые Climb рядов — иначе наверх не подняться.
        int lo = Mathf.Min(y0, y1), hi = Mathf.Max(y0, y1);
        for (int y = lo; y <= hi + 1; y++)
        for (int x = x0; x <= x0 + 1; x++)
        { put(x, y, '.'); carved++; }
        for (int y = lo + MazeCanvas.Climb; y < hi; y += MazeCanvas.Climb)
            put(x0, y, '#');                                  // полка в одну клетку: вторая — проход
        // Горизонтальный ход на высоте цели, с полом под ним.
        for (int x = x0; x != x1 + stepX; x += stepX)
        {
            put(x, y1, '.'); put(x, y1 + 1, '.'); carved += 2;
            put(x, y1 - 1, '#');
        }
        // Пол под вертикальным пролётом, чтобы упавший не улетал за границу мира.
        put(x0, lo - 1, '#'); put(x0 + 1, lo - 1, '#');
        return carved;
    }

    /// <summary>Пересобрать схему и описание после того, как сетку правили (проход возврата).</summary>
    public static void Refresh(Built b)
    {
        if (b == null || b.grid == null) return;
        var sb = new System.Text.StringBuilder();
        for (int r = 0; r < b.rows; r++) { for (int c = 0; c < b.cols; c++) sb.Append(b.grid[r, c]); sb.Append('\n'); }
        b.scheme = sb.ToString();
        b.spec = BuildSpec(b.grid, b.grp, b.rows, b.cols, b.stamps, cellSize);
    }

    /// <summary>Сколько детей у каждого узла — мера того, сколько сторон комнаты уже занято.</summary>
    private static int[] KidCounts(List<Node> nodes)
    {
        var k = new int[nodes.Count];
        foreach (var nd in nodes) if (nd.parent >= 0) k[nd.parent]++;
        return k;
    }

    /// <summary>Комната трассы, к которой можно подвесить ветку: наименее загруженная из случайной
    /// горстки. ⚠️ Не самая свободная из всех — иначе все ветки соберутся в одном месте.</summary>
    /// <summary>
    /// ⭐⭐ ТОЧКА ОТРЫВА ВЕТКИ. Кроме загруженности сторон учитывает ещё одно: СВОБОДНО ЛИ СЛЕДУЮЩЕЕ
    /// РЕБРО ТРАССЫ.
    ///
    /// 🐞 Петля возвращается на маршрут в комнату СЛЕДУЮЩУЮ за точкой отрыва. Если на ребре между
    /// ними стоит механизм, ребро возврата его ОБХОДИТ — и проверка обхода честно его отвергает.
    /// Замер: из 25 найденных кандидатов на ребро возврата 14 зарубила именно она, а не геометрия.
    /// Петля и замок на трассе дерутся за одно и то же ребро, и разнять их можно только здесь, при
    /// выборе точки отрыва: механизмы на хребте расставлены раньше веток, так что мы их уже видим.
    /// ⚠️ Это ПРЕДПОЧТЕНИЕ, а не запрет: если свободного ребра рядом нет, ветку всё равно цепляем —
    /// без петли она хуже, но без ветки хуже вдвое.
    /// </summary>
    private static int PickAttach(List<Node> nodes, List<int> spine, System.Random rng)
    {
        var load = KidCounts(nodes);
        // Следующее ребро свободно, если у комнаты за точкой отрыва нет своего механизма.
        System.Func<int, bool> nextFree = id =>
        {
            int ix = spine.IndexOf(id);
            return ix >= 0 && ix + 1 < spine.Count && nodes[spine[ix + 1]].element == null;
        };
        int best = -1, bestScore = int.MaxValue;
        for (int t = 0; t < 8; t++)
        {
            int cand = spine[1 + rng.Next(Mathf.Max(1, spine.Count - 2))];
            if (nodes[cand].sealed2) continue;
            // Занятая сторона стоит одно очко, занятое следующее ребро — сразу четыре: без него
            // петля не замкнётся вовсе, а лишняя сторона лишь усложняет посадку.
            int score = load[cand] + (nextFree(cand) ? 0 : 4);
            if (score < bestScore) { bestScore = score; best = cand; }
        }
        if (best < 0)
            foreach (int c2 in spine) if (!nodes[c2].sealed2) { best = c2; break; }
        return best;
    }

    /// <summary>Размер клетки уровня. Тот же, что у инструмента Tile в редакторе.</summary>
    private const float cellSize = 0.5f;

    /// <summary>
    /// ⭐⭐ ОПИСАНИЕ УРОВНЯ — НАСТОЯЩИЙ ВЫХОД ГЕНЕРАТОРА. Сетка символов остаётся, но уже как ВИД
    /// ДЛЯ ГЛАЗ: печатать её можно, читать обратно — нет.
    ///
    /// Зачем понадобилось (вопрос игрока, и он справедлив). Внутри генератор всегда был
    /// типизирован — <see cref="ModuleStamp"/> знает группу, инверсию, окно, кнопки, их хозяев и
    /// теперь стороны крепления. А наружу он отдавал СТРОКУ плюс два боковых канала, потому что
    /// ASCII ничего из этого не выражает. Цена уже заплачена: стоило пути забыть канал, и разбор
    /// врал — так «ломались» Level_07, 10 и 11, ровно те, где вложенность и есть. Сторона крепления
    /// стала бы третьим каналом, движущаяся платформа потребовала бы четвёртого, противник — пятого.
    ///
    /// ⚠️ Из сетки берётся только КАМЕНЬ И ЦЕЛИ — то, что она выражает честно. Всё про механизмы
    /// приходит из штампов, а не вычитывается из букв обратно.
    /// </summary>
    /// <summary>
    /// ⭐ КЛЮЧ ГРУППЫ В СПЕКЕ. Раньше это была буква из сетки, и потому групп не могло быть больше
    /// 26. Теперь ключ построен из НОМЕРА и с буквой никак не связан; ручные уровни продолжают
    /// жить со своими "A".."Z" — ключи спека это просто строки, и пересечься им негде.
    /// </summary>
    private static string GroupKey(int groupIx) => "g" + groupIx;

    public static LevelSpec BuildSpec(char[,] g, int[,] grp, int rows, int cols, List<ModuleStamp> stamps, float cell)
    {
        var spec = new LevelSpec { cell = cell };
        System.Func<int, int, Vector2Int> K = (r, c) => new Vector2Int(c, rows - 1 - r);
        System.Func<Vector2Int, LevelTarget> mkT = k => new LevelTarget
        { exists = true, cell = k, center = new Vector2(k.x, k.y), half = Vector2.zero,
          world = new Vector3(k.x * cell, k.y * cell, 0f) };

        var groupCells = new Dictionary<int, List<Vector2Int>>();
        for (int r = 0; r < rows; r++)
        for (int c = 0; c < cols; c++)
        {
            char ch = g[r, c];
            var k = K(r, c);
            if (ch == '#') spec.rock.Add(k);
            // 🐞 Здесь стояло «ch >= 'a' && ch <= 'z'» — необъявленный потолок в 26 групп: у 27-й
            // ключ был '[', он мимо диапазона, и группа уезжала БЕЗ ЕДИНОЙ ПЛИТКИ. Теперь плитку
            // опознаёт номер в плоскости, а буква осталась только для глаз и может повторяться.
            else if (grp[r, c] >= 0)
            {
                List<Vector2Int> l;
                int gx = grp[r, c];
                if (!groupCells.TryGetValue(gx, out l)) { l = new List<Vector2Int>(); groupCells[gx] = l; }
                l.Add(k);
            }
            else if (ch == MazeCanvas.Spike) spec.spikes.Add(k);
            else if (ch == '@') { spec.spawn = k; spec.hasSpawn = true; }
            else if (ch == '^') spec.finish = mkT(k);
            else if (ch == '*') spec.artifacts.Add(mkT(k));
            else if (ch == '=') spec.checkpoints.Add(mkT(k));
            else if (ch == '$') spec.coins.Add(k);
        }

        // Группы — ИЗ ШТАМПОВ: там инверсия, окно, хозяева и крепления. Буквы в сетке лишь говорят,
        // какие клетки заняты, и то сверяются с тем же штампом.
        foreach (var st in stamps)
        {
            var gr = spec.GetOrAddGroup(GroupKey(st.groupIx), st.inverted);
            gr.inverted = st.inverted;
            gr.window = st.window;
            gr.returnValve = st.returnValve;
            List<Vector2Int> tiles;
            if (groupCells.TryGetValue(st.groupIx, out tiles)) gr.tiles.AddRange(tiles);
        }
        // Кнопки — вторым проходом: хозяин ищется по УЖЕ созданным группам.
        foreach (var st in stamps)
        {
            int gi = spec.IndexOfGroup(GroupKey(st.groupIx));
            if (gi < 0) continue;
            for (int i = 0; i < st.buttons.Count; i++)
            {
                var b = st.buttons[i];
                int hostIx = i < st.buttonHosts.Count ? st.buttonHosts[i] : -1;
                int host = LevelButton.NoHost;
                if (hostIx >= 0)
                {
                    host = spec.IndexOfGroup(GroupKey(hostIx));
                    if (host < 0) host = LevelButton.NoHost;
                }
                var k = K(b.y, b.x);
                spec.groups[gi].buttons.Add(new LevelButton
                { cell = k, center = new Vector2(k.x, k.y), half = Vector2.zero, host = host,
                  mount = i < st.buttonMounts.Count ? st.buttonMounts[i] : MountSide.Floor });
            }
        }
        return spec;
    }
