    /// ровно так, как это сделано в ручных уровнях игрока.
    ///
    /// Зачем вообще: замер объёма (вертикальные пробеги открытого пространства) — в ручных уровнях
    /// 22-31% пробегов выше шести клеток и максимум 22-30, у генератора 5-7% и максимум 11-14. То
    /// есть у нас был ОДИН масштаб, 3×5 на весь уровень, и оттого «примитивный прямоугольник» вместо
    /// объёма. Разброс масштабов — то же, чем добиваются естественности в Cogmind (разбор статьи).
    /// </summary>
    public const int MaxHallHeight = MazeCanvas.Climb * 4;
    /// <summary>Сколько клеток общей стены нужно, чтобы прорезать проход (люк — 2 клетки минимум).</summary>
    private const int MinOverlap = 2;

    /// <summary>
    /// ⭐ Насколько пол соседней комнаты может отличаться по высоте. Дотяжкой НЕ ограничен: не хватает
    /// вылета — рендер достраивает ступени прямо в проёме (идея игрока 2026-09-03).
    /// ⚠️ Предел всё же есть: очень высокая лестница шириной в клетку читается как колодец, а не как
    /// проход между комнатами.
    /// </summary>
    public const int MaxFloorStep = MazeCanvas.Climb * 2;
    /// <summary>
    /// Камня между НЕ связанными комнатами. ⚠️ ОДНА КЛЕТКА — ровно как было на решётке
    /// (`colX[x+1] = colX[x] + colW[x] + 1`), и там это выглядело нормально все эти месяцы.
    /// 🐞 Сперва я поставил две «на всякий случай» — и укладка не сходилась в половине случаев:
    /// на змейке третья комната почти всегда нарушала зазор с первой. Перестраховка стоила половины
    /// раскладок, а гипотезы про регионы, которые я проверял до этого, были мимо.
    /// </summary>
    private const int Margin = 1;

    /// <summary>
    /// Разложить дерево. <paramref name="parent"/>[i] — родитель комнаты i (−1 у корня),
    /// <paramref name="dir"/>[i] — куда обязан встать ребёнок i относительно родителя.
    /// Возвращает null, если за <paramref name="tries"/> попыток уложить не удалось: недобор честнее
    /// молчаливой подмены.
    /// </summary>
    /// <remarks>
    /// Замер отдачи от числа попыток на реалистичных деревьях («гусеница» — основной путь плюс
    /// короткие ветки): 60 → 82% уложенных, 300 → 88%, 1500 → 90%. Дальше упирается в деревья,
    /// которые этой жадной укладкой не берутся в принципе (узел с тремя детьми, у каждого своё
    /// жёсткое направление). 300 стоит 0.4 мс — берём его, а оставшиеся проценты пусть решает
    /// переброс сида уровнем выше, он и так есть.
    /// </remarks>
    public static Result Build(int n, int[] parent, RoomReq[] req, LinkDir[] dir,
                               System.Random rng, int tries = 300)
        => BuildStaged(n, parent, req, dir, rng, null, tries);

    /// <summary>
    /// ⭐⭐ ПОЭТАПНАЯ УКЛАДКА (предложение игрока). Комнаты кладутся не одной попыткой на весь
    /// уровень, а группами: сперва хребет старт→финиш, потом каждая ветка отдельно, добор последним.
    /// Не встала группа — переигрывается ТОЛЬКО она, а всё уже поставленное остаётся.
    ///
    /// 🐞 Зачем. Прежняя укладка была «всё или ничего»: не встала одна комната — в мусор шла вся
    /// попытка, и снаружи это перезапускалось до 300 раз с нуля. Цена видна на замере петли: стык
    /// с трассой при жёстком требовании получался в 4 случаях из 4, а раскладка сходилась 4 попытки
    /// из 40 — губило не требование, а именно безоткатность.
    ///
    /// ⚠️ ОБЛАСТЕЙ РОСТА ЗДЕСЬ БОЛЬШЕ НЕТ. Они существовали ровно затем, чтобы ранняя ветка не
    /// занимала место поздней при отсутствии отката. С поэтапной укладкой откат есть, а области
    /// мешали: именно они разносили комнаты так, что конец ветки в 60 случаях из 86 не касался
    /// ничего, и петлю нельзя было замкнуть. Раскидистость уровня при этом не порок, а цель
    /// (решение игрока): уровень должен казаться насыщенным, а не линейным.
    /// </summary>
    /// <param name="stageOf">Номер этапа для каждого узла (null — всё одним этапом). Корень кладётся
    /// первым независимо от номера.</param>
    public static Result BuildStaged(int n, int[] parent, RoomReq[] req, LinkDir[] dir,
                                     System.Random rng, int[] stageOf, int triesPerStage = 60)
    {
        var kids = new List<int>[n];
        for (int i = 0; i < n; i++) kids[i] = new List<int>();
        int root = -1;
        for (int i = 0; i < n; i++) { if (parent[i] < 0) root = i; else kids[parent[i]].Add(i); }
        if (root < 0) return null;

        // Порядок обхода: родитель всегда раньше ребёнка.
        var order = new List<int>();
        var stack = new Stack<int>(); stack.Push(root);
        while (stack.Count > 0) { int v = stack.Pop(); order.Add(v); foreach (int k in kids[v]) stack.Push(k); }

        // Этапы в порядке возрастания номера; корень уже стоит, его пропускаем.
        var stages = new List<List<int>>();
        {
            var byStage = new Dictionary<int, List<int>>();
            foreach (int id in order)
            {
                if (id == root) continue;
                int st = stageOf != null ? stageOf[id] : 0;
                List<int> l;
                if (!byStage.TryGetValue(st, out l)) { l = new List<int>(); byStage[st] = l; }
                l.Add(id);
            }
            var nums = new List<int>(byStage.Keys); nums.Sort();
            foreach (int st in nums) stages.Add(byStage[st]);
        }

        // ⚠️ ВНЕШНИЙ ПЕРЕЗАПУСК ПОВЕРХ ЭТАПОВ. Этапы дают дешёвый откат, но не всесильны: если
        // ранние комнаты обстроили точку отрыва со всех сторон, ветке физически некуда встать, а
        // переигрывать ранний этап поздний уже не может. 🐞 Замер: одни этапы дали 29 уровней из 40.
        // Перезапуск возвращает утраченное, оставаясь во много раз дешевле прежних 300 попыток —
        // те начинали с нуля ВСЕГДА, а эти только когда действительно тупик.
        RoomBox[] boxes = null; Result res = null;
        List<RoomBox> reserved = null;
        bool allOk = false;
        StatBuilds++;
        for (int restart = 0; restart < 12 && !allOk; restart++)
        {
            if (restart > 0) StatRestarts++;
        boxes = new RoomBox[n];
        res = new Result();
        reserved = new List<RoomBox>();
        var s0 = Size(req[root], rng);
        boxes[root] = new RoomBox { id = root, x0 = 0, y0 = 0, w = s0[0], h = s0[1] };
        if (req[root].reserveBelow > 0)
            reserved.Add(new RoomBox { id = -1, x0 = -req[root].reserveWide,
                w = s0[0] + req[root].reserveWide * 2,
                y0 = -1 - req[root].reserveBelow, h = req[root].reserveBelow });
        allOk = true;

        foreach (var stageNodes in stages)
        {
            bool ok = false;
            // ⭐ Кольцо пробуем ПЕРВЫМ: его форма считается, а не подбирается.
            for (int attempt = 0; attempt < 8 && !ok; attempt++)
            {
                int linksBefore = res.links.Count;
                ok = PlaceRing(n, parent, req, rng, boxes, res, stageNodes);
                if (!ok)
                {
                    foreach (int id in stageNodes) boxes[id] = null;
                    res.links.RemoveRange(linksBefore, res.links.Count - linksBefore);
                }
            }
            for (int attempt = 0; attempt < triesPerStage && !ok; attempt++)
            {
                int linksBefore = res.links.Count, resBefore = reserved.Count;
                ok = PlaceStage(n, parent, req, dir, rng, boxes, res, stageNodes, reserved);
                if (!ok)
                {
                    StatStageRetries++;
                    // Откат ТОЛЬКО этого этапа: всё, что стояло раньше, остаётся на месте.
                    // ⚠️ Вместе с комнатами снимаем и БРОНЬ, выданную в этой попытке. 🐞 Без этого
                    // бронь копилась с каждой переигровкой и заполняла уровень: переигровок стало
                    // 553 вместо 272, а кольцу от такой брони только хуже.
                    foreach (int id in stageNodes) boxes[id] = null;
                    res.links.RemoveRange(linksBefore, res.links.Count - linksBefore);
                    reserved.RemoveRange(resBefore, reserved.Count - resBefore);
                }
            }
            // ⭐⭐ ПОДГОНКА ПЛАНА: не встала ветка — перевешиваем её на другую комнату маршрута.
            // Правим ПЛАН (одно ребро), а не геометрию всего уровня.
            if (!ok && !SkipReattach && stageNodes.Count > 0 && req[stageNodes[0]].reattach != null)
            {
                int firstNode = stageNodes[0];
                int oldParent = parent[firstNode];
                var opts = new List<int>(req[firstNode].reattach);
                for (int i = opts.Count - 1; i > 0; i--)
                { int j = rng.Next(i + 1); var t = opts[i]; opts[i] = opts[j]; opts[j] = t; }
                foreach (int cand in opts)
                {
                    if (ok) break;
                    if (cand == oldParent || cand < 0 || cand >= n || boxes[cand] == null) continue;
                    parent[firstNode] = cand;
                    for (int attempt = 0; attempt < 12 && !ok; attempt++)
                    {
                        int linksBefore = res.links.Count, resBefore = reserved.Count;
                        ok = PlaceStage(n, parent, req, dir, rng, boxes, res, stageNodes, reserved);
                        if (!ok)
                        {
                            foreach (int id in stageNodes) boxes[id] = null;
                            res.links.RemoveRange(linksBefore, res.links.Count - linksBefore);
                            reserved.RemoveRange(resBefore, reserved.Count - resBefore);
                        }
                    }
                }
                if (!ok) parent[firstNode] = oldParent;      // не помогло — возвращаем как было
            }

            // ⚠️ ПОСЛЕДНЯЯ СТУПЕНЬ: уровень не должен умирать из-за УКРАШЕНИЯ. Замыкание петли и
            // притяжение к трассе — пожелания; если этап из-за них не встаёт, снимаем их и кладём
            // ветку как обычную. 🐞 Без этой ступени этапы дали скачок замыкания (9% → 38%), но
            // уронили 11 уровней из 40: не встал этап — не встал весь уровень.
            if (!ok)
            {
                StatRelaxed++;
                var savedNext = new List<int>[stageNodes.Count];
                var savedPull = new int[stageNodes.Count];
                var savedDir  = new LinkDir[stageNodes.Count];
                for (int i = 0; i < stageNodes.Count; i++)
                {
                    savedNext[i] = req[stageNodes[i]].nextToAny; savedPull[i] = req[stageNodes[i]].pullTo;
                    savedDir[i]  = dir[stageNodes[i]];
                    req[stageNodes[i]].nextToAny = null; req[stageNodes[i]].pullTo = -1;
                    // ⚠️ Снимаем и НАПРАВЛЕНИЕ: вход в ветку просит провала вниз, и если его негде
                    // сделать, ветка должна лечь хоть как-то, а не уронить весь уровень.
                    dir[stageNodes[i]] = LinkDir.Any;
                }
                for (int attempt = 0; attempt < triesPerStage && !ok; attempt++)
                {
                    int linksBefore = res.links.Count, resBefore = reserved.Count;
                    ok = PlaceStage(n, parent, req, dir, rng, boxes, res, stageNodes, reserved);
                    if (!ok)
                    {
                        foreach (int id in stageNodes) boxes[id] = null;
                        res.links.RemoveRange(linksBefore, res.links.Count - linksBefore);
                        reserved.RemoveRange(resBefore, reserved.Count - resBefore);
                    }
                }
                for (int i = 0; i < stageNodes.Count; i++)
                { req[stageNodes[i]].nextToAny = savedNext[i]; req[stageNodes[i]].pullTo = savedPull[i];
                  dir[stageNodes[i]] = savedDir[i]; }
            }
            // ⭐ Комнате-добору место не нашлось — уровень собираем без неё, а не выбрасываем.
            if (!ok)
            {
                bool allOptional = true;
                foreach (int id in stageNodes) if (!req[id].optional) { allOptional = false; break; }
                if (allOptional) { StatDropped += stageNodes.Count; continue; }
            }
            if (!ok) { allOk = false; break; }
        }
        }
        if (!allOk) return null;

        // Нормализация: сдвигаем всё так, чтобы осталось место под оболочку.
        int minX = int.MaxValue, minY = int.MaxValue, maxX = int.MinValue, maxY = int.MinValue;
        for (int i = 0; i < n; i++)
        {
            // Пропущенная комната-добор — законное «нет»; всё остальное обязано стоять.
            if (boxes[i] == null) { if (req[i].optional) continue; return null; }
            minX = Mathf.Min(minX, boxes[i].x0); minY = Mathf.Min(minY, boxes[i].y0);
            maxX = Mathf.Max(maxX, boxes[i].X1); maxY = Mathf.Max(maxY, boxes[i].Y1);
        }
        if (minX == int.MaxValue) return null;
        const int Shell = 3;
        int dx = Shell - minX, dy = Shell - minY;
        for (int i = 0; i < n; i++)
        { if (boxes[i] == null) continue; boxes[i].x0 += dx; boxes[i].y0 += dy; res.rooms.Add(boxes[i]); }
        foreach (var l in res.links)
        {
            if (l.vertical) { l.from += dx; l.to += dx; l.wall += dy; l.wallEnd += dy; }
            else            { l.from += dy; l.to += dy; l.wall += dx; l.wallEnd += dx; }
        }
        res.Width = maxX - minX + 1 + Shell * 2;
        res.Height = maxY - minY + 1 + Shell * 2;
        return res;
    }

    /// <summary>
    /// ⭐⭐ ВЫСОТА ОБЫЧНОЙ КОМНАТЫ — РОВНО ДОТЯЖКА, И ЭТО НЕ ВКУСОВЩИНА.
    ///
    /// От пола комнаты до края люка в её потолке ровно её высота. Подъём у игрока 3, значит из
    /// комнаты высотой 4-5 сквозь люк НЕ ВЫЛЕЗТИ: провалился — остался.
    /// 🐞 Замер: из 389 вертикальных связей без механизма 203 вели в комнату выше дотяжки, и по
    /// разбору недостижимых ключей ровно этот случай давал пять поломок из девяти. Чинить подъём
    /// уступами постфактум пробовал дважды, оба раза замер становился ХУЖЕ (247 → 266 безвыходных
    /// клеток; 9 → 12 недостижимых ключей). Запрещать высокие комнаты на укладке — тоже мимо:
    /// раскладка перестаёт сходиться совсем (0 уровней из 18), потому что половина комнат как раз
    /// h=4. Осталось единственное честное место — не выдавать такую высоту вовсе.
    ///
    /// ⚠️ Разброс масштабов при этом НЕ теряется: ширина по-прежнему гуляет, а высоту сверх дотяжки
    /// просят те, кто сам отвечает за подъём в себе — залы с уступами и подвал камеры (ownClimb).
    /// </summary>
    /// <summary>
    /// ⭐⭐ КОЛЬЦО ВЕТКИ — ВЫЧИСЛЯЕТСЯ, А НЕ ПОДБИРАЕТСЯ (решение игрока).
    ///
    /// 🐞 Подбором это не получалось: свободная укладка разносит комнаты, и конец ветки в 60 случаях
    /// из 86 не касался вообще ничего. Наведение и мягкие требования подняли замыкание с 9% до 22%,
    /// а вместе с односторонним входом целиком складывались лишь 2 ветки из 27. Форма известна с
    /// рисунка игрока — значит её надо ПОСЧИТАТЬ.
    ///
    /// Форма: провал под точкой отрыва (комната выше дотяжки — назад не влезть) → марш вбок по
    /// нижнему ярусу → подъём к уровню трассы → дверь вбок в комнату маршрута.
    /// ⚠️ Геометрия сходится ровно тогда, когда комната-цель НЕ ВЫШЕ точки отрыва: пол нижнего яруса
    /// считается от точки отрыва, а подъём в конце обязан попасть на уровень цели.
    /// </summary>
    private static bool PlaceRing(int n, int[] parent, RoomReq[] req, System.Random rng,
                                  RoomBox[] boxes, Result res, List<int> stage)
    {
        StatRing[0]++;
        if (stage.Count < 3) { StatRing[1]++; return false; }
        int first = stage[0], last = stage[stage.Count - 1];
        if (!req[first].ringStart || req[last].ringTarget < 0 || req[last].ringTarget >= n) { StatRing[2]++; return false; }
        // ⭐⭐ КОЛЬЦО ВЫБИРАЕТ ОБА КОНЦА — и точку отрыва, и цель.
        // 🐞 Замер: кандидатов в цель отвергалось 960 по высоте против 512 по пролёту. Условие
        // жёсткое — цель обязана быть НЕ ВЫШЕ точки отрыва (иначе провал перестаёт быть провалом),
        // а маршрут в целом лезет вверх, поэтому почти вся трасса оказывается выше. Точка отрыва
        // назначена планом вслепую; разрешаем кольцу сменить и её — тогда пара «повыше → пониже»
        // находится куда чаще.
        var attachOpts = new List<int> { parent[first] };
        if (req[first].reattach != null) attachOpts.AddRange(req[first].reattach);

        // ⭐⭐ ЦЕЛЬ КОЛЬЦО ВЫБИРАЕТ САМО. 🐞 Пока её назначал план — вслепую, до всякой геометрии, —
        // кольцо не встало НИ РАЗУ: замер по причинам дал 136 отказов «провал не выходит по высоте»
        // (цель оказывалась выше точки отрыва) и 88 «марш не влез» (цель слишком близко).
        // Здесь же комнаты уже стоят, и годную цель видно сразу.
        const int H = MazeCanvas.Climb + 1;                    // высота комнат нижнего яруса
        int nMid0 = stage.Count - 2;
        var cands = req[last].nextToAny;
        if (cands == null || cands.Count == 0)
        { if (req[last].ringTarget >= 0) cands = new List<int> { req[last].ringTarget }; else { StatRing[2]++; return false; } }

        // Перебираем пары «точка отрыва → цель»: сперва ту, что назначил план.
        RoomBox attach = null; int chosenAttach = -1;
        var fitAll = new List<int>();
        foreach (int ap in attachOpts)
        {
            if (ap < 0 || ap >= n || boxes[ap] == null) continue;
            var ab = boxes[ap];
            var fitHere = new List<int>();
            foreach (int cand in cands)
            {
                if (cand < 0 || cand >= n || cand == ap) continue;
                var t0 = boxes[cand];
                if (t0 == null) continue;
                int b0 = t0.y0 - 1 - H, h0 = ab.y0 - b0 - 1;
                if (h0 <= MazeCanvas.Climb || h0 > MaxHallHeight) { StatRing[1]++; continue; }
                int dx0 = t0.x0 >= ab.x0 ? 1 : -1;
                int sp0 = Mathf.Abs((dx0 > 0 ? t0.x0 : t0.X1) - ab.x0);
                if (sp0 < (nMid0 + 1) * 4) { StatRing[3]++; continue; }
                fitHere.Add(cand);
            }
            if (fitHere.Count > 0) { attach = ab; chosenAttach = ap; fitAll = fitHere; break; }
        }
        if (attach == null) { StatRing[4]++; return false; }
        parent[first] = chosenAttach;                 // кольцо могло сменить точку отрыва

        // Годные цели собираем ВСЕ и сортируем по пролёту: чем длиннее, тем свободнее марш.
        // ⚠️ Порядок перебора сдвигаем случайно — иначе восемь попыток подряд дают один и тот же
        // расчёт (в кольце случайны только размеры комнат), и столкновение не обойти.
        var fit = fitAll;
        fit.Sort((p1, p2) => Mathf.Abs(boxes[p2].x0 - attach.x0).CompareTo(Mathf.Abs(boxes[p1].x0 - attach.x0)));
        int pick = rng.Next(Mathf.Min(fit.Count, 4));
        var target = boxes[fit[pick]];
        int band = target.y0 - 1 - H;
        int hDrop = attach.y0 - band - 1;
        int dirX = target.x0 >= attach.x0 ? 1 : -1;

        // Последнее звено — у самой цели, на её уровне; предпоследнее ровно под ним.
        var szLast = Size(req[last], rng);
        int wLast = Mathf.Max(szLast[0], MinOverlap + 1);
        int xLast = dirX > 0 ? target.x0 - wLast - 1 : target.X1 + 2;
        var boxLast = new RoomBox { id = last, x0 = xLast, y0 = target.y0, w = wLast, h = szLast[1] };

        var made = new List<RoomBox>();
        int wDrop = Size(req[first], rng)[0];
        var drop = new RoomBox { id = first, x0 = dirX > 0 ? attach.x0 : attach.X1 - wDrop + 1,
                                 y0 = band, w = wDrop, h = hDrop };
        made.Add(drop);

        // ⚠️ ШИРИНЫ МАРША СЧИТАЕМ, А НЕ БЕРЁМ СЛУЧАЙНЫЕ. 🐞 Со случайными последняя комната яруса
        // почти никогда не попадала точно под подъём: 55 отказов «марш не влез» из 168 попыток.
        // Пролёт известен, число звеньев известно — делим поровну.
        int nMid = stage.Count - 2;                            // звеньев в марше, включая провал
        int xStart = dirX > 0 ? drop.X1 + 2 : drop.x0 - 2;
        int xStop  = dirX > 0 ? xLast - 2 : xLast + wLast + 1; // до комнаты, что встанет под подъёмом
        int room = nMid - 1;                                   // сколько ещё комнат на ярусе, кроме провала
        if (room > 0)
        {
            int avail = Mathf.Abs(xStop - xStart) + 1;
            int each = avail / room - 1;                       // минус стена между комнатами
            if (each < 3) { StatRing[5]++; return false; }
            int x = xStart;
            for (int i2 = 1; i2 <= room; i2++)
            {
                int id = stage[i2];
                int w = (i2 == room) ? wLast : each;
                int x0 = (i2 == room) ? xLast : (dirX > 0 ? x : x - w + 1);
                made.Add(new RoomBox { id = id, x0 = x0, y0 = band, w = w, h = H });
                x = dirX > 0 ? x0 + w + 1 : x0 - 1;
            }
        }
        made.Add(boxLast);

        // Ничего не задеваем (кроме собственных комнат и точки отрыва).
        foreach (var bb in made)
        for (int i3 = 0; i3 < n; i3++)
        {
            var o = boxes[i3];
            if (o == null || o.id == attach.id) continue;
            bool self = false;
            foreach (var m2 in made) if (m2.id == o.id) self = true;
            if (self) continue;
            if (bb.x0 - Margin <= o.X1 && o.x0 - Margin <= bb.X1 &&
                bb.y0 - Margin <= o.Y1 && o.y0 - Margin <= bb.Y1) { StatRing[6]++; return false; }
        }
        foreach (var bb in made) boxes[bb.id] = bb;

        // Связи: провал вниз, марш вбок, подъём вверх.
        for (int i4 = 0; i4 < stage.Count; i4++)
        {
            int id = stage[i4], par = parent[id];
            var a = boxes[id]; var pb = boxes[par];
            if (a == null || pb == null) { StatRing[7]++; return false; }
            bool vertical = (i4 == 0) || (i4 == stage.Count - 1);
            if (vertical)
            {
                var lower = a.y0 < pb.y0 ? a : pb;
                int lo = Mathf.Max(a.x0, pb.x0), hi = Mathf.Min(a.X1, pb.X1);
                if (hi - lo + 1 < MinOverlap) { StatRing[7]++; return false; }
                res.links.Add(new RoomLink { a = lower.id, b = (lower == a ? pb.id : a.id),
                    vertical = true, from = lo, to = hi, wall = lower.Y1 + 1, wallEnd = lower.Y1 + 1 });
            }
            else
            {
                var left = a.X1 < pb.x0 ? a : pb; var right = a.X1 < pb.x0 ? pb : a;
                if (right.x0 - left.X1 - 1 < 1) { StatRing[7]++; return false; }
                int lo = Mathf.Max(a.y0, pb.y0), hi = Mathf.Min(a.Y1, pb.Y1);
                if (hi - lo + 1 < MinOverlap) { StatRing[7]++; return false; }
                res.links.Add(new RoomLink { a = par, b = id, vertical = false,
                    from = lo, to = lo + MinOverlap - 1,
                    wall = left.X1 + 1, wallEnd = right.x0 - 1 });
            }
        }
        StatRing[8]++;
        return true;
    }

    private static int[] Size(RoomReq r, System.Random rng) => new[]
    {
        Mathf.Clamp(r.minW + rng.Next(3), r.minW, r.maxW),
        // ⚠️⚠️ ТРЕБОВАНИЕ ЭЛЕМЕНТА ВЫШЕ ЭТОГО ПРАВИЛА. 🐞 Сперва я зажал высоту в дотяжку ВСЕМ — и
        // тем убил ворота: словарь просит им H≥4 ровно потому, что при H=3 ступеньку просто
        // перелезают, и подъём не надо открывать. Замер поймал это сразу: обходимых по комнатам
        // ворот всего 3 из 39, а холостых 7 — остальные обходились не проходом, а собственной
        // ненужностью. Комната с воротами обязана быть выше дотяжки: в этом и есть их работа.
        r.maxH > MaxRoomHeight
            ? Mathf.Clamp(r.minH + rng.Next(6), r.minH, Mathf.Min(r.maxH, MaxHallHeight))
            : Mathf.Max(r.minH, Mathf.Min(r.maxH, MazeCanvas.Climb))
    };

    /// <summary>
    /// Разместить узлы одного ЭТАПА относительно уже стоящих комнат. false — этап не встал целиком;
    /// откат делает вызывающий, и откатывает он только этот этап.
    /// </summary>
    private static bool PlaceStage(int n, int[] parent, RoomReq[] req, LinkDir[] dir,
                                   System.Random rng, RoomBox[] boxes, Result res, List<int> stageNodes,
                                   List<RoomBox> reserved = null)
    {
        // Свободно ли место: со всеми уложенными, кроме родителя, держим зазор Margin.
        // ⚠️ И не лезем в ЗАБРОНИРОВАННЫЕ полосы — они держатся пустыми под кольца.
        System.Func<RoomBox, int, bool> free = (cand, exceptId) =>
        {
            for (int i = 0; i < n; i++)
            {
                var p = boxes[i];
                if (p == null || p.id == exceptId) continue;
                if (cand.x0 - Margin <= p.X1 && p.x0 - Margin <= cand.X1 &&
                    cand.y0 - Margin <= p.Y1 && p.y0 - Margin <= cand.Y1) return false;
            }
            if (reserved != null)
                foreach (var rr in reserved)
                    if (cand.x0 <= rr.X1 && rr.x0 <= cand.X1 && cand.y0 <= rr.Y1 && rr.y0 <= cand.Y1)
                        return false;
            return true;
        };

        // ⭐⭐ ЗАМОК РАБОТАЕТ, ТОЛЬКО ЕСЛИ ЕГО НЕ ПЕРЕШАГНУТЬ.
        // Подпись комнаты — набор механизмов на её пути от корня. Тогда путь по дереву между двумя
        // комнатами пересекает ровно те механизмы, что различают их подписи: XOR и есть ответ.
        var lockSig = new long[n];
        {
            var order = new List<int>();
            var depth = new int[n];
            for (int i = 0; i < n; i++) depth[i] = -1;
            for (int i = 0; i < n; i++)
            {
                int d = 0, cur = i;
                while (cur >= 0 && d < n) { cur = parent[cur]; d++; }
                depth[i] = d;
            }
            for (int i = 0; i < n; i++) order.Add(i);
            order.Sort((x, y) => depth[x].CompareTo(depth[y]));
            int bit = 0;
            var bitOf = new int[n];
            for (int i = 0; i < n; i++) bitOf[i] = -1;
            foreach (int i in order)
            {
                int p = parent[i];
                lockSig[i] = p >= 0 ? lockSig[p] : 0L;
                if (p >= 0 && req[i].lockedEdge && bit < 63)
                { bitOf[i] = bit; lockSig[i] |= 1L << bit; bit++; }
            }
        }
        // Зазор, через который игрок ПЕРЕШАГНЁТ: сбоку до дотяжки, вверх до подъёма. Требуем строго
        // больше — тогда шага между коробками не бывает ни при какой их внутренней геометрии.
        System.Func<RoomBox, RoomBox, bool> farEnough = (a, b) =>
        {
            int gapX = Mathf.Max(0, Mathf.Max(a.x0 - b.X1, b.x0 - a.X1) - 1);
            int gapY = Mathf.Max(0, Mathf.Max(a.y0 - b.Y1, b.y0 - a.Y1) - 1);
            return gapX > LockGapX || gapY > LockGapY;
        };
        // Кандидат не должен оказаться в дотяжке от комнаты, отделённой от него замком.
        // ⚠️ Родитель — исключение: с ним связь объявлена, они и обязаны соприкасаться.
        System.Func<RoomBox, int, bool> lockClear = (cand, exceptId) =>
        {
            if (SkipLockClearance) return true;
            for (int i = 0; i < n; i++)
            {
                var p = boxes[i];
                if (p == null || p.id == exceptId || p.id == cand.id) continue;
                if ((lockSig[cand.id] ^ lockSig[p.id]) == 0) continue;   // замка между ними нет
                if (!farEnough(cand, p)) return false;
            }
            return true;
        };

        {
            foreach (int k in stageNodes)
            {
                int v = parent[k];
                if (v < 0 || boxes[v] == null) return false;
                var pb = boxes[v];
                var sz = Size(req[k], rng);
                int cw = sz[0], ch = sz[1];

                // Какие направления вообще дозволены ролью на этом ребре.
                var dirs = new List<LinkDir>();
                switch (dir[k])
                {
                    case LinkDir.Up:         dirs.Add(LinkDir.Up); break;
                    case LinkDir.Down:       dirs.Add(LinkDir.Down); break;
                    case LinkDir.Horizontal: dirs.Add(LinkDir.Horizontal); break;
                    // ⚠️ У СВОБОДНОГО РЕБРА ПЕРЕВЕС У БОКОВОГО. Механизмы почти все требуют подъёма
                    // (ворота), и если развязки между ними тоже лезут вверх, уровень вырождается в
                    // башню — первый же прогон дал 17 в ширину при 42 в высоту. Боковое ребро
                    // добавляем дважды, чтобы уровень разворачивался в стороны.
                    default:
                        dirs.Add(LinkDir.Horizontal); dirs.Add(LinkDir.Horizontal);
                        dirs.Add(LinkDir.Up); dirs.Add(LinkDir.Down); break;
                }
                for (int i = dirs.Count - 1; i > 0; i--)
                { int j = rng.Next(i + 1); var tmp = dirs[i]; dirs[i] = dirs[j]; dirs[j] = tmp; }
                // Желаемое направление уходит в начало очереди — но остальные остаются запасными.
                if (req[k].prefer != LinkDir.Any && dirs.Count > 1)
                { dirs.Remove(req[k].prefer); dirs.Insert(0, req[k].prefer); }

                RoomBox placed = null; RoomLink link = null;
                var placedDir = LinkDir.Any; bool placedRight = false, lastRight = false;
                // ⚠️ ЗАМЫКАНИЕ ПЕТЛИ — ЖЕЛАНИЕ, А НЕ УЛЬТИМАТУМ. Первый проход ищет место, где звено
                // касается комнаты маршрута; не нашлось — второй проход ставит его как обычно.
                // 🐞 Жёстким это требование роняло ВСЮ раскладку: сошлось 4 попытки из 40 (петля при
                // этом замыкалась в 4 из 4 — то есть механизм верный, губила именно безысходность).
                bool relaxNextTo = false;
                // Притяжение: перебираем ВСЕ варианты и берём ближайший к цели, а не первый годный.
                bool pulling = req[k].pullTo >= 0 && req[k].pullTo < n && boxes[req[k].pullTo] != null;
                long bestScore = long.MaxValue;
                for (int pass = 0; pass < 2 && placed == null; pass++)
                {
                relaxNextTo = pass == 1;
                foreach (var d in dirs)
                {
                    if (placed != null && !pulling) break;
                    for (int shot = 0; shot < Shots && (placed == null || pulling); shot++)
                    {
                        RoomBox cand; RoomLink lk;
                        if (d == LinkDir.Horizontal)
                        {
                            // ⭐ ПОЛЫ СОСЕДЕЙ НЕ ОБЯЗАНЫ СОВПАДАТЬ — достаточно, чтобы разница влезала
                            // в дотяжку: проём режется от НИЖНЕГО пола вверх, и получается ступенька.
                            // 🐞 Жёсткое выравнивание не давало горизонтальной связи НИ ОДНОЙ степени
                            // свободы: ребёнку фиксировались и X, и Y, оставалось ровно два положения
                            // (слева/справа), и укладка не сходилась на больших деревьях. Заодно это
                            // чинит вид: уровень перестаёт быть плоской лентой из комнат в один ряд.
                            // ⚠️ СТОРОНА — МОНЕТКОЙ, И ЭТО ПРОВЕРЕНО. Я пробовал разворачивать основной
                            // маршрут всегда в одну сторону, думая, что «гармошка» и сводит спавн с
                            // финишем. Замер сказал: без разворота спавн→финиш 53% габарита (худший
                            // случай 46%), с разворотом 54% (худший 38%) — то есть пользы ноль, а
                            // худший случай хуже. Сводил их не изгиб маршрута, а то, что финиш вообще
                            // ставился не в его конец (см. Node.isFinish в FreeMazeBuilder).
                            bool toRight = rng.Next(2) == 0;
                            lastRight = toRight;
                            // Зазор до родителя: 1 — общая стена (как было), больше — ТОННЕЛЬ,
                            // который прорежет рендер. Пробуем разные, начиная с тесного.
                            int gap = req[k].allowTunnel ? 1 + rng.Next(MaxTunnel) : 1;
                            int x = toRight ? pb.X1 + 1 + gap : pb.x0 - gap - cw;
                            // ⭐ ПЕРЕПАД ПОЛОВ НЕ ОГРАНИЧЕН ДОТЯЖКОЙ (идея игрока): не хватает вылета —
                            // в проёме достраиваются СТУПЕНИ. Это тот же зигзаг, только применённый к
                            // связи. Благодаря этому у горизонтального ребра появляется свобода по Y,
                            // которой раньше не было вовсе (фиксировались и X, и Y — ровно два
                            // положения на выбор, оттого укладка и не сходилась на больших деревьях).
                            // ⚠️ Разумный предел всё же нужен: слишком высокая лестница в одну клетку
                            // ширины читается как колодец, а не как проход.
                            int drop = rng.Next(-MaxFloorStep, MaxFloorStep + 1);
                            cand = new RoomBox { id = k, x0 = x, y0 = pb.y0 + drop, w = cw, h = ch };
                            int lo = Mathf.Max(cand.y0, pb.y0), hi = Mathf.Min(cand.Y1, pb.Y1);
                            if (hi - lo + 1 < MinOverlap) continue;
                            // Проём идёт от НИЖНЕГО пола до верхнего плюс запас — войти можно с любой
                            // стороны, а ступени в нём достроит рендер.
                            int lowFloor = Mathf.Min(cand.y0, pb.y0);
                            int topNeed = Mathf.Max(cand.y0, pb.y0) + MinOverlap - 1;
                            if (topNeed > hi) continue;
                            int wcol = toRight ? pb.X1 + 1 : cand.X1 + 1;
                            int wend = toRight ? cand.x0 - 1 : pb.x0 - 1;
                            // ⚠️⚠️ ТОННЕЛЬ НЕ ДОЛЖЕН ВСПОРОТЬ ТРЕТЬЮ КОМНАТУ. 🐞 Без этой проверки
                            // ход прорезался напрямую и по дороге вскрывал чужую комнату — уровень
                            // получал связь, которой в плане нет, механизм рядом становился обходимым.
                            // Замер: чистых схем 5 из 8 → 3 из 8, холостых групп стало больше.
                            // У лишних рёбер такая проверка была с самого начала (FindAdjacent).
                            if (wend >= wcol)
                            {
                                bool cut = false;
                                for (int q = 0; q < n && !cut; q++)
                                {
                                    var o = boxes[q];
                                    if (o == null || o.id == v || o.id == k) continue;
                                    if (o.x0 <= wend && wcol <= o.X1 && o.y0 <= topNeed + 1 && lowFloor - 1 <= o.Y1)
                                        cut = true;
                                }
                                if (cut) continue;
                            }
                            lk = new RoomLink { a = v, b = k, vertical = false,
                                                from = lowFloor, to = topNeed, wall = wcol, wallEnd = wend };
                        }
                        else
                        {
                            bool up = d == LinkDir.Up;
                            int y = up ? pb.Y1 + 2 : pb.y0 - 1 - ch;
                            // Сдвиг вбок случайный, но общий отрезок не меньше MinOverlap.
                            int lo = pb.x0 - (cw - MinOverlap), hi = pb.X1 - (MinOverlap - 1);
                            if (req[k].alignX) { lo = pb.x0; hi = pb.x0; }   // этаж под этажом, столбец в столбец
                            if (hi < lo) continue;
                            int x = lo + rng.Next(hi - lo + 1);
                            cand = new RoomBox { id = k, x0 = x, y0 = y, w = cw, h = ch };
                            int l2 = Mathf.Max(cand.x0, pb.x0), h2 = Mathf.Min(cand.X1, pb.X1);
                            if (h2 - l2 + 1 < MinOverlap) continue;
                            int wrow = up ? pb.Y1 + 1 : pb.y0 - 1;
                            lk = new RoomLink { a = up ? v : k, b = up ? k : v, vertical = true,
                                                from = l2, to = h2, wall = wrow, wallEnd = wrow };
                        }
                        if (!free(cand, v)) continue;
                        if (!lockClear(cand, v)) { StatLockClear++; continue; }
                        // Замыкание петли: звено должно касаться заданной комнаты с достаточным
                        // перекрытием — иначе прохода между ними не прорезать.
                        if (!relaxNextTo && req[k].nextTo >= 0 && req[k].nextTo < n
                            && boxes[req[k].nextTo] != null
                            && !Touches(cand, boxes[req[k].nextTo])) continue;
                        if (!relaxNextTo && req[k].nextToAny != null && req[k].nextToAny.Count > 0)
                        {
                            bool anyOk = false;
                            foreach (int t2 in req[k].nextToAny)
                                if (t2 >= 0 && t2 < n && boxes[t2] != null && t2 != v
                                    && Touches(cand, boxes[t2]) && !Blocked(cand, boxes[t2], boxes, n, k, v))
                                { anyOk = true; break; }
                            if (!anyOk) continue;
                        }
                        if (pulling)
                        {
                            var tb = boxes[req[k].pullTo];
                            long ddx = (cand.x0 + cand.X1) / 2 - (tb.x0 + tb.X1) / 2;
                            long ddy = (cand.y0 + cand.Y1) / 2 - (tb.y0 + tb.Y1) / 2;
                            long score = ddx * ddx + ddy * ddy;
                            if (score >= bestScore) continue;
                            bestScore = score;
                        }
                        placed = cand; link = lk; placedDir = d; placedRight = lastRight;
                    }
                }
                }
                if (placed == null)
                {
                    // Считаем, СКОЛЬКО сторон родителя уже занято: связь = одна сторона.
                    StatPlaceFail++;
                    int used = 0;
                    foreach (var l2 in res.links) if (l2.a == v || l2.b == v) used++;
                    if (parent[v] >= 0) { }        // связь с дедом уже посчитана в res.links
                    StatParentSides[Mathf.Clamp(used, 0, StatParentSides.Length - 1)]++;
                    StatFailByDir[(int)dir[k]]++;
                    return false;                                 // этот этап не встал — переиграем его
                }
                boxes[k] = placed; res.links.Add(link);
                // ⭐⭐ ПОЛОСА ТОННЕЛЯ — ЗАНЯТОЕ МЕСТО. Ход сквозь камень проверяет, что не вспорет
                // УЖЕ СТОЯЩУЮ комнату, — но комнаты следующих этапов ещё не существуют, и одна из
                // них спокойно вставала прямо в прорезанную полосу.
                // 🐞 Разбор сида 1001: тоннель 6-7 шёл столбцами 37-42 по рядам 22-23, а комната 11
                // (x38..41, y23..26) встала ровно над ним — и осталась БЕЗ ПОЛА. Отсюда сразу все
                // симптомы: ключ в ней недостижим, группы мертвы, карман замурован, уровень
                // непроходим. В статистике это давало четыре причины брака по девять раз каждая.
                if (reserved != null && !link.vertical && link.wallEnd > link.wall)
                    reserved.Add(new RoomBox { id = -1,
                        x0 = link.wall, w = link.wallEnd - link.wall + 1,
                        y0 = link.from - 1, h = link.to - link.from + 3 });
                // Комната, к которой цепляется ветка, держит под собой полосу для кольца.
                if (reserved != null && req[k].reserveBelow > 0)
                    reserved.Add(new RoomBox { id = -1,
                        x0 = placed.x0 - req[k].reserveWide, w = placed.w + req[k].reserveWide * 2,
                        y0 = placed.y0 - 1 - req[k].reserveBelow, h = req[k].reserveBelow });
            }
        }
        return true;
    }

    /// <summary>
    /// Самопроверка раскладки: комнаты не пересекаются, связанные соприкасаются через ОДНУ стену,
    /// общий отрезок достаточен для прохода. Возвращает пустую строку, если всё в порядке.
    /// ⚠️ Заведена не для красоты: раскладка — фундамент, и её ошибка проявится далеко от места,
    /// где сделана (кривой уровень вместо кривого прямоугольника).
    /// </summary>
    public static string Validate(Result r)
    {
        var sb = new System.Text.StringBuilder();
        for (int i = 0; i < r.rooms.Count; i++)
        for (int j = i + 1; j < r.rooms.Count; j++)
        {
            var a = r.rooms[i]; var b = r.rooms[j];
            if (a.x0 <= b.X1 && b.x0 <= a.X1 && a.y0 <= b.Y1 && b.y0 <= a.Y1)
                sb.Append($"комнаты {a} и {b} ПЕРЕСЕКАЮТСЯ; ");
        }
        var byId = new Dictionary<int, RoomBox>();
        foreach (var rm in r.rooms) byId[rm.id] = rm;
        foreach (var l in r.links)
        {
            var a = byId[l.a]; var b = byId[l.b];
            if (l.to - l.from + 1 < MinOverlap) sb.Append($"связь {l.a}-{l.b}: общий отрезок мал; ");
            if (l.vertical)
            {
                if (b.y0 != a.Y1 + 2) sb.Append($"связь {l.a}-{l.b}: между ними не одна стена; ");
                if (l.from < Mathf.Max(a.x0, b.x0) || l.to > Mathf.Min(a.X1, b.X1))
                    sb.Append($"связь {l.a}-{l.b}: отрезок вне общей части; ");
            }
            else
            {
                // ⚠️ ТОННЕЛЬ — ЗАКОННАЯ СВЯЗЬ, А НЕ БРАК. Проверка писалась, когда соседями могли быть
                // только комнаты через ОДНУ стену; теперь ребро дерева вправе быть ходом сквозь
                // камень (RoomReq.allowTunnel), и зазор между комнатами доходит до MaxTunnel.
                // 🐞 Иначе самопроверка сыпала ложными жалобами на каждый тоннель — одиннадцать штук
                // на уровень — и за ними не видно настоящих поломок.
                var left = a.X1 < b.x0 ? a : b; var right = a.X1 < b.x0 ? b : a;
                int gap = right.x0 - left.X1 - 1;
                if (gap < 1 || gap > MaxTunnel)
                    sb.Append($"связь {l.a}-{l.b}: зазор {gap} — не стена и не тоннель; ");
                // Полы могут различаться: перепад в проёме разбивается ступенями (см. MaxFloorStep).
                if (Mathf.Abs(a.y0 - b.y0) > MaxFloorStep)
                    sb.Append($"связь {l.a}-{l.b}: перепад полов сверх допустимого; ");
                if (Mathf.Min(a.Y1, b.Y1) - Mathf.Max(a.y0, b.y0) + 1 < MinOverlap)
                    sb.Append($"связь {l.a}-{l.b}: комнаты почти не перекрываются по высоте; ");
            }
        }
        return sb.ToString();
    }
