        /// <summary>Первое звено ветки-КОЛЬЦА (провал под точкой отрыва).</summary>
        public bool ringStart;
        /// <summary>Последнее звено ветки-кольца: id комнаты маршрута, к которой оно обязано выйти.</summary>
        public int ringTarget = -1;

        /// <summary>
        /// ⭐⭐ КУДА МОЖНО ПЕРЕВЕСИТЬ ВЕТКУ, если на назначенной комнате она не встала (идея игрока:
        /// «возврат к основному маршруту и подгонка»). Список комнат-кандидатов; раскладка вправе
        /// сменить родителя ПЕРВОГО звена и переиграть этап.
        ///
        /// Зачем. Точка отрыва выбирается в плане ВСЛЕПУЮ, до всякой геометрии. Когда она не
        /// подходит, раньше переигрывалась вся раскладка целиком — а исправить надо было одно ребро.
        /// </summary>
        public List<int> reattach;

        /// <summary>
        /// ⭐⭐ ЗАБРОНИРОВАТЬ ПОЛОСУ ПОД ЭТОЙ КОМНАТОЙ (глубина в клетках, 0 — не бронировать).
        /// Туда никто не встанет — кроме кольца, ради которого бронь и делается.
        ///
        /// 🐞 Замер, из-за которого понадобилось: вычисляемое кольцо не встало НИ РАЗУ, и по мере
        /// починки причин отказ смещался к столкновениям — 137 из 184 попыток. Кольцу нужен свободный
        /// прямоугольник примерно 30×10 на ярус ниже трассы, а его успевает занять сам хребет.
        /// Резервировать ПОСЛЕ укладки поздно: бронь должна существовать в момент, когда хребет
        /// ещё кладётся.
        /// ⚠️ Бронируем не под всем хребтом, а только под комнатами, к которым цепляются ветки:
        /// сплошная бронь заставила бы маршрут идти плоско, а разброс высот — половина вида уровня.
        /// </summary>
        public int reserveBelow;
        /// <summary>Насколько ШИРОКОЙ должна быть бронь (клеток в каждую сторону от комнаты).
        /// 🐞 Сперва бронь была шириной в саму комнату — три-восемь клеток, — а кольцу нужен марш
        /// вбок клеток на тридцать. Узкая бронь не спасала: столкновений оставалось 125 из 184.</summary>
        public int reserveWide;

        /// <summary>
        /// ⭐⭐ КОМНАТУ МОЖНО СВЯЗАТЬ С РОДИТЕЛЕМ ТОННЕЛЕМ, а не только общей стеной (предложение
        /// игрока): пара «родитель-ребёнок» остаётся связанной, а проход между ними ПРОРЕЗАЕТСЯ.
        ///
        /// 🐞 Зачем. Замер: комната не может пристроиться к родителю 1538 раз на 40 уровней — по 38
        /// на уровень. Причём родитель почти никогда не обстроен: в 74% случаев у него занято лишь
        /// ДВЕ стороны, в 25% — одна, и ни разу три или четыре. Мешает не родитель, а теснота вокруг
        /// него: соседние, с ним не связанные комнаты занимают ровно то место, куда надо встать.
        /// Три четверти отказов — у комнат, которым вообще ничего не предписано.
        ///
        /// ⚠️ Только для рёбер БЕЗ МЕХАНИЗМА: ворота, дверь и мост считают геометрию от общей стены.
        /// </summary>
        public bool allowTunnel;

        /// <summary>
        /// ⭐ КОМНАТА САМА ОТВЕЧАЕТ ЗА ПОДЪЁМ В СЕБЕ (уступы нарисует трафарет) — значит правило
        /// «под люком не выше дотяжки» к ней не относится. Нужна подвалу камеры: он девять рядов
        /// глубиной, и лестница внутри него нарисована картинкой.
        /// </summary>
        public bool ownClimb;

        /// <summary>
        /// ⭐⭐ НА РЕБРЕ К РОДИТЕЛЮ СТОИТ МЕХАНИЗМ — то есть это ЗАМОК, и всё, что за ним, игрок
        /// обязан открывать, а не обходить. Раскладка должна знать об этом ДО постановки: замок
        /// работает не сам по себе, а только если между двумя сторонами нет другой дороги.
        ///
        /// 🐞 Пока раскладка про замки не знала, она спокойно ставила комнату по ту сторону замка
        /// в дотяжке от комнаты по эту — и игрок просто перешагивал из одной в другую. Замер (сид
        /// 2008): комната 12 справа-снизу, комната 14 слева-сверху, между ними комната 13 с воротами,
        /// а полы 12 и 14 разошлись на dx=2, dy=3 — ровно в дотяжку. По графу комнат обхода нет,
        /// геометрически он есть. Ни лишние рёбра, ни возвраты, ни тоннели тут ни при чём.
        /// </summary>
        public bool lockedEdge;

        /// <summary>
        /// ⭐ КОМНАТА-ДОБОР: она добавлена ради простора, за ней нет ни цели, ни механизма. Если ей
        /// не нашлось места — её просто НЕ БУДЕТ, а уровень соберётся без неё. Ронять из-за неё всю
        /// раскладку нельзя: дешевле отдать уровень на комнату меньше, чем не отдать вовсе.
        /// ⚠️ Пропуск безопасен только потому, что этапы идут по возрастанию номера, а у ребёнка
        /// номер больше родительского: если добор не встал, его дети упрутся в «родителя нет» и
        /// пропустятся тем же правилом.
        /// </summary>
        public bool optional;
    }

    /// <summary>Куда обязан встать ребёнок относительно родителя (диктуется ролью на ребре).</summary>
    public enum LinkDir { Any, Up, Down, Horizontal }

    public class Result
