using UnityEngine;

/// <summary>
/// Цвет группы триггеров по её ключу — ОДНА формула на игру и на редактор.
/// Раньше жила только в LevelEditorWindow (подсветка групп в сцене); теперь ею же красится кнопка
/// в игре, чтобы игрок видел ту же связку «цвет ↔ группа», что и левел-дизайнер в редакторе.
///
/// Оттенок разносим ЗОЛОТЫМ СЕЧЕНИЕМ (0.618): при таком шаге соседние по алфавиту группы получают
/// максимально далёкие цвета, и 26 групп a-z не сливаются (равномерный шаг hue += 1/26 дал бы почти
/// одинаковые соседние оттенки). Одного оттенка мало: на 15-20 группах худшая пара сходится до 12°,
/// поэтому чётные группы — яркие/светлые, нечётные — насыщенные/тёмные, и худшие пары (A/N, G/T)
/// различаются ещё и по светлоте.
/// </summary>
public static class GroupPalette
{
    public static Color For(string groupId)
    {
        char c = string.IsNullOrEmpty(groupId) ? 'A' : char.ToUpperInvariant(groupId[0]);
        int idx = Mathf.Clamp(c - 'A', 0, 25);
        float hue = (idx * 0.6180339887f) % 1f;
        bool dark = (idx & 1) == 1;
        return Color.HSVToRGB(hue, dark ? 0.95f : 0.70f, dark ? 0.70f : 1f);
    }
}
