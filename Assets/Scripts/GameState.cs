/// <summary>
/// Все возможные состояния игры.
/// GameManager является единственным местом переключения состояний.
/// </summary>
public enum GameState
{
    Menu,       // Главное меню
    Playing,    // Игровой процесс
    Paused,     // Пауза
    Win,        // Уровень пройден
    Fail        // Игрок упал
}
